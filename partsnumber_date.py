def find_icon_on_screenshot(
    screenshot_bytes: bytes,
    template_paths: "str | List[str]",
    search_region: Optional[Tuple[int, int, int, int]] = None,
    threshold: float = ICON_MATCH_THRESHOLD,
    log_details: bool = True,
) -> Optional[Tuple[int, int]]:
    """
    Ищет иконку на скриншоте screenshot_bytes.

    template_paths — путь к ОДНОМУ файлу-эталону, либо СПИСОК путей к
    НЕСКОЛЬКИМ эталонам одной и той же иконки — пробуются все, берётся
    лучшее совпадение.

    log_details — писать ли подробную DEBUG-строку с max_val при каждом
    вызове. По умолчанию True. Ставится в False там, где функция вызывается
    в цикле МНОГО раз подряд (например, ожидание готовности рабочего стола,
    которое может опрашивать экран до 60 секунд каждые 0.4с) — иначе лог
    забивается десятками одинаковых строк, из-за чего кажется, что скрипт
    завис, хотя он просто ждёт и ещё укладывается в отведённый таймаут.

    Одна и та же иконка ⓘ на разных
    страницах PARTSNUMBER может отрисовываться РАЗНОГО РАЗМЕРА — у
    Chevrolet почти вдвое мельче, чем у Hyundai/Volvo (видимо, из-за более
    тесной шапки с доп. полями OEM/Enter a number). ПРОСТОЕ УМЕНЬШЕНИЕ
    эталона (resize) это не решает — мелкая иконка на экране отрисована
    с другим сглаживанием, а не просто "тот же рисунок мельче" (проверено:
    matchTemplate с уменьшенным эталоном давал только ~0.6, а эталон,
    вырезанный НАПРЯМУЮ из реального маленького скриншота — 1.0). Поэтому
    вместо масштабирования одного эталона держим НЕСКОЛЬКО файлов-эталонов
    разного реального размера и пробуем все по очереди.

    ЕСЛИ НА НОВОМ БРЕНДЕ ИКОНКА СНОВА НЕ НАЙДЕТСЯ: код сам сохранит
    диагностический скриншот (см. _dump_debug_screenshot) — вырежи из него
    иконку как новый файл-эталон (аналогично template_info_icon_small.png)
    и добавь путь к нему в список INFO_ICON_TEMPLATE_PATHS.

    search_region — необязательное сужение области поиска (x, y, w, h) в
    координатах ПОЛНОГО скриншота — используется, чтобы не спутать похожие
    иконки в разных местах экрана (например несколько "луп" рядом с разными
    полями).

    Возвращает координаты ЦЕНТРА найденной иконки в системе координат
    ПОЛНОГО скриншота (даже если искали в урезанном search_region), либо
    None, если лучшее совпадение среди всех эталонов ниже threshold.

    Сравнение приблизительное (TM_CCOEFF_NORMED), а не побайтовое — картинка
    из Blast-стрима сжата как видео и всегда немного "шумит", даже для
    одной и той же иконки на разных скриншотах.
    """
    if isinstance(template_paths, str):
        template_paths = [template_paths]

    screenshot = np.array(Image.open(io.BytesIO(screenshot_bytes)).convert("RGB"))

    offset_x, offset_y = 0, 0
    if search_region is not None:
        x, y, w, h = search_region
        screenshot = screenshot[y : y + h, x : x + w]
        offset_x, offset_y = x, y

    best_val = -1.0
    best_loc = None
    best_shape = None
    best_template_path = None
    best_scale = None

    for template_path in template_paths:
        template = cv2.imread(template_path)
        if template is None:
            raise PartsNumberSessionError(
                f"Не удалось прочитать файл шаблона иконки: {template_path}"
            )
        template = cv2.cvtColor(template, cv2.COLOR_BGR2RGB)

        # -----------------------------------------------------------------
        # ПЕРЕБОР МАСШТАБОВ — по измерению, а не по догадке.
        #
        # Без перебора логотип PARTSNUMBER на одном из скриншотов давал
        # совпадение 0.245 при пороге 0.3 — то есть "не найден", хотя был
        # прекрасно виден. С перебором масштабов на том же скриншоте: при
        # масштабе эталона 0.85 совпадение — 0.774, и точка находится ровно
        # там, где логотип и есть. Причина: удалённый рабочий стол Horizon
        # подгоняет своё содержимое под размер окна, поэтому один и тот же
        # элемент может отрисовываться то крупнее, то мельче, чем на
        # эталоне.
        #
        # ПОЧЕМУ ЭТО НЕ ПРОТИВОРЕЧИТ ДОКСТРИНГУ ВЫШЕ про иконку ⓘ, где
        # сказано, что масштабирование "не решает": там речь о МЕЛКОЙ
        # иконке (несколько десятков пикселей), у которой при уменьшении
        # сглаживание меняет сам рисунок — там действительно нужен отдельный
        # эталон. У КРУПНЫХ элементов вроде логотипа (320x40) масштабирование
        # работает прекрасно. Поэтому делаем и то, и другое: перебор
        # масштабов для каждого из имеющихся эталонов. Масштаб 1.0 тоже в
        # списке, то есть прямое сравнение остаётся частным случаем.
        #
        # Диапазон 0.6..1.4 покрывает разумные отклонения размера окна;
        # шаг 0.05 — компромисс между точностью и скоростью (перебор идёт
        # по маленькому региону поиска, поэтому это доли секунды).
        # -----------------------------------------------------------------
        for scale in [s / 100 for s in range(60, 145, 5)]:
            if scale == 1.0:
                scaled = template
            else:
                new_w = max(1, int(template.shape[1] * scale))
                new_h = max(1, int(template.shape[0] * scale))
                scaled = cv2.resize(template, (new_w, new_h), interpolation=cv2.INTER_AREA)

            th, tw = scaled.shape[:2]
            if th > screenshot.shape[0] or tw > screenshot.shape[1]:
                continue  # эталон крупнее области поиска — пропускаем

            result = cv2.matchTemplate(screenshot, scaled, cv2.TM_CCOEFF_NORMED)
            _, max_val, _, max_loc = cv2.minMaxLoc(result)

            if max_val > best_val:
                best_val = max_val
                best_loc = max_loc
                best_shape = (th, tw)
                best_template_path = template_path
                best_scale = scale

    if log_details:
        logger.debug(
            f"Template matching (эталоны: {[os.path.basename(p) for p in template_paths]}): "
            f"лучшее совпадение max_val={best_val:.3f} у "
            f"{os.path.basename(best_template_path) if best_template_path else '—'} "
            f"при масштабе {best_scale if best_scale is not None else '—'} "
            f"(порог {threshold})"
        )

    if best_val < threshold or best_loc is None:
        return None

    th, tw = best_shape
    center_x = offset_x + best_loc[0] + tw // 2
    center_y = offset_y + best_loc[1] + th // 2
    return (center_x, center_y)


def dark_pixels_in_band(screenshot_bytes: bytes, band) -> int:
    """
    Сколько тёмных пикселей в заданной полосе снимка.

    Вынесено на уровень модуля, чтобы проверку можно было прогонять на
    СОХРАНЁННЫХ скриншотах реальных сбоев, а не только на живом Horizon.
    Так проверено, что полоса ловит текст на смещённом окне, где
    фиксированная область давала 41 пиксель вместо 500.
    """
    x, y, x2, y2 = band
    gray = Image.open(io.BytesIO(screenshot_bytes)).convert("L")
    return sum(gray.crop((x, y, x2, y2)).histogram()[:VIN_FIELD_DARK_THRESHOLD])


