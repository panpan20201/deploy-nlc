# ---------------------------------------------------------------------------
# ЭКРАН ВЫБОРА ГРУППЫ ПРОИЗВОДИТЕЛЯ
#
# Пример — скриншот 20260827_034204 (VIN WDDZF0EB1JA373114, Mercedes
