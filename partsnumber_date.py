    # Вспомогательное: ожидание стабилизации области экрана
    # ------------------------------------------------------------------

    def _wait_for_area_stable(
        self,
        page: Page,
        clip: Tuple[int, int, int, int],
        timeout_sec: float,
    ) -> None:
        """
        С интервалом POLL_INTERVAL_SEC делает page.screenshot(clip=...),
        сравнивает с предыдущим снимком ПРИБЛИЗИТЕЛЬНО (среднее отличие
        яркости пикселей, а не побайтово — см. AREA_STABLE_DIFF_THRESHOLD).
        Считает область стабильной, когда отличие ниже порога
        STABLE_DURATION_SEC секунд подряд. Бросает PartsNumberSessionError
        при превышении timeout_sec.
        """
        x, y, width, height = clip
        clip_dict = {"x": x, "y": y, "width": width, "height": height}

        deadline = time.monotonic() + timeout_sec
        last_image: Optional[Image.Image] = None
        stable_since: Optional[float] = None

        while time.monotonic() < deadline:
            current_bytes = page.screenshot(clip=clip_dict)
            current_image = Image.open(io.BytesIO(current_bytes)).convert("L")

            if last_image is not None and self._images_similar(last_image, current_image):
                if stable_since is None:
                    stable_since = time.monotonic()
                elif time.monotonic() - stable_since >= STABLE_DURATION_SEC:
                    logger.debug("Область экрана стабилизировалась")
                    return
            else:
                stable_since = None

            last_image = current_image
            page.wait_for_timeout(int(POLL_INTERVAL_SEC * 1000))

        raise PartsNumberSessionError(
            f"Таймаут ({timeout_sec}с) ожидания стабилизации области экрана {clip}"
        )

    @staticmethod
    def _images_similar(
        image_a: Image.Image,
        image_b: Image.Image,
        threshold: float = AREA_STABLE_DIFF_THRESHOLD,
    ) -> bool:
        """
        Приблизительное сравнение двух скриншотов одной области: среднее
        отличие яркости пикселей (0-255) ниже threshold считается "тот же
        кадр" — устойчиво к шуму видео-сжатия Blast, в отличие от
        побайтового сравнения.
        """
        if image_a.size != image_b.size:
            return False
        diff = ImageChops.difference(image_a, image_b)
        mean_diff = ImageStat.Stat(diff).mean[0]
        return mean_diff <= threshold

