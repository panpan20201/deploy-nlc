    def _require_page(self) -> Page:
        if self._page is None:
            raise PartsNumberSessionError(
                "Сессия не инициализирована — используйте PartsNumberSession как "
                "контекстный менеджер (with PartsNumberSession() as session: ...)"
            )
        return self._page


