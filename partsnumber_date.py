    def get_vehicle_card(
        self, vin: str, _open_vin_retry: bool = False,
        _stale_retry: bool = False,
    ) -> Optional[str]:
        """
        По VIN-номеру получить ВСЮ информацию с карточки автомобиля
        (модальное окно в PARTSNUMBER), отформатированную для отчёта.

        Возвращает строку вида:

            Palisade 19 | LX2

            VIN: KMHR281ADNU407019
            Nation: KOREA
            Catalog Number: KDOMPS819
            Vehicle: Palisade 19
            Part Number / Date: 2021.11.16
            ...

        или None, если VIN не найден в базе PARTSNUMBER (правильный формат,
        но такой машины нет — окно "Vin not found"), либо формат VIN
        некорректен (красная плашка "Incorrect VIN"), либо карточку не
        удалось распознать.
        """
        logger.debug(f"get_vehicle_card(vin={vin!r})")
        # Почему вернулся None (кроме обычного «не найдено») — для pipeline.
        # Сейчас одна такая причина: "catalog_closed" (см. ниже).
        self.last_reason = None
        page = self._require_page()

        self._ensure_desktop_alive()

        # Убеждаемся, что мы в окне каталога, а не на портале. Проверка
        # идёт ПЕРЕД вводом VIN: на портале ввод не упал бы, а тихо вернул
        # список каталогов, и распознать это можно было бы только выждав
        # полный таймаут поиска (см. _ensure_catalog_window).
        self._ensure_catalog_window(page)

        self._enter_vin(page, vin)
        search_result = self._run_search(
            page, _open_vin_retry=_open_vin_retry, expected_vin=vin
        )

        if search_result == "open_vin_screen":
            # Кнопка "Open VIN" уже нажата внутри _run_search — осталось
            # дождаться рабочего стола и пройти весь путь заново: наш VIN
            # в поле ввода после перезагрузки сервера не сохранился.
            #
            # Повтор строго ОДИН раз (_open_vin_retry=True запрещает
            # следующий). Если и после нажатия кнопки мы снова упираемся в
            # тот же экран, значит, дело не в нём, и крутиться по кругу
            # бессмысленно.
            self._wait_for_desktop_ready()
            return self.get_vehicle_card(
                vin, _open_vin_retry=True, _stale_retry=_stale_retry,
            )

        if search_result == "catalog_closed":
            # Не сбой и не «машины нет»: каталог марки не входит в доступ.
            # Скриншот — чтобы по логу было видно, какая плашка стояла.
            self._dump_debug_screenshot(page, f"catalog_closed_{vin}")
            self.last_reason = "catalog_closed"
            return None

        if search_result == "invalid_format":
            # Здесь НЕ `return None`: None в pipeline означает ровно одно —
            # "искали и не нашли", и человек прочитал бы "машина не найдена
            # в каталоге" про машину, которая там есть. Между "в каталоге
            # такой машины нет" и "мы отправили в поле что-то не то"
            # разница принципиальная.
            #
            # ПОЧЕМУ ЭТО ТОЧНО НЕ ОТВЕТ ПРО МАШИНУ. VIN сюда приходит из
            # Carmoodo и всегда состоит из 17 корректных символов —
            # проверить нечего, формат правильный по построению. Значит,
            # красная плашка "Incorrect VIN" говорит не о VIN, а о том,
            # что до поля ввода дошло не то, что мы набирали: поле не
            # очистилось, фокус ушёл в другое окно, набор наложился на
            # прошлый текст. Про саму машину мы при этом не узнали
            # НИЧЕГО.
            #
            # Повтор здесь осмыслен и бесплатен: PARTSNUMBER не тратит
            # дневных квот (в отличие от Carmoodo и HeyDealer), а pipeline
            # повторит шаг с новой сессией — то есть с чистым полем.
            self._dump_debug_screenshot(page, "incorrect_vin_banner")
            raise PartsNumberSessionError(
                f"VIN {vin}: сайт показал плашку 'Incorrect VIN'. Формат "
                f"самого VIN верен (17 символов из Carmoodo), значит в поле "
                f"поиска ушло не то, что набирали — поле не очистилось или "
                f"фокус был в другом окне. Это техническая неудача, а НЕ "
                f"ответ 'машины нет в каталоге': про машину мы не узнали "
                f"ничего. Сохранён скриншот."
            )

        if search_result == "not_found":
            logger.info(
                f"VIN {vin} не найден в базе PARTSNUMBER "
                f"(обнаружено окно 'Information / Vin not found')"
            )
            # Скриншот ДО закрытия окна. «Не найдено» определяется по цвету
            # области и пропаже иконки ⓘ, и так отвечали и для машин, у
            # которых соседние VIN находились. Без снимка нельзя отличить
            # настоящий ответ каталога от ложного срабатывания.
            self._dump_debug_screenshot(page, f"vin_not_found_{vin}")
            self._dismiss_not_found_popup(page)
            return None

        # Код кузова (для заголовка карточки) берём из строки у логотипа —
        # в самой модалке его нет. Копируем ДО открытия модалки, т.к. после
        # открытия модалки эта область может быть перекрыта.
        #
        # ВАЖНО: это ЧИСТО КОСМЕТИЧЕСКИЙ шаг и он НЕ ДОЛЖЕН влиять на успех
        # всей проверки. Формат и положение этой строки разные у разных
        # марок (Hyundai — с "|", Audi — с запятой, у Mercedes логотип шире
        # и текст начинается правее, из-за чего выделение мышью по общим
        # координатам может вообще ничего не захватить). Поэтому любая
        # ошибка здесь просто означает "заголовок будет без
        # кода кузова", а все реальные данные машины всё равно берутся из
        # модалки ниже (_format_vehicle_card умеет строить заголовок и с
        # пустым chassis_code).
        chassis_code = ""
        try:
            logo_line_text = self._copy_logo_line_text(page)
            chassis_code = self._parse_chassis_code_from_logo_line(logo_line_text)
        except Exception as exc:
            logger.warning(
                f"Не удалось получить строку у логотипа (шаг косметический, "
                f"продолжаю без кода кузова в заголовке): {exc}"
            )

        # -----------------------------------------------------------------
        # ПРИЗНАК "страница реально перешла к результату поиска".
        #
        # ТЕКСТ у логотипа этим признаком служить НЕ может: он
        # КОСМЕТИЧЕСКИЙ (нужен только ради кода кузова в заголовке
        # карточки), а его формат и положение на экране РАЗНЫЕ у разных
        # марок:
        #   Hyundai:  "Palisade 19 | LX2 | 16.11.2021"  (есть "|")
        #   Audi:     "Audi Q5, 25.02.2023"             (запятая, кода нет)
        #   Mercedes: "Mercedes GLC 300 / 4MATIC coupe" (две строки, шире логотип)
        # Привязка К НЕМУ решения "загрузилась ли страница" сделала бы весь
        # пайплайн заложником вёрстки каждого нового бренда — с ложными
        # "не найдено" на машинах, данные которых на самом деле на экране.
        #
        # Признак, не зависящий от вёрстки: наличие иконки ⓘ, которая есть
        # на ЛЮБОЙ странице результата (независимо от марки и формата
        # подписи) и которой заведомо НЕТ на странице каталога марок. Её мы
        # и так обязаны найти следующим шагом, чтобы открыть модалку — то
        # есть проверка не добавляет отдельной работы.
        #
        # Ищем иконку через механизм template matching (он
        # умеет несколько эталонов разного размера и делает повторные
        # попытки — см. _click_icon_by_template). Если не нашли — это уже
        # техническая неудача, а не "машины нет": к этому моменту наличие
        # иконки на экране уже подтверждено в _run_search.
        # -----------------------------------------------------------------
        try:
            first_chunk = self._open_info_modal(page)
        except ModalDidNotOpenError:
            # Иконка ⓘ была найдена и нажата — значит, страница ДОШЛА до
            # результата поиска, и версия "машины нет в каталоге" здесь
            # неверна. Про машину мы не узнали ничего, это техническая
            # неудача: пропускаем ошибку наружу, чтобы pipeline повторил
            # шаг, а при повторной неудаче сказал человеку правду.
            # Подробности — в описании самого класса ошибки.
            raise
        except PartsNumberSessionError:
            # Прежде чем сдаваться, проверяем, не оказались ли мы на экране
            # "Open VIN" (см. подробности у OPEN_VIN_BUTTON_TEMPLATE_PATH) —
            # виртуальная машина может перезагрузить сервер ПРЯМО во время
            # поиска (реальный случай, подтверждён скриншотом).
            if not _open_vin_retry and self._recover_from_open_vin_screen(page):
                logger.info(
                    f"VIN {vin}: похоже, поиск пришёлся на перезагрузку "
                    f"сервера PARTSNUMBER (экран 'Open VIN') — повторяю "
                    f"запрос с начала."
                )
                # Повтор строго ОДИН раз (_open_vin_retry=True запрещает
                # следующий) — та же защита от зацикливания, что и при
                # повторном входе в Carmoodo (см. carmoodo_vin.py,
                # get_vin(..., _login_retry=True)).
                return self.get_vehicle_card(
                vin, _open_vin_retry=True, _stale_retry=_stale_retry,
            )

            logger.warning(
                f"VIN {vin}: иконка ⓘ на экране не найдена — похоже, страница "
                f"не перешла к результату поиска (возможно, откатилась на "
                f"каталог марок). Карточку получить не удалось."
            )
            self._dump_debug_screenshot(page, "no_info_icon_after_search")
            # Здесь НЕ `return None` ("машина не найдена в каталоге") — это
            # было бы неверно по построению. _run_search не объявляет
            # результат готовым, пока сам не убедится, что иконка ⓘ НА
            # ЭКРАНЕ (см. разбор случая с экраном загрузки там же).
            # Значит, если иконка пропала уже ПОСЛЕ этого, страница до
            # результата дошла, а потом что-то произошло — перерисовка,
            # откат, обрыв. Про саму машину мы по-прежнему не знаем ничего,
            # и утверждать, что её нет в каталоге, оснований нет.
            raise PartsNumberSessionError(
                f"VIN {vin}: иконка ⓘ пропала с экрана уже после того, как "
                f"результат поиска был подтверждён её наличием. Про машину "
                f"это не говорит ничего — техническая неудача, а не ответ "
                f"'нет в каталоге'. Сохранён скриншот."
            )

        try:
            raw_text = self._copy_modal_text(
                page, expected_vin=vin, first_chunk=first_chunk
            )
        except _StaleCardDetected as e:
            # См. подробное объяснение в _copy_modal_text — VIN оказался
            # виден уже в процессе копирования, не дожидаясь полного сбора
            # карточки. Экономим время на оставшихся проходах прокрутки и
            # на полном разборе полей, раз результат всё равно придётся
            # отбросить.
            #
            # Здесь НЕ `return None`. Пример: запросили KLAPD56LDTB195159, в
            # модалке KLAPC56LDSB000876 — машина из ПРЕДЫДУЩЕГО запроса.
            # Проверка правильно не отдаёт чужих данных, но `return None` в
            # pipeline означает "искали и не нашли", и человек прочитал бы
            # "машины нет в каталоге" про машину, которая там есть, — мы её
            # просто не успели загрузить (как и в ветке invalid_format).
            #
            # ПОЧЕМУ СНАЧАЛА ПОВТОР, А НЕ СРАЗУ ОШИБКА. Устаревшая
            # карточка означает ровно одно: страница ЕЩЁ НЕ ОБНОВИЛАСЬ.
            # Это состояние проходит само — надо просто поискать заново, и
            # дешевле всего сделать это здесь же, в живой сессии, а не
            # отдавать наверх, где повтор стоит пересоздания сессии (около
            # тридцати секунд).
            self._close_modal(page)
            self._dump_debug_screenshot(page, "vin_mismatch_stale_data_early")

            if not _stale_retry:
                logger.warning(
                    f"ПОДМЕНА ДАННЫХ (обнаружено рано): запросили VIN {vin!r}, "
                    f"а в модалке VIN {e.card_vin!r} — машина из предыдущего "
                    f"запроса. Значит, страница ещё не обновилась. Повторяю "
                    f"поиск в этой же сессии."
                )
                page.wait_for_timeout(STALE_CARD_RETRY_PAUSE_MS)
                return self.get_vehicle_card(
                    vin, _open_vin_retry=_open_vin_retry, _stale_retry=True,
                )

            raise PartsNumberSessionError(
                f"VIN {vin}: и после повторного поиска в модалке остаётся "
                f"чужая машина ({e.card_vin}). Страница не обновляется — это "
                f"техническая неудача, а НЕ ответ 'машины нет в каталоге': "
                f"про запрошенную машину мы не узнали ничего. Сохранён "
                f"скриншот."
            )

        # СТРАХОВОЧНАЯ ПРОВЕРКА "это всё ещё модалка, а не то, что под ней".
        #
        # Основная проверка стоит РАНЬШЕ — в _open_info_modal, где
        # модалка открывается циклом "нажать -> убедиться -> при неудаче
        # нажать ещё раз". Сюда мы попадаем уже с подтверждённым первым
        # куском текста.
        #
        # Но проходов копирования несколько, между ними идёт прокрутка
        # колесом, и модалка может закрыться посреди сбора (см.
        # предупреждение про резкую прокрутку в _copy_modal_text). Поэтому итоговый текст проверяем
        # ещё раз: стоит это ноль действий, а ловит целый класс сбоев.
        # Скриншот снимается ДО _close_modal — по нему видно, что было на
        # экране в момент копирования.
        if not self._modal_text_looks_valid(raw_text):
            self._dump_debug_screenshot(page, "modal_text_without_search_anchor")
            self._close_modal(page)
            raise PartsNumberSessionError(
                f"VIN {vin}: скопирован не текст карточки. В нём нет "
                f"подписи 'Search...', которая есть в модалке у всех "
                f"марок — значит, модалка не открылась (или закрылась), и "
                f"выделение захватило страницу каталога под ней. Разбирать "
                f"такой текст нельзя: получится правдоподобная ерунда с "
                f"чужими данными. Сохранён скриншот. Скопированный текст: "
                f"{raw_text[:500]!r}"
            )

        self._close_modal(page)

        fields = self._parse_vehicle_card(raw_text)
        if not fields:
            # Здесь НЕ `return None`: None в pipeline означает ровно одно —
            # "искали и не нашли", и при пустом скопированном тексте человек
            # прочитал бы "машина не найдена в каталоге" про машину, которая
            # там есть. Между "в каталоге такой машины нет" и "мы не смогли ничего
            # скопировать" разница принципиальная: первое окончательно,
            # второе лечится повтором. Раз текст пуст — мы НЕ ЗНАЕМ, есть
            # машина в каталоге или нет, и говорить, что её нет, нельзя.
            raise PartsNumberSessionError(
                f"VIN {vin}: карточка не разобралась — в скопированном "
                f"тексте нет ни одной пары метка/значение. Это техническая "
                f"неудача копирования, а НЕ ответ 'машины нет в каталоге': "
                f"о самой машине мы так ничего и не узнали. Сырой текст: "
                f"{raw_text!r}"
            )

        # СТРАХОВОЧНАЯ ПРОВЕРКА (запасной вариант, на случай если VIN не
        # был виден рано — например, у брендов, где поле VIN идёт не в
        # первых строках модалки, или в первом проходе попал в "пустое
        # место" при прокрутке). Основная, более быстрая проверка — выше,
        # внутри _copy_modal_text/_StaleCardDetected. Раз в карточке почти
        # всегда есть поле VIN (кроме брендов без такого поля вообще, см.
        # KNOWN_FIELD_LABELS) — сверяем его с тем, что реально запрашивали,
        # и если они не совпадают — считаем это ошибкой, а не результатом.
        card_vin = fields.get("VIN") or fields.get("Vin")
        if card_vin and self._normalize_vin(card_vin) != self._normalize_vin(vin):
            # Здесь тоже НЕ `return None` ("искали и не нашли"). Обоснование
            # целиком совпадает с ранней проверкой выше (ветка
            # _StaleCardDetected): устаревшая
            # карточка значит "страница не обновилась", а не "машины нет".
            self._dump_debug_screenshot(page, "vin_mismatch_stale_data")

            if not _stale_retry:
                logger.warning(
                    f"ПОДМЕНА ДАННЫХ: запросили VIN {vin!r}, а карточка "
                    f"оказалась для VIN {card_vin!r} — машина из предыдущего "
                    f"запроса. Страница ещё не обновилась, повторяю поиск в "
                    f"этой же сессии."
                )
                page.wait_for_timeout(STALE_CARD_RETRY_PAUSE_MS)
                return self.get_vehicle_card(
                    vin, _open_vin_retry=_open_vin_retry, _stale_retry=True,
                )

            raise PartsNumberSessionError(
                f"VIN {vin}: и после повторного поиска карточка остаётся от "
                f"чужой машины ({card_vin}). Страница не обновляется — это "
                f"техническая неудача, а НЕ ответ 'машины нет в каталоге'. "
                f"Сохранён скриншот."
            )

        card = self._format_vehicle_card(fields, chassis_code)
        logger.debug(f"VIN {vin} -> карточка:\n{card}")
        return card

    @staticmethod
    def _normalize_vin(value: str) -> str:
        """Приводит VIN к единому виду для сравнения — без пробелов, без
        учёта регистра (сайт иногда показывает VIN в нижнем регистре)."""
        return "".join(value.split()).upper()

