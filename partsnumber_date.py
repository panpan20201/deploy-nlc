    def _dump_debug_screenshot(self, page: Page, label: str) -> None:
        """
        Сохраняет полный скриншот текущего экрана на диск — диагностика
        при сбоях (таймаут поиска, не найдена иконка и т.п.). Это ТОЧНО
        тот же самый page.screenshot(), что использует весь остальной код,
        поэтому по такому файлу координаты калибруются напрямую, без
        искажений масштаба, которые бывают при ручном снятии скриншота с
        экрана.

        Не бросает исключение при сбое сохранения — это вспомогательная
        диагностика, а не критичная часть сценария, ошибка здесь не должна
        маскировать настоящую причину сбоя.
        """
        try:
            os.makedirs(DEBUG_SCREENSHOTS_DIR, exist_ok=True)
            filename = f"{time.strftime('%Y%m%d_%H%M%S')}_{label}.png"
            path = os.path.join(DEBUG_SCREENSHOTS_DIR, filename)
            page.screenshot(path=path)
            logger.warning(
                f"Сохранён диагностический скриншот: {path} — пришли этот "
                f"файл, если нужно уточнить координаты"
            )
        except Exception as e:  # noqa: BLE001 — диагностика, не критично
            logger.debug(f"Не удалось сохранить диагностический скриншот: {e}")

    def _region_is_error_banner(self, page: Page) -> bool:
        """
        Проверяет, показывает ли область ERROR_BANNER_REGION красный баннер
        "Incorrect VIN" — по среднему цвету области, а не по тексту (текст
        внутри Horizon-картинки недоступен напрямую без выделения+копирования,
        а цвет — простой и надёжный сигнал, устойчивый к шуму видеосжатия).
        """
        x, y, width, height = ERROR_BANNER_REGION
        screenshot_bytes = page.screenshot(
            clip={"x": x, "y": y, "width": width, "height": height}
        )
        image = Image.open(io.BytesIO(screenshot_bytes)).convert("RGB")
        avg_r, avg_g, avg_b = image.resize((1, 1)).getpixel((0, 0))

        is_red = (
            avg_r >= ERROR_BANNER_RED_MIN_R
            and avg_g <= ERROR_BANNER_RED_MAX_GB
            and avg_b <= ERROR_BANNER_RED_MAX_GB
        )
        if is_red:
            logger.debug(
                f"Цвет области баннера ошибки: RGB({avg_r},{avg_g},{avg_b}) "
                f"— похоже на 'Incorrect VIN'"
            )
        return is_red

    def _click_icon_by_template(
        self,
        page: Page,
        template_paths: "str | List[str]",
        search_region: Tuple[int, int, int, int],
        icon_label: str,
    ) -> None:
        """
        Находит иконку (лупа / ⓘ) на текущем скриншоте экрана методом
        template matching и кликает в её центр.

        template_paths — один путь к эталону, либо список путей (когда одна
        и та же иконка может отрисовываться разными по размеру — см.
        find_icon_on_screenshot).

        Делает до ICON_SEARCH_RETRIES попыток с паузой ICON_SEARCH_RETRY_DELAY_SEC
        между ними на случай, если иконка ещё не прорисовалась (рефлоу после
        ввода VIN / получения результата). Если после всех попыток иконка не
        найдена — бросает PartsNumberSessionError с понятным сообщением.
        """
        for attempt in range(1, ICON_SEARCH_RETRIES + 1):
            screenshot_bytes = page.screenshot()
            coords = find_icon_on_screenshot(
                screenshot_bytes, template_paths, search_region=search_region
            )
            if coords is not None:
                logger.debug(
                    f"Иконка '{icon_label}' найдена в {coords} (попытка {attempt})"
                )
                # Неспешный клик, а не page.mouse.click(): мгновенный клик
                # Horizon теряет — подробный разбор в _click_deliberately.
                self._click_deliberately(page, *coords)
                return

            logger.debug(
                f"Иконка '{icon_label}' не найдена (попытка {attempt}/"
                f"{ICON_SEARCH_RETRIES}), жду {ICON_SEARCH_RETRY_DELAY_SEC}с и пробую снова"
            )
            page.wait_for_timeout(int(ICON_SEARCH_RETRY_DELAY_SEC * 1000))

        self._dump_debug_screenshot(page, f"icon_not_found_{icon_label.replace(' ', '_')}")
        raise PartsNumberSessionError(
            f"Не удалось найти иконку '{icon_label}' на экране (шаблон "
            f"{template_paths}, регион поиска {search_region}, порог "
            f"{ICON_MATCH_THRESHOLD}) после {ICON_SEARCH_RETRIES} попыток"
        )

    def _click_deliberately(self, page: Page, x: int, y: int) -> None:
        """
        Клик, который удалённый рабочий стол ГАРАНТИРОВАННО замечает.

        Template matching на реальных скриншотах находит иконку ⓘ
        ПРАВИЛЬНО и с высокой уверенностью —

            Kia:         0.958 в (989, 49)   — сама иконка в (987, 48)
            SsangYong:   0.971 в (1070, 49)

        То есть промаха по координатам нет, и всё-таки после мгновенного
        клика модалка открывается не всегда. Дело не в том, КУДА мы жмём,
        а в том, КАК.

        page.mouse.click() — это перемещение, нажатие и отпускание одним
        мгновением, без единой паузы. Для обычной веб-страницы этого
        достаточно. Но Horizon — это ВИДЕОПОТОК удалённого рабочего стола
        (Blast) с сетевой задержкой: события мыши едут на другую машину, и
        мгновенное "телепортировался и щёлкнул" там просто теряется.

        Та же природа у двух других мест этого файла:
          * _select_drag_and_copy — протяжка мышью с параметром steps не
            работает вовсе (буфер пуст), поэтому движение разбито на шаги
            с настоящими паузами, "как живая рука";
          * _enter_vin — клик, Ctrl+A и Delete подряд без пауз приводят к
            тому, что старый VIN не стирается.
        Лечение везде одно: замедлить и разделить действия.

        Отсюда и характер сбоя мгновенного клика — "часто, но не всегда":
        успеет удалённая сторона его обработать или нет, зависит от сети и
        загрузки, то есть от везения. Никакой связи с маркой или VIN, хотя
        со стороны выглядит именно так.

        Порядок здесь ровно человеческий: подвести курсор, дать ему
        доехать, нажать, подержать, отпустить.
        """
        page.mouse.move(x, y)
        page.wait_for_timeout(DELIBERATE_CLICK_MOVE_PAUSE_MS)
        page.mouse.down()
        page.wait_for_timeout(DELIBERATE_CLICK_HOLD_MS)
        page.mouse.up()
        page.wait_for_timeout(DELIBERATE_CLICK_MOVE_PAUSE_MS)

    def _open_info_modal(self, page: Page) -> str:
        """
        Открывает модалку с карточкой и возвращает ПРОВЕРЕННЫЙ первый кусок
        её текста.

        Схема "клик -> фиксированная пауза -> выделить и скопировать" без
        проверки, открылась ли модалка, работать стабильно не может: если
        модалка не успела появиться, или клик пришёлся мимо, или она
        открылась и закрылась — выделение честно захватывает страницу
        каталога ПОД ней, и этот текст уходит в разбор. У разных брендов
        разное время отрисовки, и фиксированная пауза угадывает не всегда
        — отсюда кажущаяся зависимость от марки, VIN и везения.

        Поэтому: клик -> СПРОСИТЬ У ЭКРАНА, открылась ли -> если нет,
        нажать ещё раз. Признак открытия — подпись "Search..." в
        скопированном тексте. Он выбран не случайно: это элемент самой
        модалки, он есть у всех марок (подтверждено на Hyundai, Volvo,
        Kia, SsangYong) и его заведомо нет на странице каталога. То есть
        признак не зависит ни от марки, ни от VIN, ни от вёрстки.

        ПОЧЕМУ ЭТО НЕ ЗАМЕДЛЯЕТ ОБЫЧНУЮ РАБОТУ. Проверка — это и есть
        первое копирование, которое всё равно нужно сделать. Если
        модалка открылась (обычный случай), первый же кусок содержит
        якорь, мы его возвращаем и идём дальше: ни одного лишнего
        действия. Платим только за неудачу — там, где иначе молча
        получили бы мусор.

        ПОЧЕМУ ПОВТОР ЗДЕСЬ, А НЕ НА УРОВНЕ pipeline. Повтор шага целиком
        пересоздаёт Horizon-сессию — это около 45 секунд (замерено по
        логу). Повтор одного клика по иконке стоит секунды. Разница в
        сорок раз, а лечит один и тот же сбой.

        :return: первый кусок текста модалки, уже проверенный на якорь
        :raises PartsNumberSessionError: если модалка так и не открылась
        """
        last_chunk = ""
        for attempt in range(1, MODAL_OPEN_ATTEMPTS + 1):
            logger.debug(
                f"Открываю модальное окно с информацией (иконка ⓘ), "
                f"попытка {attempt}/{MODAL_OPEN_ATTEMPTS}"
            )
            # Не _click_icon_by_template: тот при ненайденной иконке
            # БРОСАЕТ исключение и обрывает весь шаг, а иконка бывает не
            # найдена (max_val=0.000 на трёх кадрах подряд) при карточке,
            # которая на экране есть.
            #
            # Поэтому две цели: точная (эталон) и широкая (полоса шапки,
            # см. INFO_BAND_CLICK_COORD). Порядок именно такой — точный
            # путь остаётся первым.
            coords = find_icon_on_screenshot(
                page.screenshot(),
                INFO_ICON_TEMPLATE_PATHS,
                search_region=INFO_ICON_REGION,
            )
            if coords is not None:
                logger.debug(f"Иконка ⓘ найдена в {coords} — жму по ней.")
                self._click_deliberately(page, *coords)
            else:
                logger.debug(
                    f"Иконку ⓘ по эталону не нашёл — жму по полосе шапки "
                    f"{INFO_BAND_CLICK_COORD} (карточка открывается по всей "
                    f"полосе от логотипа до иконки, а не только по иконке)."
                )
                self._click_deliberately(page, *INFO_BAND_CLICK_COORD)

            for probe in range(1, MODAL_OPEN_PROBE_TRIES + 1):
                page.wait_for_timeout(int(MODAL_OPEN_WAIT_SEC * 1000))
                chunk = self._select_drag_and_copy(
                    page, MODAL_SELECT_START, MODAL_SELECT_END
                )
                last_chunk = chunk
                if self._modal_text_looks_valid(chunk):
                    logger.debug(
                        f"Модалка открыта и подтверждена якорем 'Search...' "
                        f"(попытка {attempt}, проба {probe})"
                    )
                    return chunk
                logger.debug(
                    f"Якоря 'Search...' в тексте нет — модалка ещё не открылась "
                    f"(попытка {attempt}, проба {probe}/{MODAL_OPEN_PROBE_TRIES}), "
                    f"скопировано {len(chunk)} симв."
                )

            if attempt < MODAL_OPEN_ATTEMPTS:
                logger.warning(
                    "Модалка не открылась после клика по ⓘ — нажимаю Escape "
                    "(на случай наполовину открытого состояния) и пробую ещё раз."
                )
                page.keyboard.press("Escape")
                page.wait_for_timeout(500)

        self._dump_debug_screenshot(page, "modal_did_not_open")
        raise ModalDidNotOpenError(
            f"Модалка с карточкой не открылась после {MODAL_OPEN_ATTEMPTS} "
            f"нажатий на иконку ⓘ: в скопированном тексте так и не появилась "
            f"подпись 'Search...', которая есть в модалке у всех марок. "
            f"Значит, копировалась страница каталога под модалкой — разбирать "
            f"такой текст нельзя, получится правдоподобная ерунда с чужими "
            f"данными. Сохранён скриншот. Последний скопированный текст: "
            f"{last_chunk[:500]!r}"
        )

    def _select_drag_and_copy(
        self,
        page: Page,
        start: Tuple[int, int],
        end: Tuple[int, int],
        select: Optional[Callable[[], None]] = None,
        what: str = "",
    ) -> str:
        """
        Единая надёжная механика "выделить -> Ctrl+C -> прочитать буфер
        обмена", используется для модалки, строки у логотипа и поля VIN.

        select — необязательный СВОЙ способ выделения. Если не задан,
        выделение делается протяжкой мыши из start в end. Задан — вместо
        протяжки вызывается он, а start/end используются только для
        диагностической записи в лог.

        Зачем это нужно: в текстовом поле протяжка мышью — плохой
        способ выделить содержимое (зависит от того, где именно текст
        нарисован, а именно этого мы и не знаем — см. разбор в
        _read_vin_field_text). Там правильное выделение — Ctrl+A, и вся
        остальная механика этой функции нужна ровно та же: метка, пауза
        на доставку, ожидание пересылки обратно.

        ПОДТВЕРЖДЕНО НА РЕАЛЬНОМ ПРОГОНЕ: ручное выделение мышью + Ctrl+C
        работает и копирует текст полностью. Автоматическая
        версия с Playwright'овским встроенным steps=N — нет (буфер пуст).
        Наиболее вероятная причина: Playwright с параметром steps рассылает
        все промежуточные mousemove ПРАКТИЧЕСКИ МГНОВЕННО, без пауз между
        ними, а сессия идёт на удалённый сервер (Horizon/Blast) с сетевой
        задержкой — удалённое приложение может не успевать зарегистрировать
        протяжку при "телепортирующемся" движении, в отличие от живой руки,
        которая тянет мышь естественно медленно.

        Поэтому здесь ВРУЧНУЮ разбиваем протяжку на шаги с РЕАЛЬНОЙ паузой
        между каждым mouse.move — имитация человеческой скорости движения,
        а не мгновенная телепортация.
        """
        DRAG_STEPS = 20
        DRAG_STEP_PAUSE_MS = 25  # пауза между промежуточными точками протяжки

        # ---------------------------------------------------------------
        # ПОЧЕМУ ЗДЕСЬ МЕТКА-ПУСТЫШКА, А НЕ ПРОСТО ОЧИСТКА БУФЕРА
        #
        # Разобрано по скриншоту 20260822_182411 (VIN KMTGC41DBNU118311):
        #
        #     МОДАЛКА НА ЭКРАНЕ ОТКРЫТА. Её поля выделены синим — то есть
        #     протяжка отработала правильно, по правильным координатам, и
        #     выделила именно карточку.
        #
        # А в буфере при этом оказывается текст ЛЕВОЙ ПАНЕЛИ КАТАЛОГА
        # ("MI / Transmission / CH / Chassis / ..."), а на следующей
        # попытке — ПУСТО.
        #
        # Значит, ломается не выделение и не открытие модалки, а
        # ПОЛУЧЕНИЕ СКОПИРОВАННОГО. Механика такая: Ctrl+C уходит на
        # УДАЛЁННУЮ машину и кладёт текст в ЕЁ буфер обмена. В браузер он
        # попадает только после того, как Horizon перешлёт его обратно —
        # а это отдельная передача по сети, со своей задержкой. Если после
        # фиксированной паузы читать браузерный буфер, что бы в нём ни
        # лежало, то при неуспевшей синхронизации читается ПРОШЛОЕ
        # содержимое, то есть результат предыдущей протяжки. Отсюда и
        # "каталог вместо карточки": это текст, скопированный шагом
        # раньше, когда модалки ещё не было.
        #
        # То есть копируется не то не потому, что выделено не то, — а
        # потому, что прочитано не тогда.
        #
        # Поэтому не гадаем по таймеру, а дожидаемся положительного
        # признака. Перед копированием
        # кладём в буфер УНИКАЛЬНУЮ метку и ждём, пока там появится
        # что-нибудь другое. Появилось — синхронизация дошла, читаем
        # настоящий результат.
        #
        # Метка, а не пустая строка: пустой буфер неотличим от "скопировали
        # пустоту", и ждать было бы нечего.
        # ---------------------------------------------------------------
        # ПРЕДОХРАНИТЕЛЬ ОТ ЗАВИСАНИЯ.
        #
        # Одно копирование ждёт до CLIPBOARD_SYNC_TIMEOUT_SEC. Копирований
        # на одну карточку много: до MODAL_SCROLL_PASSES проходов, и всё
        # это до MODAL_OPEN_ATTEMPTS раз. Если буфер сломан по-настоящему,
        # каждое ожидание отрабатывает впустую, и снаружи это выглядит не
        # как ошибка, а как зависание.
        #
        # Поэтому: если буфер не приехал CLIPBOARD_MAX_FAILURES_IN_ROW раз
        # подряд, дальше не ждём вовсе. Дело не в конкретном фрагменте —
        # сломан канал, и следующие попытки просто потратят время.
        # Счётчик обнуляется при первой же удачной синхронизации, так что
        # редкие одиночные промахи ничего не блокируют.
        if self._clipboard_failures_in_row >= CLIPBOARD_MAX_FAILURES_IN_ROW:
            logger.warning(
                f"[CLIPBOARD_DEAD] Пропускаю ожидание: буфер не приезжал "
                f"{self._clipboard_failures_in_row} раз подряд. Канал явно "
                f"не работает, ждать ещё {CLIPBOARD_SYNC_TIMEOUT_SEC:.0f}с "
                f"бессмысленно — отвечаю сразу, чтобы шаг завершился "
                f"ошибкой, а не превратился в зависание."
            )
            clipboard_health.mark_dead()
            return ""

        sentinel = f"__NLC_WAITING_{time.time_ns()}__"
        page.evaluate("text => navigator.clipboard.writeText(text)", sentinel)

        # ⚠️ МЕТКУ НАДО НЕ ТОЛЬКО ПОЛОЖИТЬ, НО И УБЕДИТЬСЯ, ЧТО ОНА ЛЕГЛА.
        #
        # writeText асинхронный, а цикл ниже считает "буфер обновился"
        # ЛЮБОЕ значение, отличное от метки. Если метка не успела лечь к
        # первому опросу, в буфере ещё лежит текст ПРЕДЫДУЩЕЙ операции —
        # он отличается от метки, и функция немедленно вернула бы его как
        # свежий результат.
        #
        # То есть механизм, поставленный ПРОТИВ устаревшего буфера, при
        # неудачном стечении сам же устаревший буфер и отдал бы. Это ровно
        # тот класс отказа, который иначе ловится дорого и поздно —
        # проверкой "ПОДМЕНА ДАННЫХ" и защитой от текста меню.
        #
        # Проверка стоит одного чтения буфера.
        sentinel_landed = False
        for _ in range(SENTINEL_WRITE_CHECK_ATTEMPTS):
            try:
                if page.evaluate("navigator.clipboard.readText()") == sentinel:
                    sentinel_landed = True
                    break
            except Exception as exc:
                logger.debug(f"[БУФЕР] чтение при проверке метки не удалось: {exc}")
            page.wait_for_timeout(CLIPBOARD_POLL_MS)

        if not sentinel_landed:
            # Не смогли поставить метку — значит, отличить свежий результат
            # от прошлого нечем. Копировать в таких условиях нельзя:
            # вернём то, что лежит, и не узнаем, чьё оно.
            logger.warning(
                "[CLIPBOARD_NOSENTINEL] Метку не удалось положить в буфер за "
                f"{SENTINEL_WRITE_CHECK_ATTEMPTS} попыток. Без неё свежий "
                "результат неотличим от прошлого — считаю, что скопировать "
                "не удалось."
            )
            return ""

        # ⚠️ ПАУЗА ПЕРЕД КОПИРОВАНИЕМ — НЕ «НА ВСЯКИЙ СЛУЧАЙ».
        #
        # Вручную, в обычном браузере, Ctrl+C в Horizon и вставка в
        # блокнот РАБОТАЮТ (проверено владельцем). То есть канал
        # синхронизации исправен, а у бота без этой паузы тот же канал
        # молчал — 12 отказов подряд по 20 секунд каждый.
        #
        # Единственное, чем бот отличается от человека в этом месте: он
        # КЛАДЁТ МЕТКУ В БУФЕР БРАУЗЕРА. Человек этого не делает. А
        # Horizon синхронизирует буфер В ОБЕ СТОРОНЫ:
        #
        #   1. пишем метку в буфер БРАУЗЕРА
        #        -> Horizon видит изменение и НАЧИНАЕТ слать метку
        #           на удалённую машину — асинхронно, с задержкой
        #   2. Ctrl+C на машине      -> буфер машины = текст карточки
        #   3. прилетает отложенная посылка из п.1
        #                            -> буфер машины = МЕТКА (затёрла текст)
        #   4. буфер машины теперь совпадает с тем, что Horizon считает в
        #      браузере -> изменений нет -> пересылать нечего -> ТАЙМАУТ
        #
        # То есть механизм, поставленный, чтобы отличить свежее от
        # старого, при неудачном раскладе сам стирает свежее. Это
        # объясняет, почему такое молчание не зависит от таймаута (5с и
        # 20с одинаково), почему не помогает «разогрев» (он тоже пишет в
        # буфер), и почему один и тот же код то работает, то нет — меняется
        # лишь задержка сети, то есть кто успеет первым.
        #
        # ЛЕЧЕНИЕ: дождаться, пока метка ДОЕДЕТ до машины, и только потом
        # жать Ctrl+C. Тогда наше копирование — последнее изменение, и
        # затирать его нечему.
        #
        # Наблюдать доставку напрямую мы не можем (буфер удалённой машины
        # нам не виден), поэтому здесь именно пауза. Это осознанное
        # исключение из правила «не гадать по таймеру»: измерить нечего.
        # Зато цена ошибки мала — полторы секунды против двадцати секунд
        # гарантированного отказа.
        page.wait_for_timeout(SENTINEL_SETTLE_MS)

        if select is not None:
            select()
            page.wait_for_timeout(150)
        else:
            # Клик в стартовую точку — фокус на нужной области перед протяжкой.
            page.mouse.click(*start)
            page.wait_for_timeout(150)

            start_x, start_y = start
            end_x, end_y = end

            page.mouse.move(start_x, start_y)
            page.mouse.down()
            page.wait_for_timeout(80)

            for step in range(1, DRAG_STEPS + 1):
                t = step / DRAG_STEPS
                x = round(start_x + (end_x - start_x) * t)
                y = round(start_y + (end_y - start_y) * t)
                page.mouse.move(x, y)
                page.wait_for_timeout(DRAG_STEP_PAUSE_MS)

            page.mouse.up()
            page.wait_for_timeout(150)

        page.keyboard.press("Control+C")

        # Ждём, пока Horizon перешлёт буфер удалённой машины обратно в
        # браузер. Признак — метка сменилась на что-то другое.
        started_at = time.monotonic()
        deadline = started_at + CLIPBOARD_SYNC_TIMEOUT_SEC
        polls = 0
        focus_lost_at: Optional[int] = None

        while time.monotonic() < deadline:
            page.wait_for_timeout(CLIPBOARD_POLL_MS)
            polls += 1

            # ДИАГНОСТИКА. Буфер иногда не приезжает (около 8% операций по
            # логу). Гадать нельзя, поэтому собираем ФАКТЫ на каждом
            # опросе — они ничего не меняют в поведении, но отвечают на
            # три вопроса:
            #
            #   1. Не теряет ли страница фокус? Без фокуса чтение буфера
            #      в браузере запрещено, и повести себя оно может тихо.
            #   2. Не мал ли просто таймаут? Если удачные копирования
            #      приходят под самый потолок, дело не в поломке, а в том,
            #      что мы не дожидаемся.
            #   3. Не совпадает ли отказ с ПОВТОРНЫМ копированием того же
            #      текста? Horizon пересылает буфер, когда тот ИЗМЕНИЛСЯ.
            #      Если выделение то же, что в прошлый проход, на удалённой
            #      машине буфер не меняется — и пересылать нечего. А
            #      _copy_modal_text копирует несколько проходов подряд, и
            #      совпадение соседних проходов у него штатное (это его же
            #      условие остановки).
            try:
                has_focus = page.evaluate("document.hasFocus()")
            except Exception:
                has_focus = None
            if has_focus is False and focus_lost_at is None:
                focus_lost_at = polls

            try:
                current = page.evaluate("navigator.clipboard.readText()")
            except Exception as exc:
                logger.debug(
                    f"[БУФЕР] опрос {polls}: чтение не удалось ({exc}), "
                    f"фокус={has_focus}"
                )
                continue

            if current != sentinel:
                logger.debug(
                    f"[CLIPBOARD_OK] Синхронизация дошла за "
                    f"{time.monotonic() - started_at:.2f}с (опрос {polls}, "
                    f"фокус={has_focus}, символов {len(current)})."
                )
                self._clipboard_failures_in_row = 0
                clipboard_health.mark_alive()
                return current

            logger.debug(
                f"[БУФЕР] опрос {polls}: всё ещё метка, "
                f"{time.monotonic() - started_at:.2f}с, фокус={has_focus}"
            )

        # Метка на месте — из удалённой машины так ничего и не приехало.
        # Считаем отказ (см. предохранитель CLIPBOARD_MAX_FAILURES_IN_ROW
        # в начале метода) и пишем в лог диагностику, собранную выше.
        self._clipboard_failures_in_row += 1
        logger.warning(
            f"[CLIPBOARD_FAIL] Буфер обмена не обновился за "
            f"{CLIPBOARD_SYNC_TIMEOUT_SEC:.0f}с после Ctrl+C — Horizon не переслал скопированное из удалённой "
            f"машины. Считаю, что скопировать не удалось. "
            f"[отказов подряд: {self._clipboard_failures_in_row}] "
            f"[диагностика: опросов {polls}, "
            f"фокус терялся: {'нет' if focus_lost_at is None else f'да, с опроса {focus_lost_at}'}, "
            f"выделение {what or f'{start}->{end}'}]"
        )

        # ⚠️ ПОЧЕМУ ЗДЕСЬ НЕТ «РАЗОГРЕВА БУФЕРА» (повторного копирования
        # другого фрагмента, чтобы буфер удалённой машины гарантированно
        # изменился и Horizon его переслал).
        #
        # Замер времени удачных синхронизаций (см.
        # CLIPBOARD_SYNC_TIMEOUT_SEC) показал, что короткий потолок стоял
        # ВНУТРИ рабочего разброса, и отказы объясняются просто тем, что
        # синхронизации не дожидались. Кроме того, разогрев удваивает время
        # каждого отказа, а вместе с четырьмя проходами прокрутки и тремя
        # попытками открыть модалку это снаружи выглядит зависанием.
        #
        # Если отказы при длинном таймауте всё же станут частыми — разогрев
        # можно рассмотреть снова, но проверять его надо по ДЛИННОМУ
        # таймауту: на коротком его молчание ничего не доказывает.
        return ""

    def _copy_modal_text(
        self,
        page: Page,
        expected_vin: Optional[str] = None,
        first_chunk: Optional[str] = None,
    ) -> str:
        """
        Копирует ВЕСЬ текст модального окна, включая то, что видно только
        после прокрутки (у некоторых карточек часть полей находится ниже
        видимой части модалки).

        Модалка прокручивается в начало, затем в цикле: выделяем видимую
        часть -> копируем -> прокручиваем чуть ниже -> повторяем, до
        MODAL_SCROLL_PASSES раз. Останавливаемся раньше, если два прохода
        подряд дали одинаковый текст — значит, дальше внизу пусто, дошли
        до конца содержимого.

        expected_vin — если передан, после КАЖДОГО прохода проверяем, не
        появилась ли уже строка "VIN" с ДРУГИМ значением. Сайт может не
        показать ошибку и молча оставить карточку предыдущей машины (см.
        "ПОДМЕНА ДАННЫХ" в get_vehicle_card); без ранней проверки время
        уходило бы на все оставшиеся проходы прокрутки и ПОЛНЫЙ разбор
        карточки, и только потом обнаруживалось бы несовпадение. Если VIN
        виден уже в первом проходе (а он обычно виден, т.к. это одно из
        первых полей модалки) — останавливаемся сразу. Бросает
        _StaleCardDetected при обнаружении несовпадения — ловится в
        get_vehicle_card.

        ВАЖНО: НЕ делаем резкую прокрутку "в самый верх"
        (page.mouse.wheel(0, -5000)) — по наблюдениям на реальном прогоне
        после неё модалка исчезала, и вместо карточки копировался список
        категорий из фонового окна. Модалка открывается уже прокрученной в
        начало по умолчанию.
        """
        logger.debug("Копирую весь текст модального окна (с учётом прокрутки)")

        collected_chunks: List[str] = []
        previous_chunk: Optional[str] = None

        for pass_num in range(1, MODAL_SCROLL_PASSES + 1):
            if pass_num == 1 and first_chunk is not None:
                # Первый кусок уже скопирован — им же подтверждалось, что
                # модалка действительно открыта (см. _open_info_modal).
                # Копировать то же самое второй раз значит потратить лишнюю
                # протяжку мышью и лишние полторы секунды на каждом запросе.
                chunk = first_chunk
                logger.debug(
                    f"Модалка, проход 1/{MODAL_SCROLL_PASSES}: беру кусок, "
                    f"скопированный при проверке открытия ({len(chunk)} симв.)"
                )
            else:
                chunk = self._select_drag_and_copy(
                    page, MODAL_SELECT_START, MODAL_SELECT_END
                )
                logger.debug(
                    f"Модалка, проход {pass_num}/{MODAL_SCROLL_PASSES}: "
                    f"скопировано {len(chunk)} симв.: {chunk!r}"
                )

            if chunk.strip():
                if chunk == previous_chunk:
                    logger.debug(
                        f"Проход {pass_num}: текст совпал с предыдущим "
                        f"проходом — дальше внизу пусто, прекращаю прокрутку"
                    )
                    break
                collected_chunks.append(chunk)
                previous_chunk = chunk

                if expected_vin is not None:
                    found_vin = self._quick_extract_vin(chunk)
                    if found_vin is not None and self._normalize_vin(
                        found_vin
                    ) != self._normalize_vin(expected_vin):
                        logger.debug(
                            f"Проход {pass_num}: уже видно VIN {found_vin!r}, "
                            f"не совпадает с ожидаемым {expected_vin!r} — "
                            f"прекращаю прокрутку досрочно"
                        )
                        raise _StaleCardDetected(found_vin)
            else:
                logger.debug(
                    f"Проход {pass_num}: выделение попало в пустое место "
                    f"(буфер пуст после очистки)"
                )

            page.mouse.wheel(0, MODAL_SCROLL_STEP_PX)
            page.wait_for_timeout(200)

        return "\n".join(collected_chunks)

    @staticmethod
    def _quick_extract_vin(raw_text: str) -> Optional[str]:
        """
        Быстро достаёт значение поля "VIN" из ЕЩЁ НЕ ПОЛНОСТЬЮ собранного
        (возможно, обрезанного прокруткой) куска текста модалки — для
        досрочной проверки в _copy_modal_text. В отличие от
        _parse_vehicle_card, не пытается разобрать ВСЮ карточку — только
        найти одно конкретное поле, максимально просто и быстро.
        Возвращает None, если строка "VIN" не встретилась (например, у
        брендов без такого поля вообще, см. KNOWN_FIELD_LABELS — тогда
        досрочная проверка просто не сработает, и решение будет принято
        позже, при полном разборе карточки).
        """
        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]
        for i, line in enumerate(lines):
            if line.upper() == "VIN" and i + 1 < len(lines):
                return lines[i + 1]
        return None

    def _close_modal(self, page: Page) -> None:
        """
        Закрывает модальное окно.

        Клик по координате "мимо модалки" как единственный способ ненадёжен:
        модалки разных брендов разной ширины, и точка может оказаться
        ВНУТРИ широкой модалки (см. подробности у MODAL_CLOSE_CLICK_COORD)
        — экран останется затемнённым, и сессия не сможет стартовать.

        Поэтому основной способ — клавиша Escape: она не зависит ни от
        ширины модалки, ни от бренда, ни от размера окна. Клик по
        координате — второй шаг на случай, если конкретная модалка на
        Escape не реагирует.
        """
        logger.debug("Закрываю модальное окно (Escape, затем клик в стороне)")
        page.keyboard.press("Escape")
        page.wait_for_timeout(400)
        page.mouse.click(*MODAL_CLOSE_CLICK_COORD)
        page.wait_for_timeout(200)

    def _recover_from_open_vin_screen(self, page: Page) -> bool:
        """
        ⚠️ КНОПКА "Open VIN" — НЕ ПРИЗНАК ПЕРЕЗАГРУЗКИ СЕРВЕРА.

        Прогон эталона по скриншоту 20260823_120331 (Mercedes, совершенно
        здоровый экран):

            экран портала PARTSNUMBER   max_val = 1.000  в (660, 40)
            окно каталога (рабочее)     max_val = 0.353

        Совпадение ИДЕАЛЬНОЕ. То есть кнопка "Open VIN" — ПОСТОЯННЫЙ
        элемент шапки портала, а не примета аварии. Она видна всегда,
        когда окно каталога не перекрывает портал.

        Значит, признак означает не "сервер перезагрузился", а всего лишь
        "каталог сейчас не открыт поверх портала". Нажатие кнопки при этом
        остаётся осмысленным действием — оно и должно открывать каталог, —
        но выводов о состоянии сервера из него делать нельзя: упоминание
        перезагрузки сервера в сообщениях лога — лишь предположение о
        причине.

        Неудача после нажатия не превращается в "машины нет в каталоге"
        (см. ветку invalid_format в get_vehicle_card).

        Возвращает True, если кнопка найдена и нажата (это НЕ означает,
        что каталог уже открыт — только что мы нажали кнопку, которая
        должна к этому привести; готовность проверяется вызывающим кодом
        дальше по обычной схеме). Возвращает False, если кнопки на
        скриншоте нет.

        Не бросает исключений: это разведывательная проверка, а не
        обязательный шаг сценария — если что-то пойдёт не так при попытке
        сделать скриншот или кликнуть, лучше вернуть False и дать
        вызывающему коду попробовать другой путь восстановления.
        """
        try:
            screenshot_bytes = page.screenshot()
            coords = find_icon_on_screenshot(
                screenshot_bytes,
                OPEN_VIN_BUTTON_TEMPLATE_PATH,
                search_region=OPEN_VIN_BUTTON_REGION,
                threshold=OPEN_VIN_BUTTON_MATCH_THRESHOLD,
                log_details=False,  # свой лог ниже, чтобы не путать с обычным логотипом/иконками
            )
        except Exception as exc:
            logger.debug(f"Проверка экрана 'Open VIN' не удалась (не критично): {exc}")
            return False

        if coords is None:
            return False

        logger.debug(
            f"На экране видна кнопка 'Open VIN' в {coords} — значит, окно "
            f"каталога сейчас НЕ поверх портала. Нажимаю её, чтобы каталог "
            f"открылся."
        )
        # Неспешный клик, а не page.mouse.click(): мгновенный клик Horizon
        # теряет (подробный разбор в _click_deliberately). Здесь это особенно
        # обидно — потерянное нажатие выглядит как "кнопку нашли, нажали, а
        # экран не сменился", то есть как поломка распознавания, хотя
        # распознавание отработало верно.
        self._click_deliberately(page, *coords)
        page.wait_for_timeout(1500)  # даём каталогу время открыться после клика
        return True

