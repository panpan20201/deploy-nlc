# хранится БЕССРОЧНО (карточка описывает машину такой, какой она сошла с
# конвейера, и меняться не может), поэтому одна испорченная запись
# выдавалась бы человеку снова и снова, мгновенно и без единого обращения
# к PARTSNUMBER — например, "Enter a number: Enter a name / Notepad:
# Models" вместо карточки.
#
# Отсюда правило: защиты на входе мало, если данные хранятся дольше
# самой ошибки. Нужна ещё проверка на выходе из хранилища.
#
# Признаки взяты из реальных испорченных ответов. Это подписи элементов
# интерфейса каталога, которых в карточке машины быть не может ни у
# одной марки: поля поиска, боковое меню, блок групп деталей.
CATALOG_PAGE_MARKERS = (
    "Enter a number",
    "Enter a name",
    "Notepad",
    "Main group number",
)


def looks_like_catalog_page_text(card_text: str) -> bool:
    """
    Похоже ли, что это текст главной страницы каталога, а не карточки.

    Используется для проверки СОХРАНЁННЫХ карточек перед выдачей — см.
    подробное объяснение у CATALOG_PAGE_MARKERS.
    """
    if not card_text:
        return False
    return any(marker in card_text for marker in CATALOG_PAGE_MARKERS)


class PartsNumberSession:
    """
    Сессия работы с partsnumber.com (VMware Horizon веб-клиент).

    Открывается один раз (__enter__), заход в Horizon-сеанс не быстрый —
    пересоздавать сессию на каждый VIN нельзя. Используется как:

        with PartsNumberSession() as session:
            card1 = session.get_vehicle_card("KMHXX00XXXX000001")
            card2 = session.get_vehicle_card("KMHXX00XXXX000002")
    """

    def __init__(
        self,
        username: Optional[str] = None,
        password: Optional[str] = None,
        headless: bool = True,
    ):
        self.username = username or PARTSNUMBER_USERNAME
        self.password = password or PARTSNUMBER_PASSWORD
        if not self.username or not self.password:
            raise PartsNumberSessionError(
                "Не заданы PARTSNUMBER_USERNAME / PARTSNUMBER_PASSWORD в .env"
            )
        self.headless = headless
        self.last_reason: Optional[str] = None  # см. get_vehicle_card
        # Сколько раз ПОДРЯД не приехал буфер обмена. Предохранитель
        # от превращения отказа в зависание — см. _select_drag_and_copy.
        self._clipboard_failures_in_row = 0

        self._playwright: Optional[Playwright] = None
        self._browser: Optional[Browser] = None
        self._context: Optional[BrowserContext] = None
        self._page: Optional[Page] = None

    # ------------------------------------------------------------------
    # Контекстный менеджер
    # ------------------------------------------------------------------

    def __enter__(self) -> "PartsNumberSession":
        """
        Браузер иногда закрывается сам собой во время входа/ожидания
        рабочего стола (TargetClosedError) — не по вине пользователя.
        Точная причина не установлена. Плашка "session expired"
        подтверждена скриншотом и лечится в _wait_for_desktop_ready (см.
        SESSION_EXPIRED_TEXT); связана ли она с закрытием браузера —
        неизвестно. Для остальных сбоев Playwright здесь хотя бы
        превращаем сырой технический traceback в понятное сообщение — и
        советуем просто перезапустить скрипт, раз сессия и так уже
        разрушена.
        """
        try:
            logger.debug("Запуск Playwright и браузера")
            self._playwright = sync_playwright().start()
            self._browser = self._playwright.chromium.launch(headless=self.headless)
            self._context = self._browser.new_context(
                viewport={"width": VIEWPORT_WIDTH, "height": VIEWPORT_HEIGHT}
            )

            # Разрешения на буфер обмена нужны заранее — читать/писать через
            # navigator.clipboard.* без них Playwright не даст.
            self._grant_clipboard_permissions(PARTSNUMBER_LOGIN_URL)

            self._page = self._context.new_page()
            self._login()
            self._wait_for_desktop_ready()

            # Убираем с экрана всё, что могло остаться от ПРЕДЫДУЩЕГО
            # запуска.
            #
            # ЗАЧЕМ: Horizon-сессия живёт на сервере и переживает закрытие
            # браузера — при новом входе мы подключаемся к тому же рабочему
            # столу в том состоянии, в каком его бросили. Реально
            # наблюдается (подтверждено скриншотами): открытая карточка
            # (модалка) от машины из прошлого запроса. Такая модалка
            # перехватывает ввод — поле VIN становится недоступно, и первый
            # же поиск в этой сессии не срабатывает.
            #
            # Закрытие безопасно и когда закрывать нечего: Escape без
            # открытых окон ничего не делает, а клик приходится в пустое
            # место каталога (см. _close_modal).
            self._close_modal(self._page)

            # ВАЖНО: после входа в сам Horizon-сеанс адрес страницы почти
            # наверняка меняется (уходит на другой путь/поддомен относительно
            # страницы логина). Разрешение на буфер обмена выдаётся Playwright
            # на конкретный origin — если он не совпадёт с финальным адресом,
            # readText() в _copy_modal_text молча не сработает. Перевыдаём
            # разрешение уже на фактический origin рабочего стола.
            self._grant_clipboard_permissions(self._page.url)
        except PlaywrightError as e:
            raise PartsNumberSessionError(
                f"Браузер или страница закрылись сами по себе во время "
                f"входа в Horizon-сессию (техническая причина: {e}). Это "
                f"похоже на сбой самого браузера/сети, а не на ошибку в "
                f"сценарии — если это повторяется часто, сообщите об этом "
                f"и по возможности пришлите скриншот, если что-то необычное "
                f"видно на экране перед сбоем (например, плашку "
                f"'session expired'). Пока что просто перезапустите скрипт."
            ) from e
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> None:
        """
        Если браузер уже закрылся сам (см. пояснение в __enter__), попытка
        закрыть его ещё раз может бросить свою собственную ошибку —
        глушим её здесь, чтобы не перекрыть исходную настоящую причину
        сбоя (которая уже вылетела из __enter__/get_vehicle_card выше).
        """
        # Перед закрытием браузера прибираем за собой НА САМОМ УДАЛЁННОМ
        # РАБОЧЕМ СТОЛЕ — закрываем возможную открытую карточку (модалку).
        #
        # ЗАЧЕМ: Horizon-сессия живёт на сервере и переживает закрытие
        # браузера. Всё, что осталось открытым на экране, увидит СЛЕДУЮЩИЙ
        # запуск — и открытая модалка затемняет экран настолько, что
        # распознавание логотипа перестаёт срабатывать (см. подробности в
        # _wait_for_desktop_ready). Восстановление там тоже есть, но
        # правильнее не создавать проблему вовсе: закрыть
        # модалку в конце дешевле, чем распознавать и лечить её в начале.
        #
        # Строго best-effort: если сессия уже мертва или браузер отвалился —
        # молча пропускаем, это уборка, а не часть сценария.
        try:
            if self._page is not None and not self._page.is_closed():
                self._close_modal(self._page)
                self._page.wait_for_timeout(300)
        except Exception:
            pass

        logger.debug("Закрытие браузера")
        try:
            if self._context is not None:
                self._context.close()
        except PlaywrightError:
            pass
        finally:
            try:
                if self._browser is not None:
                    self._browser.close()
            except PlaywrightError:
                pass
            if self._playwright is not None:
                self._playwright.stop()

    # ------------------------------------------------------------------
    # Буфер обмена
    # ------------------------------------------------------------------

    def _grant_clipboard_permissions(self, url_or_origin: str) -> None:
        """
        Выдаёт разрешения clipboard-read/clipboard-write на origin,
        вычисленный из переданного URL. Вызывается повторно при смене
        адреса страницы (логин -> Horizon-сеанс), т.к. разрешение
        привязано к конкретному origin.
        """
        parsed = urlparse(url_or_origin)
        origin = f"{parsed.scheme}://{parsed.netloc}"
        logger.debug(f"Выдаю разрешения на буфер обмена для origin={origin}")
        self._context.grant_permissions(
            ["clipboard-read", "clipboard-write"], origin=origin
        )

    # ------------------------------------------------------------------
    # Логин / готовность рабочего стола
    # ------------------------------------------------------------------

    def _login(self) -> None:
        """
        Логин на странице до входа в сам Horizon-сеанс.

        ВАЖНО (подтверждено скриншотом): страница логина, в отличие
        от самого рабочего стола Horizon после входа, — это ОБЫЧНАЯ HTML-
        страница с настоящими доступными подписями полей ("Username",
        "Password", кнопка "Login"). Поэтому здесь используем обычные
        Playwright-селекторы с автоматическим ожиданием готовности элемента
        — это надёжнее фиксированных координат (не зависит от точного
        размера окна/времени загрузки) и не требует ручной калибровки.
        Координатный клик оставлен только там, где он неизбежен —
        внутри самого Horizon-рабочего стола после входа (там нет DOM).
        """
        logger.debug(f"Открываю страницу логина: {PARTSNUMBER_LOGIN_URL}")
        page = self._require_page()
        # Оба параметра навигации заданы явно: умолчания Playwright здесь не
        # подходят. С ними вход падает так:
        #
        #     PartsNumberSessionError: ... Page.goto: Timeout 30000ms exceeded.
        #     - navigating to "https://login.partsnumber.com/portal/webclient/
        #       index.html?desktopId=pn&action=start-session#/",
        #       waiting until "load"
        #
        # wait_until="load" ждёт, пока догрузятся ВСЕ подресурсы страницы.
        # Horizon-клиент — тяжёлое SPA, и это ожидание ничего нам не даёт:
        # сразу после goto идёт собственная гонка "форма логина ИЛИ готовый
        # рабочий стол" (см. ниже), у каждой ветки свой явный таймаут. То
        # есть "load" не приближает нас к цели, зато добавляет отдельный
        # способ упасть.
        #
        # 30 секунд для входа в стриминг рабочего стола — просто мало;
        # обоснование выбранного потолка — у NAVIGATION_TIMEOUT_SEC.
        goto_started = time.monotonic()
        page.goto(
            PARTSNUMBER_LOGIN_URL,
            wait_until="domcontentloaded",
            timeout=NAVIGATION_TIMEOUT_SEC * 1000,  # Playwright ждёт миллисекунды
        )
        # Замер в лог на КАЖДЫЙ вход, а не только на сбой: потолок
        # NAVIGATION_TIMEOUT_SEC выбирался по разбросу этих чисел (см.
        # константу), и пересматривать его надо по ним же, а не по
        # ощущениям. INFO, чтобы было видно и в консоли.
        logger.info(
            "Страница логина открылась за %.0f с (потолок %.0f).",
            time.monotonic() - goto_started, NAVIGATION_TIMEOUT_SEC,
        )

        # -----------------------------------------------------------------
        # ГОНКА "форма логина ИЛИ уже готовый рабочий стол"
        #
        # Форма логина появляется НЕ ВСЕГДА: если сессия в браузере ещё
        # жива, Horizon сам восстанавливает уже открытый сеанс и сразу
        # уводит страницу на URL с "#/desktop", вообще не показывая форму
        # входа. В логе это выглядит так:
        #     navigated to "...&action=start-session#/desktop"
        #     waiting for get_by_placeholder("Username") to be visible
        # Безусловное ожидание поля "Username" упало бы по таймауту ровно в
        # том случае, когда логиниться и НЕ НУЖНО, потому что мы уже внутри.
        #
        # Поэтому ждём ЛЮБОЙ из двух исходов: появилось поле
        # "Username" (обычный вход — вводим данные) ИЛИ страница уже на
        # рабочем столе (вход не требуется — просто выходим, а вызывающий
        # код дальше сам проверит готовность через _wait_for_desktop_ready).
        # -----------------------------------------------------------------
        username_field = page.get_by_placeholder("Username")
        deadline = time.monotonic() + LOGIN_FORM_TIMEOUT_SEC
        login_form_visible = False

        while time.monotonic() < deadline:
            try:
                if username_field.is_visible():
                    login_form_visible = True
                    break
            except Exception:
                # Страница в этот момент могла перезагружаться — не страшно,
                # просто пробуем снова на следующей итерации.
                pass

            if "#/desktop" in page.url:
                logger.debug(
                    "Форма логина не показана — Horizon восстановил уже "
                    "открытую сессию (страница /desktop). Ввод учётных "
                    "данных не требуется."
                )
                return

            page.wait_for_timeout(300)

        if not login_form_visible:
            # Ни формы, ни рабочего стола. Намеренно НЕ бросаем исключение
            # здесь: окончательный вердикт вынесет _wait_for_desktop_ready()
            # у вызывающего кода — там и проверка полноценнее, и сообщение
            # об ошибке понятнее. Здесь только честно фиксируем ситуацию.
            logger.warning(
                "За %s сек не появилась ни форма логина, ни рабочий стол "
                "Horizon — продолжаю, проверку готовности сделает "
                "вызывающий код.",
                LOGIN_FORM_TIMEOUT_SEC,
            )
            return

        logger.debug("Ввожу логин")
        username_field.click()
        username_field.fill(self.username)

        logger.debug("Ввожу пароль")
        password_field = page.get_by_placeholder("Password")
        password_field.click()
        password_field.fill(self.password)

        logger.debug("Нажимаю кнопку входа")
        page.get_by_role("button", name="Login").click()

        logger.debug("Форма логина отправлена")

    def _is_on_catalogs_screen(
        self,
        page: Page,
        retries: int = 3,
        retry_delay_sec: float = 1.0,
        log_details: bool = True,
    ) -> bool:
        """
        Проверяет, виден ли логотип "PARTSNUMBER" в левом верхнем углу —
        признак, что мы на экране приложения Catalogs (а не на каком-то
        непредвиденном другом экране Horizon-сессии). См. пояснение у
        константы PARTSNUMBER_LOGO_TEMPLATE_PATH выше.

        Сразу после того, как область у логотипа
        "стабилизировалась" (см. _wait_for_area_stable), самого логотипа
        PARTSNUMBER на экране ещё может не быть — Blast-стрим иногда
        прорисовывает элементы не одновременно, и один кадр может оказаться
        почти пустым/чёрным (наблюдалось: max_val=0.000 — явный признак
        "кадр ещё не готов", а не "логотипа тут никогда не будет"). Поэтому,
        как и для иконки ⓘ, делаем несколько попыток с паузой, а не решаем
        по одному кадру.

        log_details=False — не писать подробную DEBUG-строку на каждую
        попытку (используется при вызове из длинного цикла ожидания в
        _wait_for_desktop_ready — см. пояснение у find_icon_on_screenshot).
        """
        for attempt in range(1, retries + 1):
            screenshot_bytes = page.screenshot()
            coords = find_icon_on_screenshot(
                screenshot_bytes,
                PARTSNUMBER_LOGO_TEMPLATE_PATH,
                search_region=PARTSNUMBER_LOGO_REGION,
                threshold=PARTSNUMBER_LOGO_MATCH_THRESHOLD,
                log_details=log_details,
            )
            if coords is not None:
                return True
            if attempt < retries:
                if log_details:
                    logger.debug(
                        f"Логотип PARTSNUMBER не найден (попытка {attempt}/{retries}), "
                        f"жду {retry_delay_sec}с и пробую снова — возможно, кадр ещё не прорисовался"
                    )
                page.wait_for_timeout(int(retry_delay_sec * 1000))
        return False

    def _desktop_responds_to_input(self, page: Page) -> bool:
        """
        ФУНКЦИОНАЛЬНАЯ проверка готовности рабочего стола — дополнение к
        распознаванию логотипа.

        ПОЧЕМУ НУЖНА ДРУГАЯ ПРОВЕРКА. Совпадение картинки логотипа
        PARTSNUMBER с эталоном хрупко сразу по нескольким причинам, и все
        они встречаются на практике:
          - открытая модалка ЗАТЕМНЯЕТ фон, логотип на месте, но совпадение
            падает ниже порога (наблюдалось стабильное 0.245 при пороге 0.3);
          - у разных брендов разная вёрстка шапки;
          - любое изменение масштаба/темы ломает эталон.
        То есть логотип — ПОБОЧНЫЙ признак (узнаётся ли картинка), а не то,
        что нам на самом деле нужно (можно ли работать с приложением).

        Эта проверка спрашивает ровно то, что важно: ОТВЕЧАЕТ ЛИ приложение
        на ввод. Механика: закрыть возможную модалку -> кликнуть в поле VIN
        -> напечатать короткий маркер -> выделить и скопировать -> сравнить
        с тем, что печатали. Если в буфере оказался наш маркер, значит поле
        доступно, фокус ставится, ввод доходит, буфер работает — рабочий
        стол функционален, независимо от того, как он сейчас выглядит.

        В конце поле очищается, чтобы маркер не мешал последующему вводу VIN.

        Возвращает True/False и НЕ бросает исключений: это проверка
        состояния, а не действие — вызывающий код сам решает, что делать
        с отрицательным ответом (подождать ещё, перелогиниться, сдаться).
        """
        PING_MARKER = "PNPING"
        try:
            # Escape + клик в стороне: если открыта модалка (например,
            # осталась от прошлого запуска — Horizon-сессия живёт на
            # сервере и переживает закрытие браузера), она перехватывает
            # ввод, и поле VIN недоступно.
            self._close_modal(page)

            page.evaluate("navigator.clipboard.writeText('')")

            page.mouse.click(*VIN_INPUT_COORD)
            page.wait_for_timeout(250)
            page.keyboard.press("Control+A")
            page.wait_for_timeout(120)
            page.keyboard.type(PING_MARKER, delay=40)
            page.wait_for_timeout(200)

            page.keyboard.press("Control+A")
            page.wait_for_timeout(120)
            page.keyboard.press("Control+C")
            page.wait_for_timeout(500)

            clipboard_text = page.evaluate("navigator.clipboard.readText()") or ""
            responded = PING_MARKER in clipboard_text.strip().upper()

            # Прибираем за собой в любом случае — маркер не должен остаться
            # в поле и приклеиться к следующему вводимому VIN.
            page.keyboard.press("Control+A")
            page.wait_for_timeout(120)
            page.keyboard.press("Delete")
            page.wait_for_timeout(120)

            return responded
        except Exception as exc:  # noqa: BLE001 — это проверка состояния
            logger.debug(f"Функциональная проверка поля VIN не прошла: {exc}")
            return False

    def _session_expired_dialog_visible(self, page: Page) -> bool:
        """
        Показывает ли портал Horizon диалог «Your session has expired».

        Ищем по тексту в DOM (см. SESSION_EXPIRED_TEXT): портал — обычная
        HTML-страница. На холсте рабочего стола такого текста нет, поэтому
        на нормальном экране проверка отвечает «нет» и ничего не стоит.

        Не бросает исключений: это проверка состояния. Если страница в
        этот момент перегружается и DOM недоступен — считаем, что диалога
        нет, и обычное ожидание продолжается.
        """
        try:
            return page.get_by_text(SESSION_EXPIRED_TEXT).first.is_visible()
        except Exception as exc:  # noqa: BLE001 — проверка состояния
            logger.debug(f"Не удалось проверить диалог истёкшей сессии: {exc}")
            return False

    def _reconnect_after_session_expired(self, page: Page) -> None:
        """
        Закрывает диалог «session has expired» и заново открывает адрес
        запуска сеанса — ровно то, что Horizon и просит («please
        re-connect the server»).

        Повторный вход идёт через тот же _login(): он сам разберётся,
        показана ли форма (сессия портала тоже истекла) или Horizon
        восстановил вход и сразу запускает рабочий стол.
        """
        logger.warning(
            "Портал Horizon сообщает, что сессия истекла (диалог «Your session "
            "has expired») — закрываю диалог и переподключаюсь."
        )
        try:
            page.get_by_role("button", name=SESSION_EXPIRED_OK_BUTTON).first.click(
                timeout=3000
            )
        except Exception as exc:  # noqa: BLE001
            # Кнопка не нашлась — не страшно: повторная навигация всё
            # равно уводит со страницы вместе с диалогом. В лог — чтобы
            # по следующему случаю понять, как кнопка называется на деле.
            logger.debug(f"Кнопку «{SESSION_EXPIRED_OK_BUTTON}» нажать не удалось: {exc}")
        self._login()

    def _describe_page_for_log(self, page: Page) -> str:
        """
        Адрес и первые строки ТЕКСТА страницы — для лога при непонятном
        экране. Скриншот показывает, как экран выглядит; текст DOM — из
        чего он сделан, и по нему можно написать проверку, как для
        диалога истёкшей сессии. Нужно ровно затем, чтобы следующий
        незнакомый экран портала не пришлось разбирать по пикселям.
        """
        try:
            url = page.url
        except Exception:  # noqa: BLE001
            url = "?"
        try:
            text = page.inner_text("body", timeout=2000) or ""
        except Exception as exc:  # noqa: BLE001
            text = f"<текст недоступен: {exc}>"
        text = " | ".join(line.strip() for line in text.splitlines() if line.strip())
        if len(text) > 400:
            text = text[:400] + "…"
        return f"url={url}; текст: {text or '<пусто>'}"

    def _wait_for_desktop_ready(self) -> None:
        """
        Дождаться загрузки удалённого рабочего стола и появления окна
        "Catalogs" с полем "Enter VIN/Frame".

        Ожидание "область у логотипа перестала меняться"
        (_wait_for_area_stable) здесь не годится: экран ЗАГРУЗКИ — сплошной
        серый прямоугольник БЕЗ единого другого пикселя (подтверждено
        сохранённым скриншотом) — тоже технически "не меняется" и
        засчитывался бы как "стабильно", хотя реальный контент ещё даже не
        начал прорисовываться. Время самой загрузки нестабильно и каждый
        раз разное, поэтому небольшого числа попыток с паузой (например, 3
        попытки по 1 секунде) недостаточно.

        Поэтому ждём НЕПОСРЕДСТВЕННО появления самого логотипа
        PARTSNUMBER, поллингом, в рамках всего бюджета времени
        DESKTOP_READY_TIMEOUT_SEC (60с) — а не по отдельному мелкому
        лимиту попыток. Экран загрузки (без логотипа) просто продолжает
        считаться "ещё не готово" и не сбивает проверку с толку.

        Подробный DEBUG-лог на КАЖДУЮ попытку (раз в ~0.4с, то есть до ~150
        одинаковых строк за 60 секунд) выглядит как зависание скрипта, хотя
        он просто ждёт в рамках отведённого времени, — так недолго и
        прервать его вручную раньше таймаута. Поэтому подробности не
        печатаются на каждой попытке — вместо этого раз в
        PROGRESS_LOG_INTERVAL_SEC печатается одна
        компактная строка о том, сколько уже прошло секунд и какое сейчас
        лучшее совпадение — видно, что скрипт жив и чем именно занят.
        """
        logger.debug("Ожидаю готовности удалённого рабочего стола (Catalogs)")
        page = self._require_page()
        start = time.monotonic()
        deadline = start + DESKTOP_READY_TIMEOUT_SEC
        last_progress_log = 0.0

        # -----------------------------------------------------------------
        # ДВА КРИТЕРИЯ ГОТОВНОСТИ
        #
        # 1) БЫСТРЫЙ: логотип PARTSNUMBER распознан в левом верхнем углу.
        # 2) НАДЁЖНЫЙ: приложение отвечает на ввод в поле VIN.
        #
        # Второй нужен потому, что первый может давать ЛОЖНОЕ "не готово"
        # на полностью рабочем экране. Подтверждено скриншотами: с прошлого
        # запуска остаётся открытая карточка (Horizon-сессия живёт на
        # сервере и переживает закрытие браузера), она затемняет фон, и
        # совпадение логотипа падает ниже порога — экран при этом
        # совершенно рабочий. Ждать в такой ситуации бессмысленно: картинка
        # статична и сама себя не "дорисует".
        #
        # Поэтому отрицательный ответ первой проверки — не приговор, а повод
        # задать вопрос по-другому: не "узнаю ли я картинку", а "работает ли
        # приложение" (см. _desktop_responds_to_input — там же оно заодно
        # закрывает мешающую модалку).
        # -----------------------------------------------------------------
        # Как часто пробовать ФУНКЦИОНАЛЬНУЮ проверку (она "дороже" по
        # времени, чем сравнение картинки: клики, ввод, чтение буфера — под
        # секунду), поэтому не на каждой итерации, а раз в несколько секунд.
        FUNCTIONAL_CHECK_EVERY_SEC = 6.0
        last_functional_check = 0.0
        # Переподключение после «session has expired» — ОДИН раз за
        # ожидание. Если диалог возвращается и после него, крутиться
        # здесь нельзя: причина потеряется, а время уйдёт.
        reconnected = False

        while time.monotonic() < deadline:
            elapsed = time.monotonic() - start
            log_now = elapsed - last_progress_log >= PROGRESS_LOG_INTERVAL_SEC

            # Быстрый путь: логотип виден — всё точно хорошо, дальше не
            # проверяем (сравнение картинки дешевле функциональной проверки).
            if self._is_on_catalogs_screen(page, retries=1, log_details=log_now):
                logger.debug("Рабочий стол готов (логотип распознан)")
                return

            # Экран "Open VIN" (виртуальная машина
            # перезагрузила сервер PARTSNUMBER — см. подробности у
            # OPEN_VIN_BUTTON_TEMPLATE_PATH) может встретиться и сразу
            # после входа, не только между запросами.
            if self._recover_from_open_vin_screen(page):
                continue  # сразу на следующую итерацию — проверим логотип заново

            # Вместо рабочего стола может оказаться портал с диалогом
            # «session has expired»
            # (подробности у SESSION_EXPIRED_TEXT). Ждать здесь логотип
            # бессмысленно, на портале его не бывает. Переподключаемся и
            # даём рабочему столу полный срок заново: время до диалога
            # ушло на первый, несостоявшийся запуск.
            if not reconnected and self._session_expired_dialog_visible(page):
                reconnected = True
                self._reconnect_after_session_expired(page)
                start = time.monotonic()
                deadline = start + DESKTOP_READY_TIMEOUT_SEC
                last_progress_log = last_functional_check = 0.0
                continue

            # Медленный, но надёжный путь: логотип не распознался — это ещё
            # НЕ значит, что рабочий стол не готов (он мог быть затемнён
            # модалкой, вёрстка бренда могла отличаться и т.п. — см.
            # подробности в _desktop_responds_to_input). Спрашиваем у
            # приложения напрямую, отвечает ли оно на ввод.
            if elapsed - last_functional_check >= FUNCTIONAL_CHECK_EVERY_SEC:
                last_functional_check = elapsed
                logger.debug("Логотип не распознан — проверяю, отвечает ли приложение на ввод")
                if self._desktop_responds_to_input(page):
                    logger.debug("Рабочий стол готов (поле VIN отвечает на ввод)")
                    return

            if log_now:
                logger.debug(
                    f"Всё ещё жду появления логотипа PARTSNUMBER "
                    f"({elapsed:.0f}с из {DESKTOP_READY_TIMEOUT_SEC:.0f}с)"
                )
                last_progress_log = elapsed
            page.wait_for_timeout(int(POLL_INTERVAL_SEC * 1000))

        self._dump_debug_screenshot(page, "unexpected_screen_after_login")
        # Текст DOM рядом со скриншотом: на сплошном сером кадре по
        # картинке не понять ничего, а по тексту страницы видно, что
        # именно Horizon показывал.
        logger.warning("Что на странице: %s", self._describe_page_for_log(page))
        raise PartsNumberSessionError(
            f"Логотип PARTSNUMBER не появился за {DESKTOP_READY_TIMEOUT_SEC}с "
            f"после входа в Horizon-сессию — либо загрузка занимает дольше "
            f"обычного, либо открылся не экран каталога, а что-то другое "
            f"(см. сохранённый диагностический скриншот)."
        )

    def _ensure_desktop_alive(self) -> None:
        """
        Проверка/восстановление сессии Horizon перед очередным поиском.

        Два независимых уровня проверки:
          1) мы вообще на экране каталога (логотип PARTSNUMBER на месте) —
             см. _is_on_catalogs_screen;
          2) поле VIN реально откликается на ввод (проверка ping-текстом).

        Если что-то из этого не так — пробуем один раз перелогиниться.
        Если и после этого не помогло — не пытаемся угадывать дальше,
        останавливаемся с понятной ошибкой и сохранённым скриншотом (см.
        пояснение у PARTSNUMBER_LOGO_TEMPLATE_PATH — автоматическое
        восстановление предусмотрено только для известных экранов).
        """
        page = self._require_page()
        logger.debug("Проверка отклика поля VIN (на случай разлогина Horizon)")

        needs_relogin = not self._is_on_catalogs_screen(page)
        if needs_relogin:
            # Проверяем ещё и экран "Open VIN" — он появляется, когда виртуальная машина сама перезагрузила
            # сервер PARTSNUMBER (см. подробности у
            # OPEN_VIN_BUTTON_TEMPLATE_PATH). В отличие от "приложение не
            # отвечает" ниже, здесь мы точно знаем, что делать — нажать
            # конкретную кнопку — поэтому проверяем это раньше остального:
            # дешевле и вернее, чем полагаться на функциональный "пинг".
            if self._recover_from_open_vin_screen(page):
                if self._is_on_catalogs_screen(page):
                    logger.debug("Восстановились после экрана 'Open VIN' — рабочий стол снова на месте")
                    return
                # Кнопку нажали, но обычный рабочий стол всё ещё не виден —
                # не страшно, ниже по коду есть ещё один уровень проверки
                # (функциональный "пинг"), дадим ему шанс.

            # Нераспознанный логотип НЕ означает автоматически "надо
            # перелогиниться". Он мог не распознаться из-за затемнения
            # открытой модалкой или иной вёрстки бренда, тогда как
            # приложение полностью работоспособно (см. подробности в
            # _desktop_responds_to_input). Перелогин в такой
            # ситуации — лишние 30+ секунд и лишний риск, поэтому сначала
            # спрашиваем приложение напрямую, отвечает ли оно на ввод.
            logger.debug(
                "Логотип PARTSNUMBER не распознан — проверяю, отвечает ли "
                "приложение на ввод, прежде чем перелогиниваться"
            )
            if self._desktop_responds_to_input(page):
                logger.debug("Приложение отвечает на ввод — перелогин не нужен")
                return

            logger.warning(
                "Логотип PARTSNUMBER не найден и приложение не отвечает на "
                "ввод — похоже, сессия действительно нерабочая, "
                "перелогиниваюсь"
            )
            # Скриншот именно ЭТОГО момента: без него из лога видно только
            # "логотип не найден", но не видно, что же реально было на
            # экране — заставка, разорванное соединение, диалог Horizon или
            # просто чёрный кадр. Разные причины лечатся по-разному, поэтому
            # кадр стоит сохранить до перелогина, пока состояние не затёрлось.
            self._dump_debug_screenshot(page, "logo_not_found_before_relogin")
        else:
            try:
                page.mouse.click(*VIN_INPUT_COORD)
                page.wait_for_timeout(300)  # см. пояснение в _enter_vin про паузы
                page.keyboard.press("Control+A")
                page.wait_for_timeout(150)
                page.keyboard.type("PING_TEST", delay=50)
                page.wait_for_timeout(150)
                # Если поле реагирует нормально — сотрём тестовый ввод и продолжим.
                page.keyboard.press("Control+A")
                page.wait_for_timeout(150)
                page.keyboard.press("Delete")
            except Exception as e:  # noqa: BLE001 — ловим широко, это heuristics-проверка
                logger.warning(
                    f"Поле VIN не отвечает как ожидалось ({e}), "
                    f"пробую перелогиниться в Horizon-сессию"
                )
                needs_relogin = True

        if not needs_relogin:
            return

        self._login()
        self._wait_for_desktop_ready()  # сама бросит понятную ошибку, если снова не тот экран

