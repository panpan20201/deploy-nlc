# "Mercedes").
#
# ПОЧЕМУ ЧЕРЕЗ ЭТАЛОНЫ, А НЕ ЧЕРЕЗ ЧТЕНИЕ ТЕКСТА. Читать надписи бот не
# умеет — он сравнивает картинки. Скопировать текст экрана буфером можно,
# но текст не даёт КООРДИНАТ, а сетка здесь разрежена (FCA и Mercedes в
# одной строке, VAG во второй), и вычислить положение по номеру строки
# нельзя. Эталон же даёт точку напрямую.
#
# Замер на четырёх реальных экранах:
#
#     экран выбора группы     max_val = 1.000  центр (869, 177)
#     рабочий экран Hyundai   max_val = 0.642
#     портал Hyundai          max_val = 0.534
#     лаунчер Horizon         max_val = 0.574
#
# Запас до ближайшего чужого — больше трети. Порог 0.85 надёжен.
