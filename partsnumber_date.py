    @staticmethod
    def _find_modal_anchor(lines: "List[str]") -> Optional[int]:
        """
        Номер строки "Search..." — подписи поля поиска ВНУТРИ модалки.

        Это единственный элемент, который есть в модалке у всех брендов и
        которого нет среди полей данных (подтверждено на Hyundai и Volvo).
        Поэтому он служит сразу двум целям: границей "шапки" при разборе и
        доказательством того, что скопирована именно модалка.

        :return: индекс строки или None, если якоря в тексте нет
        """
        for i, line in enumerate(lines):
            if line.upper().rstrip(".").strip() == "SEARCH":
                return i
        return None

    @staticmethod
    def _modal_text_looks_valid(raw_text: str) -> bool:
        """
        Скопирован ли действительно текст модалки, а не то, что под ней.

        Пример — VIN KNAKR814DMA223636 (Kia Mohave): якоря 'Search...' в
        скопированном тексте нет, а текст главной страницы каталога,
        разобранный "как есть" в пары метка/значение, проходит все
        остальные проверки и выглядит как готовый ответ:

            Enter a number: Enter a name
            EN: Kia
            Notepad: Models
            KNAKM814DJA174170:

        Это худший из возможных исходов: не ошибка, а УВЕРЕННАЯ
        БЕССМЫСЛИЦА. Человек не может отличить её от настоящих данных, а
        внутри — чужой VIN (KNAKM814DJA174170 вместо запрошенного
        KNAKR814DMA223636) и дата 2017 года у машины 2021-го.

        Почему это не ловят другие проверки: обе сверки VIN ("ПОДМЕНА
        ДАННЫХ") ищут поле с меткой "VIN", а на странице каталога такого
        поля нет вовсе — обе тихо пропускают ход. Наш собственный VIN при
        этом в тексте ЕСТЬ (он же набран в поле поиска), так что и
        досрочная проверка несовпадения молчит.

        Что происходит физически: модалка не открылась или успела
        закрыться, и протяжка мышью выделила фоновое окно каталога. Ровно
        то, о чём предупреждает комментарий в _copy_modal_text
        ("вместо карточки копировался список категорий из фонового окна").
        Косвенный признак — время шага: около 19 секунд против обычных
        50-70, проходы прокрутки по модалке просто не выполняются.

        Правило: отсутствие якоря — это
        НЕ повод "попробовать разобрать как есть". Это доказательство, что
        перед нами не модалка, и единственный честный ответ — ошибка шага.
        Шаг после неё повторится (STEP_ATTEMPTS=2 в pipeline.py), а
        PARTSNUMBER не тратит никаких дневных квот, так что повтор
        бесплатен и, скорее всего, откроет модалку нормально.
        """
        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]
        return PartsNumberSession._find_modal_anchor(lines) is not None

    @staticmethod
    def _parse_vehicle_card(raw_text: str) -> "dict[str, str]":
        """
        Разбирает сырой скопированный текст модалки на пары метка/значение.

        ДВЕ ОСОБЕННОСТИ (обе видны на Volvo):

        1) "Шапку" модалки (кнопка закрытия, названия вкладок) нельзя
           отбрасывать по строке "VIN": у Hyundai реальные поля
           начинаются с неё, но у Volvo поля "VIN" в модалке ВООБЩЕ НЕТ
           (вместо него "Chassis No") — в разбор попала бы шапка целиком,
           сдвигая все пары метка/значение на произвольное число строк.

           Поэтому ищем строку "Search..." — это подпись поля поиска
           ВНУТРИ САМОЙ МОДАЛКИ (общий элемент интерфейса, есть у всех
           брендов, а не название поля данных), реальные поля идут сразу
           после неё. Подтверждено и на Hyundai, и на Volvo.

        2) У некоторых полей ЗНАЧЕНИЕ ПУСТОЕ (у Volvo — "License Plate",
           номер скрыт/недоступен). Если всегда брать следующую строку
           как значение, вся карточка "съезжает" на одну строку, и все
           поля после этого поля перепутываются местами (значение одного
           поля утекает под меткой соседнего).

           Поэтому перед тем как забрать следующую строку как значение,
           проверяем — не похожа ли она сама на известную метку поля (см.
           KNOWN_FIELD_LABELS). Если похожа — считаем, что у текущего поля
           значение пустое, и НЕ трогаем эту строку, она станет следующей
           меткой.

           ВАЖНО: KNOWN_FIELD_LABELS собран из полей, что уже реально
           встречались. Для НОВОГО бренда с незнакомыми названиями полей
           эта проверка бессильна (пустое значение снова может сдвинуть
           карточку) — при похожей путанице на новом бренде нужно по
           DEBUG-логу с сырым текстом модалки добавить недостающие метки в
           список.

        Формат полей — метка на одной строке, значение на следующей
        (если оно не пустое). Т.к. текст может быть собран из НЕСКОЛЬКИХ
        проходов прокрутки с перекрытием (см. _copy_modal_text), одинаковые
        метки могут повториться — оставляем первое встреченное значение для
        каждой метки, порядок появления сохраняется.
        """
        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]

        # Отбрасываем "шапку" модалки — она заканчивается строкой "Search..."
        # (см. п.1 в описании метода выше). Работает одинаково для всех
        # брендов, в отличие от поиска строки "VIN".
        search_index = PartsNumberSession._find_modal_anchor(lines)
        if search_index is not None:
            lines = lines[search_index + 1:]
        else:
            # Сюда мы в обычном ходе дел не попадаем: отсутствие якоря
            # ловится РАНЬШЕ, в get_vehicle_card, и приводит к честной
            # ошибке шага (см. _modal_text_looks_valid). Ветка нужна на
            # случай прямого вызова этого метода из тестов или калибровки.
            logger.warning(
                "В скопированном тексте модалки не найдена строка "
                "'Search...' — разбираю текст как есть, но результату "
                "доверять нельзя."
            )

        fields: "dict[str, str]" = {}
        i = 0
        while i < len(lines):
            label = PartsNumberSession._format_label(lines[i])

            next_line_is_label = (
                i + 1 < len(lines)
                and lines[i + 1].strip().upper() in KNOWN_FIELD_LABELS
            )
            if i + 1 < len(lines) and not next_line_is_label:
                value = PartsNumberSession._format_value(lines[i + 1])
                i += 2
            else:
                # Следующая строка сама похожа на метку (см. п.2 выше) или
                # строк больше не осталось — у текущего поля пустое значение.
                value = ""
                i += 1

            if label not in fields:
                fields[label] = value

        return fields

    @staticmethod
    def _format_label(label: str) -> str:
        """
        Косметика метки: убрать хвостовую точку ("Fuel." -> "Fuel"),
        если метка изначально строчная — сделать заглавной только первую
        букву ("engine displacement" -> "Engine displacement"). Метки,
        уже оформленные (ПРОПИСНЫМИ или с Заглавной буквы), не трогаем.
        """
        label = label.rstrip(".").strip()
        if label and label != label.upper() and label[0].islower():
            label = label[0].upper() + label[1:]
        return label

    @staticmethod
    def _format_value(value: str) -> str:
        """
        Косметика значения: если значение имеет вид "А - А" (обе половины
        разделённые " - " совпадают, без учёта регистра) — это дублирующая
        запись вроде "DIESEL - DIESEL", схлопываем в одну "DIESEL".
        Если половины разные ("DRIVE TYPE - LEFT-HAND DRIVE") — оставляем
        значение целиком, там есть дополнительный смысл.
        """
        value = value.strip()
        if " - " in value:
            left, _, right = value.partition(" - ")
            if left.strip().lower() == right.strip().lower():
                return left.strip()
        return value

    def _copy_logo_line_text(self, page: Page) -> str:
        """
        Копирует СЫРОЙ текст у логотипа бренда, без какого-либо разбора —
        просто то, что реально показано на экране в этом месте. Формат
        этого текста РАЗНЫЙ у разных марок (см. _parse_chassis_code_from_
        logo_line ниже) — эта функция сама по себе формат не предполагает.

        Однострочная область, скролл не требуется (в отличие от модалки).

        Конечная точка протяжки — LOGO_LINE_SELECT_END_COORD (не путать с
        LOGO_AREA_CLIP, которая используется только для скриншот-сравнения
        в _run_search) — см. комментарий у константы, почему они разделены.
        """
        x, y, _width, _height = LOGO_AREA_CLIP
        start = (x, y)
        end = LOGO_LINE_SELECT_END_COORD

        text = self._select_drag_and_copy(page, start, end)
        logger.debug(f"Строка у логотипа скопирована: {text!r}")
        return text

    @staticmethod
    def _parse_chassis_code_from_logo_line(text: str) -> str:
        """
        Достаёт код кузова из строки формата "Model | Код | Дата" (так у
        Hyundai, например "Palisade 19 | LX2 | 16.11.2021") — средний
        сегмент между "|".

        ВАЖНО (проверено на Audi и Mercedes): у
        других марок этот формат вообще ДРУГОЙ — например, у Audi просто
        "Audi Q5, 25.02.2023" (запятая вместо "|", кода кузова там в
        принципе НЕТ отдельным сегментом), у Mercedes и того короче,
        просто "Mercedes GLC 300 / 4MATIC coupe" без даты вообще. Если
        разделителя "|" нет — это НЕ ошибка и НЕ признак того, что
        страница не загрузилась, это просто у марки нет отдельного кода
        кузова в этом месте экрана. Возвращаем "" в этом случае, и
        ВЫЗЫВАЮЩИЙ КОД ДОЛЖЕН ПРОДОЛЖАТЬ РАБОТУ, а не считать это сбоем —
        см. get_vehicle_card, где признаком "страница перешла к результату"
        служит иконка ⓘ, а не результат этого разбора. _format_vehicle_card
        штатно
        обрабатывает пустой chassis_code — просто не добавляет " | код"
        к заголовку карточки.
        """
        parts = [p.strip() for p in text.split("|")]
        if len(parts) >= 2 and parts[1]:
            return parts[1]
        return ""

    @staticmethod
    def _format_vehicle_card(fields: "dict[str, str]", chassis_code: str) -> str:
        """
        Собирает итоговый текст карточки:

            Palisade 19 | LX2

            VIN: KMHR281ADNU407019
            Nation: KOREA
            ...
        """
        # У Hyundai поле называется "Vehicle", у Volvo такого поля нет —
        # вместо него "Model" (то же значение по смыслу, для заголовка
        # карточки). Берём первое, что нашлось.
        vehicle_name = fields.get("Vehicle") or fields.get("Model", "")
        header = f"{vehicle_name} | {chassis_code}" if chassis_code else vehicle_name

        lines = [header, ""]
        for label, value in fields.items():
            lines.append(f"{label}: {value}")
        return "\n".join(lines)

