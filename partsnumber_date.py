#
# ПОЧЕМУ ЭТО ВООБЩЕ ПРОИСХОДИТ. Когда VIN разрешается однозначно,
# каталог открывается сразу. Когда несколько поставщиков каталогов
# берутся его расшифровать — портал спрашивает, чей брать. Правило,
