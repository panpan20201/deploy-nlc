    def _wait_until_screen_settles(
        self, page: Page, clip: Tuple[int, int, int, int],
        timeout_sec: float, what: str,
    ) -> bool:
        """
        Ждёт, пока указанная область экрана перестанет меняться.

        Используется вместо фиксированной паузы: запас в этом модуле стоит
        везде именно затем, чтобы сайт успел догрузиться, когда он
        тормозит, — а фиксированная пауза это ставка на то, что он всегда
        одинаково быстрый. На быстром прогоне она тратит время зря, на
        медленном не спасает.

        Здесь наоборот: быстрый случай стоит долей секунды, медленный
        получает столько, сколько нужно.

        ВАЖНО, ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЧИТ. Неподвижность — не готовность:
        экран загрузки каталога залит ровным серым, и признак "ничего не
        меняется" срабатывает на нём мгновенно. Поэтому здесь стабилизация — только
        первая половина дела; вторая половина в том, что после набора мы
        ПРОВЕРЯЕМ поле поиска (см. _enter_vin). Один признак отвечает за
        "перестало грузиться", второй — за "ввод действительно дошёл", и
        подменять второй первым нельзя.

        Исчерпание таймаута НЕ считается ошибкой: возможно, на экране
        что-то анимировано постоянно. Возвращаем False, пишем в лог и
        идём дальше — проверка поля всё равно поймает неудачу.
        """
        deadline = time.monotonic() + timeout_sec
        x, y, width, height = clip
        clip_dict = {"x": x, "y": y, "width": width, "height": height}
        last: Optional[Image.Image] = None
        stable_since: Optional[float] = None
        started = time.monotonic()

        while time.monotonic() < deadline:
            current = Image.open(
                io.BytesIO(page.screenshot(clip=clip_dict))
            ).convert("L")

            if last is not None and self._images_similar(last, current):
                if stable_since is None:
                    stable_since = time.monotonic()
                elif time.monotonic() - stable_since >= STABLE_DURATION_SEC:
                    logger.debug(
                        f"{what}: картинка успокоилась за "
                        f"{time.monotonic() - started:.1f} сек."
                    )
                    return True
            else:
                stable_since = None

            last = current
            page.wait_for_timeout(250)

        logger.warning(
            f"{what}: за {timeout_sec:.0f} сек картинка так и не перестала "
            f"меняться. Иду дальше — если ввод не дойдёт, это поймает "
            f"проверка поля поиска."
        )
        return False

    def _vin_field_band_dark(self, page: Page) -> int:
        """Тёмные пиксели в полосе поля — для относительного замера."""
        x, y, x2, y2 = VIN_FIELD_BAND
        shot = page.screenshot(
            clip={"x": x, "y": y, "width": x2 - x, "height": y2 - y}
        )
        gray = Image.open(io.BytesIO(shot)).convert("L")
        return sum(gray.histogram()[:VIN_FIELD_DARK_THRESHOLD])

    def _wait_vin_field_settled(self, page: Page) -> int:
        """
        Дождаться, пока полоса поля перестанет меняться, и вернуть замер.

        Набранный текст доезжает до экрана не мгновенно: нажатия идут в
        браузер, оттуда в Horizon, и удалённая машина их отрисовывает.
        Фиксированная пауза здесь — ставка на то, что канал всегда
        одинаково быстрый; на деле он бывает медленным настолько, что
        молчит и буфер обмена.

        Ждём не время, а СОСТОЯНИЕ: два одинаковых замера подряд означают,
        что отрисовка закончилась. Быстрый канал стоит одного лишнего
        опроса, медленный получает столько, сколько нужно.
        """
        proshlo = 0
        predydushchiy = None
        while proshlo < VIN_FIELD_SETTLE_TIMEOUT_MS:
            tekushchiy = self._vin_field_band_dark(page)
            if tekushchiy == predydushchiy:
                return tekushchiy
            predydushchiy = tekushchiy
            page.wait_for_timeout(VIN_FIELD_SETTLE_POLL_MS)
            proshlo += VIN_FIELD_SETTLE_POLL_MS
        return predydushchiy if predydushchiy is not None else 0

    def _vin_field_dark_pixels(self, page: Page) -> int:
        """
        Сколько тёмных пикселей в поле поиска — то есть набран там текст
        или поле пустое.

        Замер по пяти реальным экранам (в том числе скриншот
        20260826_201948):

            поле ПУСТОЕ (плейсхолдер "Enter VIN/Frame")      9 пикселей
            поле с VIN, окно каталога                      718
            поле с VIN, портал                             780
            поле с VIN, портал (Mercedes)                  938
            поле с VIN, портал (Mercedes, 2-й случай)     2133

        Разрыв в восемьдесят раз — это не подгонка под один скриншот.
        Плейсхолдер светло-серый, набранный текст чёрный, и никакое
        сжатие Blast эту разницу не сотрёт.

        Регион VIN_FIELD_TEXT_REGION подобран так, чтобы попадать внутрь
        поля И на портале, И в окне каталога: поля у них в разных местах,
        но перекрываются, и VIN_INPUT_COORD по той же причине работает в
        обоих окнах.
        """
        x, y, x2, y2 = VIN_FIELD_TEXT_REGION
        shot = page.screenshot(
            clip={"x": x, "y": y, "width": x2 - x, "height": y2 - y}
        )
        gray = Image.open(io.BytesIO(shot)).convert("L")
        # Гистограмма, а не перебор пикселей: то же число, но одним
        # вызовом и без getdata(), объявленного в Pillow устаревшим.
        # histogram()[i] — сколько пикселей яркости i, значит сумма
        # первых VIN_FIELD_DARK_THRESHOLD корзин и есть число тёмных.
        return sum(gray.histogram()[:VIN_FIELD_DARK_THRESHOLD])

    def _read_vin_field_text(self, page: Page) -> str:
        """
        Читает то, что РЕАЛЬНО лежит в поле поиска: клик в поле, Ctrl+A,
        Ctrl+C, чтение буфера. Возвращает "" если прочитать не удалось.

        ЗАЧЕМ ЭТО ВМЕСТО СЧЁТА ТЁМНЫХ ПИКСЕЛЕЙ (разбор по скриншоту
        20260827_195859).

        Счёт тёмных пикселей в прямоугольнике VIN_FIELD_TEXT_REGION =
        (390, 36)-(675, 62) на этом скриншоте даёт 108 при пороге 150 —
        поле объявляется пустым. Поле пустым не было — в нём стояло
        "wbajf3100lcd130". Арифметика верна, а вывод нет:

            текст в поле на том экране занимал x = 278..402
            прямоугольник проверки начинается с x = 390

        В прямоугольник попали последние 12 пикселей текста, а остальное
        насчитанное — вообще не поле, а надпись "Mercedes S 450 4MATIC"
        из шапки, она там на x = 613..697.

        ПОЧЕМУ ЭТО НЕ ЧИНИТСЯ СДВИГОМ ПРЯМОУГОЛЬНИКА. Шапка каталога
        рисуется в разном масштабе от сессии к сессии. Замер ширины
        логотипа PARTSNUMBER по всем сохранённым скриншотам каталога:

            323, 315, 296, 279, 278 и 212 пикселей

        При широкой шапке поле стоит на x = 347..620, при узкой — на
        x = 270..570. Прямоугольник, накрывающий оба положения, при
        широкой шапке залезает на логотип (а он тёмный) и будет считать
        "поле заполнено" всегда, в том числе когда оно пустое. То есть
        фиксированный прямоугольник тут не подобрать в принципе, а не
        "подобран неудачно".

        ВТОРАЯ ПРИЧИНА, БОЛЕЕ ВАЖНАЯ. В поле стояло 15 символов из 17:
        набор потерял хвост "85". Счёт пикселей такое не ловит НИКОГДА —
        для него 15 символов и 17 одинаково "не пусто". Попади
        прямоугольник в текст, мы бы уверенно пошли искать чужой VIN и
        получили бы правдоподобный ответ про другую машину. Это хуже
        честного отказа.

        Чтение буфера отвечает на нужный вопрос прямо: что в поле, и то
        ли это, что мы набирали. От масштаба шапки не зависит, обрезание
        ловит.
        """
        def select_field_content() -> None:
            # Клик, пауза на регистрацию фокуса, Ctrl+A. Пауза здесь по
            # той же причине, что и во всём этом файле: Horizon идёт с
            # сетевой задержкой, и Ctrl+A, пришедший раньше, чем поле
            # получило фокус, выделит не поле, а весь экран каталога.
            page.mouse.click(*VIN_INPUT_COORD)
            page.wait_for_timeout(300)
            page.keyboard.press("Control+A")

        text = self._select_drag_and_copy(
            page,
            start=VIN_INPUT_COORD,
            end=VIN_INPUT_COORD,
            select=select_field_content,
            what="поле поиска VIN (Ctrl+A)",
        )
        return (text or "").strip()

    @staticmethod
    def _same_vin(a: str, b: str) -> bool:
        """
        Совпадают ли VIN. Приложение показывает набранное строчными
        буквами, а мы набираем прописными, поэтому сравнение без учёта
        регистра. Пробелы и переводы строк буфер может добавить свои —
        убираем их тоже.
        """
        clean = lambda s: "".join(s.split()).upper()
        return clean(a) == clean(b)

    def _enter_vin(self, page: Page, vin: str) -> None:
        """
        Клик → Ctrl+A → Delete → ввод текста идут с паузами. Причина та
        же, что и с протяжкой мыши для выделения текста (см.
        _select_drag_and_copy) — Horizon-сессия идёт с сетевой задержкой
        и не всегда успевает зарегистрировать одно действие до того, как
        приходит следующее. Без пауз старый VIN в поле не стирается, и
        поиск уходит по старым данным — как будто новый VIN вообще не
        пытались ввести. Отсюда небольшие паузы между шагами и небольшая
        задержка между нажатиями клавиш при наборе текста (параметр delay).

        ПРОВЕРКА РЕЗУЛЬТАТА НАБОРА. Окно каталога, которое только что
        появилось, может ещё не принимать ввод: набор не доезжает вовсе, в
        поле остаётся плейсхолдер "Enter VIN/Frame", а поиск впустую
        отрабатывает полные 45 секунд — и так на каждой попытке шага.
        Поэтому после набора проверяем, что в поле действительно нужный
        VIN, и при неудаче повторяем набор.

        Проверка идёт чтением содержимого поля через буфер обмена, а не
        счётом тёмных пикселей — почему именно, подробно разобрано в
        _read_vin_field_text. Здесь важны два следствия.

        Первое: проверяется ЧТО набрано, а не СКОЛЬКО там тёмного.
        Обрезанный набор ("wbajf3100lcd130" вместо "WBAJF3100LCD13085")
        виден и лечится повтором, а не проходит как исправный с поиском
        чужой машины.

        Второе: три попытки, и все — внутри одной сессии. Так дешевле:
        pipeline на исключении из этого метода закрывает сессию
        PARTSNUMBER целиком и поднимает новую (пауза 3 сек + 15 сек на
        запуск браузера и вход в Horizon), хотя сессия полностью исправна
        — не набрался текст в поле, только и всего. Лишний набор стоит
        трёх секунд, лишняя сессия — двадцати шести.
        """
        logger.debug(f"Ввожу VIN {vin!r} в поле поиска")

        last_seen = ""
        # ⚠️ ЧИТАЕМ ПОЛЕ БУФЕРОМ НЕ БОЛЬШЕ ОДНОГО РАЗА ЗА ВЫЗОВ.
        #
        # Канал буфера Horizon иногда молчит (см. [CLIPBOARD_FAIL], около
        # 8% операций), и каждое молчание стоит CLIPBOARD_SYNC_TIMEOUT_SEC
        # = 20 секунд. Защита CLIPBOARD_MAX_FAILURES_IN_ROW срабатывает
        # только после трёх отказов подряд, то есть без этого ограничения
        # все три попытки набора успевали бы отстоять полный таймаут:
        #
        #     попытка 1   20 с + 1.5 с на метку
        #     попытка 2   20 с + 1.5 с
        #     попытка 3   20 с + 1.5 с
        #     ---------------------------
        #     64.5 секунды на пустом месте
        #
        # Молчание канала — свойство сессии, а не отдельной попытки: если
        # буфер не приехал сейчас, через три секунды он не приедет тоже.
        # Поэтому пробуем прочитать один раз, а дальше в пределах этого
        # вызова работаем по тёмным пикселям.
        clipboard_usable = True

        for attempt in (1, 2, 3):
            page.mouse.click(*VIN_INPUT_COORD)
            page.wait_for_timeout(300)  # дать полю зарегистрировать фокус
            page.keyboard.press("Control+A")
            page.wait_for_timeout(150)
            page.keyboard.press("Delete")
            page.wait_for_timeout(150)
            # Замер ДО набора. Дальше судим по РАЗНИЦЕ, а не по
            # абсолютному числу: посторонние элементы внутри полосы
            # одинаковы на обоих снимках и взаимно уничтожаются, поэтому
            # сдвиг и масштаб окна перестают что-либо значить (см.
            # VIN_FIELD_BAND).
            fon_do_nabora = self._vin_field_band_dark(page)

            page.keyboard.type(vin, delay=50)  # delay между символами — та же причина

            # Ждём СОСТОЯНИЕ, а не время: отрисовка в Horizon отстаёт от
            # набора, и фиксированная пауза была бы ставкой на то, что
            # канал всегда одинаково быстрый.
            posle_nabora = self._wait_vin_field_settled(page)
            pribylo = posle_nabora - fon_do_nabora

            last_seen = self._read_vin_field_text(page) if clipboard_usable else ""

            if self._same_vin(last_seen, vin):
                logger.debug(
                    f"Поле поиска содержит ровно {vin!r} — набор дошёл "
                    f"полностью (попытка {attempt})."
                )
                # Ctrl+A оставил текст выделенным. Снимаем выделение, чтобы
                # следующее действие вызывающего кода (Enter) работало с
                # обычным полем, а не с полностью выделенным.
                page.keyboard.press("End")
                page.wait_for_timeout(100)
                return

            if not last_seen:
                # Буфер молчит (или мы уже знаем, что он молчит) — канал
                # синхронизации Horizon сейчас не работает. Прочитать поле
                # нечем, но это НЕ повод объявлять набор неудачным:
                # откатываемся на проверку по тёмным пикселям. Она
                # слабее (масштаб шапки плавает, обрезание не ловит), но
                # это лучше, чем отказ на ровном месте.
                if clipboard_usable:
                    clipboard_usable = False
                    logger.warning(
                        "Буфер обмена молчит — дальше в этом вводе поле "
                        "читать не пытаюсь, проверяю по тёмным пикселям. "
                        "Повторные попытки чтения стоили бы по 20 секунд "
                        "каждая и ничего бы не дали."
                    )
                # Судим по ПРИБАВКЕ тёмных пикселей, а не по абсолютному
                # числу в области с жёсткими координатами: такая область
                # промахивается мимо поля на смещённом окне и заставляет
                # бота отказаться от уже найденной машины.
                if pribylo >= VIN_FIELD_MIN_DELTA:
                    logger.warning(
                        f"Прочитать поле поиска не удалось (буфер обмена "
                        f"молчит), но полоса поля потемнела на {pribylo} "
                        f"пикселей — значит набор дошёл, иду искать. "
                        f"Проверить, ровно ли там {vin}, сейчас нечем."
                    )
                    return
                logger.warning(
                    f"Прочитать поле поиска не удалось (буфер молчит), и "
                    f"полоса поля потемнела лишь на {pribylo} пикселей при "
                    f"пороге {VIN_FIELD_MIN_DELTA} — набор, похоже, не дошёл. "
                    f"Попытка {attempt} из 3, набираю ещё раз."
                )
            else:
                logger.warning(
                    f"В поле поиска оказалось {last_seen!r} вместо {vin!r}. "
                    f"Попытка {attempt} из 3, набираю ещё раз."
                )

            if attempt < 3:
                page.wait_for_timeout(1500)

        # Три захода не дали в поле нужного VIN. Запускать поиск нет
        # смысла: он либо отработает полный таймаут и вернёт "не нашли",
        # либо — что хуже — найдёт машину по обрезанному VIN. И то, и
        # другое притворилось бы ответом про машину.
        self._dump_debug_screenshot(page, "vin_field_stayed_empty")
        raise PartsNumberSessionError(
            f"VIN {vin} не удалось ввести: после трёх попыток в поле поиска "
            f"{last_seen!r} вместо нужного. Запускать поиск не с чем — это "
            f"техническая неудача, а НЕ ответ про машину. Сохранён скриншот."
        )

    def _run_search(
        self, page: Page, _open_vin_retry: bool = False,
        expected_vin: Optional[str] = None, _group_retry: bool = False,
    ) -> str:
        """
        Запуск поиска клавишей Enter. Запасной способ, если Enter
        перестанет срабатывать, — клик по найденной через template
        matching иконке лупы (см. _click_icon_by_template и
        SEARCH_ICON_REGION).

        ДВА РАЗНЫХ СОСТОЯНИЯ ОШИБКИ, А НЕ ОДНО:

        1) НЕКОРРЕКТНЫЙ ФОРМАТ VIN — красная плашка "Incorrect VIN" в
           правом верхнем углу.

        2) ПРАВИЛЬНЫЙ ФОРМАТ, НО МАШИНЫ НЕТ В БАЗЕ — СОВЕРШЕННО ДРУГОЕ,
           отдельное светлое окно по центру экрана "Information / Vin not
           found" (подтверждено скриншотом). Без этой проверки код шёл бы
           открывать модалку деталей, не нашёл бы иконку ⓘ (она перекрыта
           этим окном) и упал бы с ошибкой. Это и есть ГЛАВНЫЙ ожидаемый
           сценарий "не найдено" в реальной работе бота (VIN'ы из Carmoodo
           всегда правильного формата).

        Возвращает одну из строк:
            "ok"             — результат готов, можно открывать модалку
            "invalid_format" — красная плашка (некорректный формат VIN)
            "catalog_closed" — та же плашка, но после выбора группы:
                               "Access to the catalog is closed"
            "not_found"      — окно "Vin not found" (VIN не в базе)

        ВАЖНО: при любой из двух ошибок область у логотипа (LOGO_AREA_CLIP)
        может вообще НЕ измениться — там остаются данные ПРЕДЫДУЩЕГО
        успешного поиска (подтверждено на реальном скриншоте: в поле у
        логотипа виден VIN и модель машины из предыдущего запроса).
        Поэтому нельзя полагаться только на стабилизацию этой области —
        оба типа ошибки проверяются на каждой итерации параллельно со
        стабилизацией, а не последовательно.
        """
        x, y, width, height = LOGO_AREA_CLIP
        clip_dict = {"x": x, "y": y, "width": width, "height": height}

        # ⚠️ ПРИЗНАКИ ГОТОВНОСТИ НИЖЕ НЕ ПРИВЯЗАНЫ К НАШЕМУ ЗАПРОСУ.
        #
        # Пример (VIN KLAPD56LDTB195159):
        #
        #     в поле поиска    klapd56ldtb195159   (наш VIN, набран верно)
        #     в шапке          BMW 520d 17.03.2017
        #     во вкладке       BMW
        #     в крошках        Models > WBAJC3107HG923605 > 25-gearshift
        #
        # Окно каталога может стоять ГЛУБОКО ВНУТРИ каталога чужой машины
        # из прошлого запроса. Наш VIN набрался, Enter нажался, а каталог
        # не переключился — и все признаки готовности выполняются
        # МГНОВЕННО, потому что выполняет их чужая страница: иконка ⓘ на
        # месте (она BMW-шная), область у логотипа неподвижна (она просто
        # не менялась). Такой случай ловит проверка "ПОДМЕНА ДАННЫХ" в
        # get_vehicle_card по настоящему VIN из карточки; почему здесь нет
        # отдельного признака «шапка сменилась» — см. комментарий у
        # return "ok" ниже.
        #
        logger.debug("Запускаю поиск (Enter)")
        page.keyboard.press("Enter")
        # Если Enter перестанет срабатывать — запасной путь: клик по лупе
        # через _click_icon_by_template(SEARCH_ICON_TEMPLATE_PATH,
        # SEARCH_ICON_REGION).

        deadline = time.monotonic() + SEARCH_TIMEOUT_SEC
        last_image: Optional[Image.Image] = None
        stable_since: Optional[float] = None

        while time.monotonic() < deadline:
            if self._region_is_error_banner(page):
                if _group_retry:
                    # Пример — VIN KNMK5B2RMNP032028, Renault XM3 (см.
                    # tests/fixtures/evidence/20261001_182734_renault_catalog_closed.png).
                    # Та же красная плашка в том же месте, но текст другой:
                    # "Access to the catalog is closed". По цвету их не
                    # различить, по моменту — да: экран выбора группы каталог
                    # показывает только для VIN, который он уже распознал,
                    # так что после выбора группы "Incorrect VIN" быть не
                    # может. Это ответ "марка не входит в наш доступ", и
                    # повтор его не изменит.
                    logger.info(
                        "После выбора группы — красная плашка: каталог этой "
                        "марки закрыт для нашего доступа PARTSNUMBER."
                    )
                    return "catalog_closed"
                logger.debug("Обнаружена красная плашка 'Incorrect VIN' (некорректный формат)")
                return "invalid_format"

            if self._region_is_not_found_popup(page):
                # ЦВЕТ — ТОЛЬКО ПРЕДПОЛОЖЕНИЕ, ЕМУ НУЖНО ПОДТВЕРЖДЕНИЕ.
                #
                # Замер на реальном скриншоте (20260822_165402, VIN
                # KPBPH3AT1PP011988, SsangYong):
                #
                #     эталон окна "Vin not found": (228, 242, 255)
                #     фактический фон страницы:    (244, 249, 254)
                #     расстояние по каналам:       [16, 7, 1]
                #     допуск в коде:                25
                #
                # То есть обычная страница результата отличается от эталона
                # максимум на 16 при допуске 25 — по одному цвету эти два
                # состояния не различить В ПРИНЦИПЕ. Цвет срабатывает не
                # когда есть окно, а когда в точке (860, 415) случайно
                # оказывается светлый фон, — а это зависит от того,
                # насколько длинные названия узлов у конкретной марки и
                # докуда дотягивается список.
                #
                # Цена ошибки максимальная: человек получил бы "машина не
                # найдена в каталоге" про машину, которая там есть.
                #
                # ПОЧЕМУ НЕ ПРОСТО СУЗИТЬ ДОПУСК. Потому что 16 против 25 —
                # это не "чуть промахнулись с числом", а отсутствие запаса
                # вообще: подгонка допуска под один скриншот сломается на
                # следующем бренде. Нужен признак другой природы, а не
                # более точный порог.
                #
                # ПОДТВЕРЖДЕНИЕ. Берём признак, который описан в этом
                # файле как надёжный и НЕ зависящий от марки: иконка ⓘ есть
                # на ЛЮБОЙ странице результата, а окно "Vin not found" её
                # перекрывает. Значит: иконка видна — окна нет, цвет
                # обманул. Иконки нет — окно действительно на экране.
                #
                # Проверка стоит одного поиска по эталону и выполняется
                # только когда цвет уже сработал, то есть на обычный ход
                # работы не влияет.
                if find_icon_on_screenshot(
                    page.screenshot(),
                    INFO_ICON_TEMPLATE_PATHS,
                    search_region=INFO_ICON_REGION,
                ) is not None:
                    logger.debug(
                        "Цвет в области окна 'Vin not found' совпал, но иконка ⓘ "
                        "на месте — значит, окна нет и это ложное срабатывание "
                        "по цвету. Продолжаю ждать результат."
                    )
                else:
                    logger.debug(
                        "Обнаружено окно 'Information / Vin not found' "
                        "(совпал цвет И пропала иконка ⓘ)"
                    )
                    return "not_found"

            current_bytes = page.screenshot(clip=clip_dict)
            current_image = Image.open(io.BytesIO(current_bytes)).convert("L")

            if last_image is not None and self._images_similar(last_image, current_image):
                if stable_since is None:
                    stable_since = time.monotonic()
                elif time.monotonic() - stable_since >= STABLE_DURATION_SEC:
                    # НЕПОДВИЖНОСТЬ — ЕЩЁ НЕ ГОТОВНОСТЬ: как и цвет окна
                    # "Vin not found", этот признак выполняется не только в
                    # нужном состоянии.
                    #
                    # Пример (VIN KMTGC41DBNU118311, скриншот
                    # 20260822_180959): каталог ещё ГРУЗИТСЯ — экран залит
                    # ровным серым, посередине три точки, в заголовке
                    # вкладки вообще предыдущий VIN. Область у логотипа при
                    # этом неподвижна ИДЕАЛЬНО — она же просто однотонная.
                    # По одной неподвижности поиск объявили бы завершённым,
                    # иконки ⓘ не нашли бы, и человек получил бы "машина не
                    # найдена в каталоге" про машину, которая там есть.
                    #
                    # Отсюда правило: решение нельзя принимать по
                    # ОТСУТСТВИЮ чего-либо (изменений, цвета, элемента) —
                    # нужен ПОЛОЖИТЕЛЬНЫЙ признак, который бывает только в
                    # нужном состоянии.
                    #
                    # Такой признак описан в этом файле как не зависящий от
                    # марки: иконка ⓘ. Она есть на любой
                    # странице результата и её заведомо нет ни на экране
                    # загрузки, ни на каталоге марок. Её же мы обязаны найти
                    # следующим шагом — то есть проверка не добавляет
                    # отдельной работы, просто переносится на шаг раньше,
                    # где ещё есть время подождать.
                    if find_icon_on_screenshot(
                        page.screenshot(),
                        INFO_ICON_TEMPLATE_PATHS,
                        search_region=INFO_ICON_REGION,
                    ) is not None:
                        # ⚠️ ПОЧЕМУ НЕТ ТРЕТЬЕГО ПРИЗНАКА «ШАПКА ОБЯЗАНА
                        # СМЕНИТЬСЯ».
                        #
                        # Оба признака выше — неподвижность и иконка ⓘ —
                        # описывают состояние СТРАНИЦЫ ВООБЩЕ, а не то, наш
                        # ли на ней результат: чужая страница из прошлого
                        # запроса удовлетворяет им обоим мгновенно (см.
                        # пример с VIN KLAPD56LDTB195159 в начале метода).
                        # Напрашивается признак, привязанный к НАШЕМУ
                        # запросу, — смена шапки. Но он неверен.
                        #
                        # Когда ту же машину проверяют повторно, каталог
                        # УЖЕ стоит на ней с прошлого раза, шапка законно не
                        # меняется — и такой признак держал бы поиск все 45
                        # секунд, хотя иконка ⓘ на месте (совпадение
                        # 1.000), в крошках нужный VIN, в шапке нужная
                        # машина. Всё готово с первой секунды.
                        #
                        # Оговорка «тот же VIN, что и в прошлый раз» не
                        # спасает: запомненный VIN живёт внутри сессии
                        # Playwright и обнуляется при её пересоздании, тогда
                        # как окно каталога на удалённой машине переживает
                        # любые пересоздания.
                        #
                        # И он лишний: задачу «на экране чужая машина»
                        # решает проверка «ПОДМЕНА ДАННЫХ» — она сравнивает
                        # НАСТОЯЩИЕ VIN'ы из карточки, а не пиксели шапки.
                        #
                        # Правило с другой стороны: признак должен быть не
                        # только положительным, но и выполнимым во ВСЕХ
                        # законных состояниях. «Шапка сменилась» —
                        # положительный признак, но в законном случае
                        # повторной проверки той же машины он невыполним.
                        logger.debug(
                            "Область у логотипа стабилизировалась И иконка ⓘ "
                            "на месте — результат готов"
                        )
                        return "ok"
                    logger.debug(
                        "Область у логотипа неподвижна, но иконки ⓘ нет — "
                        "похоже, страница ещё грузится (серый экран с "
                        "точками неподвижен не хуже готового результата). "
                        "Продолжаю ждать."
                    )

                    # ЭКРАН "Open VIN" — ВОССТАНОВЛЕНИЕ ПОСЛЕ ПЕРЕЗАГРУЗКИ
                    # СЕРВЕРА PARTSNUMBER.
                    #
                    # Экран "Open VIN" статичен — на нём ничего не движется,
                    # но иконки ⓘ на нём нет, поэтому "ok" он не даёт. Без
                    # этой проверки поиск ждал бы свои 45 секунд и падал бы
                    # по таймауту, не дойдя до восстановления в
                    # get_vehicle_card.
                    #
                    # Поэтому экран проверяется прямо здесь — там, где мы и
                    # обнаружили, что готовности нет, — и опознаётся прямо,
                    # по своей собственной кнопке, а не задним числом по
                    # отсутствию иконки.
                    #
                    # Проверка стоит скриншота и поиска по эталону, и
                    # выполняется только когда экран замер без иконки. На
                    # обычной работе (иконка появилась) в эту ветку вообще
                    # не заходим.
                    if not _open_vin_retry and self._recover_from_open_vin_screen(page):
                        logger.info(
                            "Во время ожидания результата обнаружен экран "
                            "'Open VIN' — сервер PARTSNUMBER, похоже, "
                            "перезагружался. Кнопка нажата, поиск нужно "
                            "повторить с самого начала."
                        )
                        return "open_vin_screen"

                    # Сбрасываем отсчёт, иначе следующая же итерация снова
                    # сочтёт область "стабильной уже давно" и мы будем
                    # дёргать поиск иконки на каждом обороте цикла.
                    stable_since = None
            else:
                stable_since = None

            last_image = current_image
            page.wait_for_timeout(int(POLL_INTERVAL_SEC * 1000))

        # ⚠️ ПЕРЕД ТЕМ КАК СДАТЬСЯ — ПРОВЕРИТЬ ЭКРАН ВЫБОРА ГРУППЫ.
        #
        # Иконка ⓘ не появилась не всегда потому,
        # что "каталог грузился дольше обычного": бывает, что каталог
        # ждёт от нас выбора группы производителя и без ответа не
        # двинется никогда (разбор — у VIN_WMI_TO_GROUP).
        #
        # Проверка стоит здесь, а не внутри цикла, намеренно. Внутри цикла
        # она шла бы на каждом обороте ожидания, то есть поиск по эталону
        # десятки раз за секунду на нормально грузящейся странице. Здесь
        # же мы уже точно знаем, что обычным путём результат не пришёл, и
        # цена одной проверки ничтожна на фоне 45 отработанных секунд.
        #
        # Повтор ровно один: флаг _group_retry не даёт зациклиться, если
        # после выбора группы экран снова окажется тем же.
        if not _group_retry and expected_vin and self._select_catalog_group(page, expected_vin):
            logger.info(
                "Группа производителя выбрана — жду результат поиска заново."
            )
            return self._run_search(
                page, _open_vin_retry=_open_vin_retry,
                expected_vin=expected_vin, _group_retry=True,
            )

        # Прежде чем валить всё на медленную загрузку — посмотреть, не
        # ответил ли каталог ТАБЛИЦЕЙ из нескольких строк на один VIN.
        #
        # Пример — скриншот
        # debug_screenshots/20260914_172806_search_timeout.png (VIN
        # WDBEA22D1RC131656, Mercedes W124): каталог нашёл машину и выдал
        # ДВЕ записи с ОДИНАКОВЫМ VIN — разные разделы каталога на одну
        # машину, а не разные машины. Иконки ⓘ в таком виде нет, и без
        # этой проверки шаг падал бы с сообщением про медленную загрузку,
        # то есть с НЕВЕРНОЙ причиной: человек шёл бы проверять сеть.
        if self._looks_like_multirow_result(page):
            self._dump_debug_screenshot(page, "multirow_result")
            raise PartsNumberSessionError(
                "Каталог нашёл машину, но выдал НЕСКОЛЬКО записей на один "
                "VIN — это разные разделы каталога, а не разные машины. "
                "Выбрать нужный автоматически пока нечем: у Horizon нет "
                "структуры страницы, только картинка, а привязываться к "
                "координатам строк нельзя — высота строки зависит от длины "
                "описания. Сохранён скриншот. Это техническая неудача, а НЕ "
                "ответ 'машины нет в каталоге'."
            )

        self._dump_debug_screenshot(page, "search_timeout")
        raise PartsNumberSessionError(
            f"Таймаут ({SEARCH_TIMEOUT_SEC}с) ожидания результата поиска VIN: "
            f"страница так и не дошла до состояния, где видна иконка ⓘ. "
            f"Это техническая неудача, а не ответ 'машины нет в каталоге' — "
            f"сохранён скриншот. Если на нём каталог просит выбрать группу "
            f"производителя, значит для этой марки не хватает эталона "
            f"надписи (см. CATALOG_GROUP_TEMPLATES)."
        )

    def _looks_like_multirow_result(self, page: Page) -> bool:
        """
        Ответил ли каталог таблицей результатов (шапка vin / name / note).

        Отличить это от «страница не догрузилась» важно не ради красоты:
        сообщения ведут человека в разные стороны. «Каталог грузился
        дольше обычного» отправляет проверять сеть, а «каталог вернул
        несколько записей» — открывать машину руками.
        """
        try:
            return find_icon_on_screenshot(
                page.screenshot(), [VIN_RESULT_TABLE_TEMPLATE]
            ) is not None
        except Exception as exc:
            logger.debug("Проверить таблицу результатов не удалось: %s", exc)
            return False

    def _is_on_portal_screen(self, page: Page) -> bool:
        """
        Стоим ли мы на ПОРТАЛЕ (а не в окне каталога).

        Признак — яркость боковой панели, см. разбор у
        PORTAL_SIDEBAR_REGION. Приём тот же, что в
        _region_is_not_found_popup: маленький клип и средний цвет, без
        поиска по эталону — панель сплошная, шаблону тут не за что
        зацепиться, а яркость различает состояния с огромным запасом.
        """
        x, y, width, height = PORTAL_SIDEBAR_REGION
        try:
            shot = page.screenshot(
                clip={"x": x, "y": y, "width": width, "height": height}
            )
        except Exception as exc:
            # Не смогли посмотреть — значит, не знаем. Отвечаем "не
            # портал", чтобы не запускать вход в каталог вслепую: лишний
            # заход стоит двух кликов не туда, а обычный путь дальше сам
            # упрётся в понятную ошибку.
            logger.debug(f"Не удалось снять боковую панель: {exc}")
            return False

        image = Image.open(io.BytesIO(shot)).convert("RGB")
        r, g, b = image.resize((1, 1)).getpixel((0, 0))
        brightness = (r + g + b) / 3
        on_portal = brightness < PORTAL_SIDEBAR_MAX_BRIGHTNESS
        logger.debug(
            f"Боковая панель: RGB({r},{g},{b}), яркость {brightness:.1f} "
            f"(порог {PORTAL_SIDEBAR_MAX_BRIGHTNESS}) — "
            f"{'ПОРТАЛ' if on_portal else 'не портал'}."
        )
        return on_portal

    def _ensure_catalog_window(self, page: Page) -> bool:
        """
        Убеждается, что открыто окно каталога, а не портал. Если мы на
        портале — заходит в FAVOURITES и открывает сохранённый каталог.

        ЗАЧЕМ ЭТО ДЕЛАЕТСЯ ЗАРАНЕЕ, А НЕ ПО ФАКТУ ОШИБКИ. Поиск на
        портале не падает — он честно отрабатывает и возвращает список
        каталогов. Отличить это от "ещё грузится" можно только по
        отсутствию иконки ⓘ, то есть выждав полный таймаут в 45 секунд, и
        так дважды. Проверка тут стоит одного маленького скриншота и
        снимает полторы минуты ожидания на каждом таком запросе.

        Приложение откатывается на портал само, если запросов долго не
        было, — поэтому проверять надо перед КАЖДЫМ поиском, а не один
        раз при создании сессии.

        Возвращает True, если в итоге мы в окне каталога.
        """
        if not self._is_on_portal_screen(page):
            return True

        logger.info(
            "Открыт портал PARTSNUMBER, а не окно каталога (так бывает, если "
            "запросов долго не было). Поиск по VIN здесь вернул бы список "
            "каталогов вместо карточки — захожу в каталог через FAVOURITES."
        )

        self._click_deliberately(page, *FAVOURITES_TAB_COORD)
        page.wait_for_timeout(800)
        self._click_deliberately(page, *FAVOURITE_ENTRY_COORD)

        # Окно каталога открывается не мгновенно — ждём смены экрана,
        # опрашивая, а не засыпая на фиксированное время: на быстрой
        # машине это сэкономит секунды, на медленной не сломается.
        for _ in range(20):
            page.wait_for_timeout(500)
            if not self._is_on_portal_screen(page):
                # ⚠️ ОКНО ПОЯВИЛОСЬ — ЭТО ЕЩЁ НЕ «ОНО ГОТОВО».
                #
                # Сразу после смены яркости окно уже перекрывает портал,
                # но ввод ещё не принимает: набор VIN в этот момент уходит
                # в пустоту, поле остаётся пустым, и поиск отрабатывает
                # полные 45 секунд впустую.
                #
                # Ждём НЕ фиксированную паузу, а пока картинка перестанет
                # меняться. Фиксированная пауза — это ставка на то, что
                # сайт всегда одинаково быстрый: на быстром прогоне она
                # тратит время зря, на медленном не спасает. Здесь же
                # быстрый случай стоит долей секунды, а медленный получает
                # столько времени, сколько нужно, вплоть до
                # CATALOG_RENDER_TIMEOUT_SEC.
                self._wait_until_screen_settles(
                    page,
                    CATALOG_CONTENT_CLIP,
                    CATALOG_RENDER_TIMEOUT_SEC,
                    "содержимое окна каталога",
                )
                logger.info("Окно каталога открыто — можно искать по VIN.")
                return True

        # ⚠️ УСПЕХ ПОДТВЕРЖДАЕТСЯ ПРОВЕРКОЙ ЭКРАНА, а не тем, что клики
        # не бросили исключения. Если мы всё ещё на портале — значит,
        # кликнули не туда (например, в FAVOURITES появилась вторая
        # запись, и первой строкой стала не та). Скриншот покажет это
        # сразу.
        logger.warning(
            "После захода в FAVOURITES экран всё ещё портальный. Возможно, в "
            "избранном теперь больше одной записи и первая строка — не та. "
            "Сохраняю скриншот."
        )
        self._dump_debug_screenshot(page, "favourites_did_not_open_catalog")
        return False

    def _select_catalog_group(self, page: Page, vin: str) -> bool:
        """
        На экране выбора группы производителя жмёт нужную группу.

        Возвращает True, если клик сделан. False — если это не тот экран,
        группа по VIN неизвестна или эталона для неё нет.

        Разбор и обоснование — у VIN_WMI_TO_GROUP. Коротко: марка берётся
        из первых трёх символов VIN (WMI, стандарт ISO 3780), а положение
        нужной надписи на экране — поиском по эталону.

        ⚠️ НЕ УГАДЫВАЕТ. Если группу определить нельзя или эталона нет,
        функция ничего не нажимает и честно возвращает False. Ткнуть
        наугад здесь означало бы открыть каталог ЧУЖОЙ марки и получить
        правдоподобную карточку не той машины — то есть ровно тот вид
        ошибки, который в этом проекте дороже всего.
        """
        wmi = (vin or "")[:3].upper()
        group = VIN_WMI_TO_GROUP.get(wmi)

        if group is None:
            logger.warning(
                f"На экране, похоже, выбор группы каталога, но марку по "
                f"началу VIN ({wmi}) определить не могу. Нажимать наугад не "
                f"буду: откроется каталог чужой марки. Добавь '{wmi}' в "
                f"VIN_WMI_TO_GROUP."
            )
            return False

        template = CATALOG_GROUP_TEMPLATES.get(group)
        if template is None or not os.path.exists(template):
            logger.warning(
                f"Группу по VIN определил ({group}), но эталона надписи для "
                f"неё нет. Сохраняю скриншот: вырежи из него надпись группы "
                f"и положи как templates/template_group_{group}.png, после "
                f"чего эта марка заработает."
            )
            self._dump_debug_screenshot(page, f"catalog_group_no_template_{group}")
            return False

        coords = find_icon_on_screenshot(page.screenshot(), [template])
        if coords is None:
            logger.debug(
                f"Надписи группы '{group}' на экране нет — значит, это не "
                f"экран выбора группы."
            )
            return False

        logger.info(
            f"Экран выбора группы производителя: VIN начинается на {wmi}, "
            f"значит нужна группа '{group}'. Нажимаю её в {coords}."
        )
        self._click_deliberately(page, *coords)
        return True

    def _region_is_not_found_popup(self, page: Page) -> bool:
        """
        Проверяет, показывает ли область VIN_NOT_FOUND_POPUP_REGION светлое
        окно "Information / Vin not found" — по среднему цвету небольшого
        участка ЗАВЕДОМО ВНУТРИ окна (см. пояснение у константы), тем же
        принципом, что и _region_is_error_banner, но с другим цветом и
        другой областью экрана.
        """
        x, y, width, height = VIN_NOT_FOUND_POPUP_REGION
        screenshot_bytes = page.screenshot(
            clip={"x": x, "y": y, "width": width, "height": height}
        )
        image = Image.open(io.BytesIO(screenshot_bytes)).convert("RGB")
        avg_r, avg_g, avg_b = image.resize((1, 1)).getpixel((0, 0))

        target_r, target_g, target_b = VIN_NOT_FOUND_POPUP_BG_COLOR
        is_match = (
            abs(avg_r - target_r) <= VIN_NOT_FOUND_POPUP_COLOR_TOLERANCE
            and abs(avg_g - target_g) <= VIN_NOT_FOUND_POPUP_COLOR_TOLERANCE
            and abs(avg_b - target_b) <= VIN_NOT_FOUND_POPUP_COLOR_TOLERANCE
        )
        if is_match:
            logger.debug(
                f"Цвет области попапа 'Vin not found': RGB({avg_r},{avg_g},{avg_b}) "
                f"— похоже на окно 'не найдено'"
            )
        return is_match

