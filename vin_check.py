"""
Проверка VIN, пришедшего с Encar, без обращения к планшету.

ЗАЧЕМ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ. Carmoodo стоит около 45 секунд на каждой
проверке (замер: медиана 29 с, p90 43 с) и расходует дневной лимит в 30
запросов. При этом сверка Encar с Carmoodo на реальных объявлениях
показала: из 78 объявлений, где Encar отдал полный VIN, он совпал с
Carmoodo во ВСЕХ 78 случаях. Ни одного чужого VIN.

Все отклонения Encar оказались двух видов — VIN отсутствует (4 случая) и
VIN обрезан до 8 символов (1 случай). Оба ловятся формально, без второго
источника. Поэтому VIN с Encar принимается, если прошёл проверки; Carmoodo остаётся запасным путём для остальных случаев.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И НА КАКОМ ОСНОВАНИИ.

Замер по боевой базе (115 VIN) разделил машины надвое:

    контрольный разряд сошёлся   — 53 из 53: BMW (18), Mercedes (15),
                                   Audi (5), MINI (4), Jeep (2),
                                   Toyota (2), VW, Porsche, Land Rover;
    не сошёлся                   — 61 из 61: Kia (27), Hyundai (13),
                                   GM Korea (9), Genesis (5) и прочие
                                   корейские.

У машин внутреннего корейского рынка девятая позиция VIN не является
контрольным разрядом. Требовать его от них означало бы отправлять в
Carmoodo больше половины потока — то есть не получить выигрыша вовсе.

Отсюда правило: контрольный разряд ОБЯЗАН сойтись у всех, кроме VIN,
начинающихся на "K". Не сошёлся у импортной машины — отказ в безопасную
сторону, в Carmoodo.

⚠️ ЧЕГО ЭТА ПРОВЕРКА НЕ ЛОВИТ — сказано прямо, чтобы никто не считал её
гарантией. Перебор всех 27136 одиночных опечаток в 53 VIN с рабочим
разрядом: ловится 92.8%. Остальные 7.2% — замены букв внутри одной группы
кодирования (A и J обе дают 1, B/K/S дают 2, и так далее), они не меняют
контрольную сумму в принципе. Из них по-настоящему слепая зона — 2.6%:
опечатки в серийной части (позиции 12-17), дающие соседнюю машину той же
модели, года и завода. Опечатки в позициях марки, модели и года видны по
расхождению с объявлением.

Стопроцентной гарантии формальная проверка дать не может ни при каком
устройстве: у корейских и европейских VIN нет избыточности, достаточной
для этого. Единственный стопроцентный способ — второй независимый
источник, то есть Carmoodo. Это осознанный размен, а не недосмотр.
"""
from typing import Optional, Tuple

# Перевод символов VIN в числа для контрольной суммы (ISO 3779).
# Буквы I, O и Q в VIN не используются вовсе: их путают с 1 и 0.
_TRANSLIT = {
    **{str(d): d for d in range(10)},
    **dict(zip("ABCDEFGH", [1, 2, 3, 4, 5, 6, 7, 8])),
    **dict(zip("JKLMNP", [1, 2, 3, 4, 5, 7])),
    **dict(zip("RSTUVWXYZ", [9, 2, 3, 4, 5, 6, 7, 8, 9])),
}

# Веса позиций. Девятая (индекс 8) — сам контрольный разряд, её вес 0.
_WEIGHTS = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2]

VIN_LENGTH = 17
FORBIDDEN_LETTERS = ("I", "O", "Q")

# Префиксы, у которых контрольного разряда нет. Сейчас это весь корейский
# внутренний рынок: KNA, KMH, KLA, KMT, KMJ, KPB, KMF, KNM — все на "K".
# Проверяем по первой букве, а не списком: список пришлось бы пополнять
# при каждой новой марке, и забытая марка молча уезжала бы в Carmoodo.
NO_CHECK_DIGIT_PREFIX = "K"


def normalize(vin: Optional[str]) -> Optional[str]:
    """Привести VIN к виду для сравнения: верхний регистр, без пробелов."""
    if not vin:
        return None
    cleaned = "".join(vin.split()).upper()
    return cleaned or None


def check_digit_ok(vin: str) -> bool:
    """
    Сходится ли контрольный разряд (девятая позиция).

    Ложь означает либо опечатку, либо машину рынка, где этот разряд не
    используется. Различать эти два случая — забота is_usable().
    """
    vin = normalize(vin) or ""
    if len(vin) != VIN_LENGTH:
        return False
    try:
        total = sum(_TRANSLIT[c] * w for c, w in zip(vin, _WEIGHTS))
    except KeyError:
        return False
    remainder = total % 11
    return vin[8] == ("X" if remainder == 10 else str(remainder))


def is_usable(vin: Optional[str]) -> Tuple[bool, str]:
    """
    Можно ли принять этот VIN с Encar, не обращаясь к Carmoodo.

    :return: (годен, причина отказа). При годном VIN причина пустая.
    """
    cleaned = normalize(vin)
    if not cleaned:
        return False, "Encar не показал VIN"

    if len(cleaned) != VIN_LENGTH:
        return False, (f"длина {len(cleaned)}, а VIN обязан быть {VIN_LENGTH} "
                       f"символов — похоже на обрезок")

    for letter in FORBIDDEN_LETTERS:
        if letter in cleaned:
            return False, (f"в VIN есть буква {letter}, которой в VIN не "
                           f"бывает — строку набирали руками")

    unknown = [c for c in cleaned if c not in _TRANSLIT]
    if unknown:
        return False, f"недопустимые символы: {''.join(sorted(set(unknown)))}"

    # Корейский внутренний рынок: контрольного разряда нет, требовать его
    # бессмысленно — см. замер в шапке модуля.
    if cleaned.startswith(NO_CHECK_DIGIT_PREFIX):
        return True, ""

    if not check_digit_ok(cleaned):
        return False, ("контрольный разряд не сошёлся — для машины этой "
                       "марки он обязателен, значит в VIN ошибка")

    return True, ""
