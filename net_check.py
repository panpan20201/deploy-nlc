"""
Быстрая проверка связи с каталогом PARTSNUMBER.

ЗАЧЕМ ЭТОТ МОДУЛЬ. Вот как выглядит в логе проверка, во время которой
пропал интернет (метка 8af520):

    21:22:18  Шаг PARTSNUMBER: попытка 1/2
    21:24:29  попытка 1 не удалась — «Логотип PARTSNUMBER не появился
              за 60.0с после входа в Horizon-сессию»
    21:24:32  попытка 2/2

Сто тридцать одна секунда на первую попытку и столько же на вторую.
Система не зависла — она честно отработала свои таймауты. Но чтобы
УЗНАТЬ об отсутствии связи, ей понадобилось больше четырёх минут, и для
человека, который ждёт ответа, это неотличимо от зависания.

Факт «до каталога не достучаться» при этом устанавливается попыткой
соединения за доли секунды.

⚠️ ПРОВЕРКА АСИММЕТРИЧНА, И ЭТО ВАЖНО ПОНИМАТЬ ПРАВИЛЬНО.

Успешное соединение НИЧЕГО НЕ ОБЕЩАЕТ. Бывало, что TCP до этого же хоста
открывался прекрасно, DNS резолвился, а страница входа грузилась со
скоростью 18 КБ/с — при 2.4 МБ обязательных скриптов шаг всё равно не
успевал за минуту. Поэтому «связь есть» не меняет ход работы ни на шаг:
дальше всё идёт обычным порядком, со всеми штатными проверками.

А вот «связи нет» — надёжный признак того, что тратить две минуты
незачем. Только ради этого случая модуль и существует.
"""
import logging
import os
import socket
from urllib.parse import urlparse

logger = logging.getLogger(__name__)

# Сколько ждать соединения. Смысл всей затеи — узнать БЫСТРО, поэтому
# таймаут заметно меньше таймаутов самих шагов (60 секунд у PARTSNUMBER):
# иначе проверка сама стала бы тем, от чего спасает.
PROBE_TIMEOUT_SEC = 4.0

DEFAULT_CATALOG_URL = "https://login.partsnumber.com/"


def catalog_host() -> str:
    """
    Хост каталога — тот самый, к которому пойдёт шаг PARTSNUMBER.

    Проверять надо именно его, а не «интернет вообще»: бывало, что
    интернет работал (Cloudflare отдавал 723 КБ/с), а путь до каталога
    еле дышал на 18 КБ/с. Проверка «есть ли сеть» сказала бы «есть» и
    ничем бы не помогла.
    """
    url = os.getenv("PARTSNUMBER_LOGIN_URL") or DEFAULT_CATALOG_URL
    host = urlparse(url).hostname
    return host or urlparse(DEFAULT_CATALOG_URL).hostname


def host_reachable(host: str, port: int = 443,
                   timeout: float = PROBE_TIMEOUT_SEC) -> bool:
    """
    Открывается ли соединение с хостом.

    Ошибка любого рода означает «нет»: и отказ соединения, и молчащий
    DNS (пропавший интернет чаще всего выглядит именно так —
    getaddrinfo failed), и превышение таймаута.
    """
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except Exception as exc:
        logger.info("Хост %s недоступен (%s).", host, exc)
        return False


def catalog_reachable() -> bool:
    """Достучаться ли сейчас до каталога PARTSNUMBER."""
    return host_reachable(catalog_host())
