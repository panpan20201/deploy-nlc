async def _recover_heydealer_limit() -> bool:
    """
    Пытается снять дневной лимит HeyDealer сбросом рекламного
    идентификатора Google.

    ПОЧЕМУ ЭТО ВООБЩЕ РАБОТАЕТ: лимит в 10 проверок HeyDealer привязывает
    к рекламному ID устройства — проверено на живом планшете (очистка
    данных и переустановка приложения лимит не снимали, а сброс
    идентификатора снял).

    Вызывается ТОЛЬКО изнутри лока планшета: сброс идёт тапами по
    настройкам Google, и наложение на идущий сценарий сломало бы оба.

    Сессии на планшете закрываются перед сбросом обязательно: приложения
    читают идентификатор при запуске и держат в памяти, поэтому без
    перезапуска HeyDealer продолжил бы работать со старым значением и
    лимит остался бы на месте.

    :return: True, если сброс выполнен и повтор шага имеет смысл
    """
    allowed, why = usage.can_reset_ads()
    if not allowed:
        logger.warning("Сброс рекламного ID не выполняю: %s.", why)
        return False

    logger.info("Исчерпан лимит HeyDealer — пробую снять его сбросом рекламного ID.")
    await close_device_sessions("сброс рекламного ID")

    success, message = await asyncio.to_thread(ads_id.reset_advertising_id, ANDROID_UDID)
    if not success:
        logger.error("Сброс рекламного ID не удался: %s", message)
        return False

    count = usage.record_ads_reset()
    # Сообщаем модулю HeyDealer, что следующая сессия стартует после
    # сброса: после него приложение считает устройство новым и показывает
    # экраны первого запуска, но НЕ мгновенно. Без этого признака проверка
    # онбординга успевает пройти до появления экрана согласия и уходит
    # ждать нижнюю навигацию — 45 секунд впустую и пересоздание сессии
    # (подтверждено логом, см. разбор в heydealer_history).
    heydealer_history.expect_onboarding_next_session()
    logger.info("Сброс выполнен (%d из %d за сутки) — повторяю шаг HeyDealer. "
                "Следующая сессия будет ЖДАТЬ экран согласия с условиями.",
                count, usage.MAX_ADS_RESETS_PER_DAY)
    return True


async def _run_partsnumber_step(vin: str, deadline: float) -> StepResult:
    """
    PARTSNUMBER под собственным локом — чтобы два РАЗНЫХ запроса не полезли
    в одну Horizon-сессию одновременно. С планшетом он не пересекается и
    работает параллельно с HeyDealer.
    """
    async with _partsnumber_lock:
        # БЫСТРАЯ ПРОВЕРКА СВЯЗИ ПЕРЕД ДОРОГИМ ШАГОМ.
        #
        # Без неё при пропавшем интернете шаг честно отрабатывает свои
        # таймауты — 131 секунда на попытку, 262 на обе (замер на реальном
        # случае). Чтобы УЗНАТЬ об отсутствии связи, нужно больше четырёх
        # минут, а человек всё это время ждёт ответа. Соединение же не
        # открывается за доли секунды.
        #
        # ⚠️ Проверка асимметрична: «связь есть» НИЧЕГО не обещает и ход
        # работы не меняет (бывает, что TCP открывается, а страница
        # грузится со скоростью 18 КБ/с и всё равно не успевает). Значим
        # только отказ.
        if not await asyncio.to_thread(net_check.catalog_reachable):
            logger.warning(
                "До каталога PARTSNUMBER нет связи — не трачу две минуты на "
                "попытки. Проверил за доли секунды вместо 131 (см. net_check)."
            )
            return StepResult(
                "error",
                reason="no_network",
                message=("нет связи с каталогом — проверьте интернет и "
                         "повторите; VIN и история ремонта в отчёте выше"),
            )

        logger.info("Запрашиваю карточку деталей в PARTSNUMBER для VIN %s...", vin)
        return await _run_step(
            step_name="PARTSNUMBER",
            var_name="_partsnumber_session",
            action=lambda session: session.get_vehicle_card(vin),
            interpret=_interpret_partsnumber,
            deadline=deadline,
        )


