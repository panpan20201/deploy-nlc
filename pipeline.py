async def process_plate_number(
    plate_number: str,
    on_partial_result: Optional[Callable[[str], Awaitable[None]]] = None,
    grade_hint: Optional[str] = None,
    force_refresh: bool = False,
    encar_vin: Optional[str] = None,
) -> str:
    """
    Полная проверка по номеру машины. ВСЕГДА возвращает готовый текст и
    никогда не бросает исключение (правило 1 в шапке файла).

    :param on_partial_result: необязательный колбэк — вызывается по ходу
        проверки с ПОЛНЫМ текстом ответа, накопленным на данный момент (а
        не только с новым куском), чтобы вызывающему коду не нужно было
        ничего склеивать самому.
    :param grade_hint: текст модели/трима с Encar. Нужен, только если
        Carmoodo покажет экран выбора комплектации.
    """
    deadline = time.monotonic() + REQUEST_BUDGET_SEC

    vin_res: Optional[StepResult] = None
    repair_res: Optional[StepResult] = None
    parts_res: Optional[StepResult] = None
    repair_text: Optional[str] = None
    parts_task: Optional[asyncio.Task] = None

    # Показ промежуточного результата вызывается из ДВУХ мест
    # одновременно: из основного хода проверки и из фоновой задачи
    # PARTSNUMBER, которая может закончиться в любой момент. Обе правят
    # одно и то же сообщение в Telegram, поэтому пускаем их по очереди —
    # иначе два вызова могут перемешаться и показать человеку текст,
    # собранный из разных моментов времени.
    progress_lock = asyncio.Lock()

    # ------------------------------------------------------------------
    # ЗАПИСИ ИСТОРИИ РЕМОНТА ПО МЕРЕ ИЗВЛЕЧЕНИЯ
    #
    # Записи дописываются правками одна за другой в то же сообщение, где
    # обновляются остальные разделы.
    #
    # Зачем. Обход одной карточки HeyDealer занимает около 15 секунд.
    # При семи записях человек больше полутора минут смотрел бы на
    # «проверяю... ⏳», хотя первая запись готова через пятнадцать
    # секунд.
    #
    # Отдельного сообщения на запись НЕ делаем — по требованию владельца
    # это именно правки одного. И это удачно совпадает с тем, как здесь
    # всё устроено: _assemble каждый раз собирает ПОЛНЫЙ текст заново из
    # того, что известно на данный момент, поэтому добавить растущий
    # список записей — это просто ещё один известный кусок.
    # ------------------------------------------------------------------
    partial_records: list = []
    loop = asyncio.get_running_loop()

    def on_repair_record(record: dict) -> None:
        """
        Вызывается ИЗ РАБОЧЕГО ПОТОКА (HeyDealer крутится в executor).

        Из потока трогать Telegram и asyncio напрямую нельзя, поэтому
        перебрасываем показ в основной цикл через
        run_coroutine_threadsafe. Результат НЕ ждём: поток должен идти
        дальше к следующей карточке, а не стоять в очереди за правкой
        сообщения. Если правка не пройдёт, следующая запись всё равно
        покажет и её тоже — текст каждый раз собирается целиком.
        """
        partial_records.append(record)
        try:
            asyncio.run_coroutine_threadsafe(show_progress(), loop)
        except Exception:
            # Показ — удобство, сбор данных — задача. Ронять вторую
            # из-за первой нельзя (см. тот же принцип в on_record
            # на стороне heydealer_history).
            logger.debug("Не удалось запланировать показ новой записи.", exc_info=True)

    async def show_progress() -> None:
        if on_partial_result is None:
            return
        async with progress_lock:
            try:
                await on_partial_result(
                    _assemble(
                        plate_number, vin_res, repair_res, repair_text,
                        parts_res, partial_records,
                    )
                )
            except Exception:
                # Промежуточное сообщение — удобство, а не результат. Его
                # неудача (например, Telegram отверг правку сообщения) не
                # должна обрывать саму проверку.
                logger.exception("Не удалось показать промежуточный результат.")

    # ------------------------------------------------------------------
    # PARTSNUMBER: показать результат СРАЗУ, как только он готов
    #
    # Шаг PARTSNUMBER уходит в фон и работает параллельно с HeyDealer на
    # планшете. Если показывать его результат только в конце проверки (в
    # `await parts_task`), то при PARTSNUMBER, закончившем первым (а он
    # часто быстрее HeyDealer), готовые данные молча лежали бы и ждали,
    # пока планшет домотает свой список, а человек видел бы "проверяю... ⏳"
    # напротив уже полученного раздела.
    #
    # Поэтому задача сама, закончив работу, кладёт результат и
    # обновляет сообщение. Порядок разделов в ответе от этого не зависит —
    # текст каждый раз собирается заново из того, что известно на данный
    # момент (см. _assemble), так что раздел просто перестаёт быть
    # "проверяю..." на своём месте.
    # ------------------------------------------------------------------
    async def run_parts_and_show(vin: str) -> "StepResult":
        result = await _run_partsnumber_step(vin, deadline)
        nonlocal parts_res
        parts_res = result
        if result.cacheable:
            _cache_put(plate_number, "parts", result.value)
        await show_progress()
        return result

    # --- Что уже есть в кэше --------------------------------------------
    if force_refresh:
        # Принудительная перепроверка: человек явно попросил свежие
        # данные (например, машина только что была на сервисе, и
        # сохранённая история ремонта уже неактуальна). Забываем всё
        # сохранённое по этому номеру и идём в сервисы заново.
        #
        # Это стоит запросов из дневных лимитов, поэтому включается
        # только по явной просьбе, а не само.
        forgotten = storage.forget(plate_number)
        logger.info(
            "Принудительная перепроверка %s: забыто сохранённых разделов — %d.",
            plate_number, forgotten,
        )

    cached_vin = _cache_get(plate_number, "vin")
    cached_parts = _cache_get(plate_number, "parts")

    # История ремонта достаётся ВМЕСТЕ с датой получения: это единственный
    # раздел, который может измениться со временем, и отчёт обязан назвать
    # человеку, на какой момент он проверен (см. format_data_age).
    _repair_found = storage.get_with_age(plate_number, "repair")
    cached_repair = None if _repair_found is None else _repair_found[0]
    cached_repair_at = None if _repair_found is None else _repair_found[1]

    # Отмечаем в журнале, обошлись ли мы без обращения к сервисам. При
    # дефицитных лимитах доля таких проверок — рабочий показатель, а не
    # любопытство: каждая из них освобождает запрос для новой машины.
    served_from_base = all(x is not None for x in (cached_vin, cached_repair, cached_parts))
    storage.record_lookup(plate_number, from_cache=served_from_base)

    if cached_vin is not None:
        vin_res = StepResult("ok", value=cached_vin)
        logger.info(
            "VIN для %s взят из кэша — Carmoodo не трогаем (экономим дневной лимит).",
            plate_number,
        )
    if cached_repair is not None:
        repair_res = StepResult("ok", value=cached_repair,
                                obtained_at=cached_repair_at)
        repair_text = await _format_repair_text(cached_repair)
        logger.info(
            "История ремонта для %s взята из кэша (%s).",
            plate_number, format_data_age(cached_repair_at),
        )
    if cached_parts is not None:
        # ПРОВЕРКА СОХРАНЁННОГО ПЕРЕД ВЫДАЧЕЙ.
        # Раздел "parts" хранится бессрочно, поэтому запись, попавшая в
        # базу испорченной, выдавалась бы человеку вечно — и ни одна
        # защита на стороне PARTSNUMBER этого не перехватила бы, ведь к
        # PARTSNUMBER мы в таком случае вообще не обращаемся.
        # Подробности — у looks_like_catalog_page_text.
        if looks_like_catalog_page_text(str(cached_parts)):
            logger.warning(
                "Сохранённая карточка PARTSNUMBER для %s — это текст главной "
                "страницы каталога, а не карточка машины (осталась от старой "
                "ошибки копирования). Забываю её и запрашиваю заново.",
                plate_number,
            )
            storage.forget(plate_number, "parts")
            cached_parts = None
        else:
            parts_res = StepResult("ok", value=cached_parts)
            logger.info("Карточка PARTSNUMBER для %s взята из кэша.", plate_number)

    need_vin = vin_res is None
    need_repair = repair_res is None
    need_parts = parts_res is None

    if not (need_vin or need_repair or need_parts):
        logger.info("Все данные по %s есть в кэше — устройства не трогаем вовсе.", plate_number)
        return _assemble(plate_number, vin_res, repair_res, repair_text, parts_res)

    # --- Работа с планшетом ---------------------------------------------
    # Если VIN уже известен (взят из кэша), PARTSNUMBER можно запускать
    # НЕМЕДЛЕННО, не дожидаясь очереди на планшет: планшет ему не нужен
    # вообще, и ждать очереди на него было бы пустой тратой времени.
    if need_parts and vin_res is not None and vin_res.ok:
        parts_task = asyncio.create_task(run_parts_and_show(vin_res.value))

    # Лок планшета берём, ТОЛЬКО если планшет реально нужен. Когда обе
    # "планшетные" секции уже есть в кэше и переделывать надо лишь
    # PARTSNUMBER — занимать устройство незачем, и следующий в очереди
    # запрос может работать с ним параллельно.
    if need_vin or need_repair:
        async with _device_lock:
            # Шаг 1: VIN (Carmoodo). Первым — потому что от него зависит
            # PARTSNUMBER, и чем раньше появится VIN, тем раньше
            # PARTSNUMBER уйдёт работать в фон параллельно с HeyDealer.
            if need_vin:
                # VIN С ENCAR ВМЕСТО ПЛАНШЕТА.
                #
                # Сверка Encar с Carmoodo: из 78 объявлений,
                # где Encar отдал полный VIN, он совпал с Carmoodo во всех
                # 78. Отклонения Encar — только отсутствие VIN (4 случая) и
                # обрезок в 8 символов (1 случай), и оба ловятся формально,
                # без второго источника. Решение владельца: принимать VIN с
                # Encar, Carmoodo оставить запасным путём.
                #
                # Выигрыш — около 45 секунд на проверке (замер Carmoodo:
                # медиана 29 с, p90 43 с) плюс сэкономленный дневной лимит.
                # По боевой базе правило принимает 114 VIN из 115.
                #
                # Отказ всегда в безопасную сторону: любое сомнение — и
                # машина идёт на планшет, в Carmoodo.
                vin_godnyy, vin_prichina = vin_check.is_usable(encar_vin)
                if vin_godnyy:
                    vin_res = StepResult("ok", value=vin_check.normalize(encar_vin))
                    logger.info(
                        "VIN взят с Encar (%s) — Carmoodo не трогаем: "
                        "экономим около 45 секунд и один запрос из дневного лимита.",
                        vin_res.value,
                    )
                    await show_progress()
                elif usage.limit_reached():
                    logger.info(
                        "Carmoodo: дневной лимит уже исчерпан — пропускаю шаг, "
                        "не создавая сессию (сэкономлено около минуты)."
                    )
                    vin_res = StepResult(
                        "empty",
                        reason="daily_limit",
                        message=_CARMOODO_REASON_MESSAGES["daily_limit"][1],
                    )
                    await show_progress()
                else:
                    logger.info(
                        "VIN с Encar не годится (%s) — иду в Carmoodo для номера %s...",
                        vin_prichina, plate_number,
                    )
                    vin_res = await _run_step(
                        step_name="Carmoodo",
                        var_name="_carmoodo_session",
                        action=lambda session: session.get_vin(
                            plate_number, grade_hint, return_home=False
                        ),
                        interpret=_interpret_carmoodo,
                        deadline=deadline,
                    )
                    if vin_res.cacheable:
                        _cache_put(plate_number, "vin", vin_res.value)
                    await show_progress()

            # Планшет держит по одной сессии за раз: Appium молча обрывает
            # первую сессию при создании второй на том же устройстве. Плюс
            # у простаивающей сессии есть свой таймаут бездействия —
            # держать Carmoodo открытой на всё время HeyDealer
            # бессмысленно и опасно.
            await _close_session("_carmoodo_session", reason="VIN получен, освобождаю приложение")

            # Шаг 2: PARTSNUMBER уходит в фон — он работает через браузер,
            # и планшет ему не нужен, так что пусть крутится одновременно
            # с HeyDealer. Экономия — почти всё время его работы.
            if need_parts and parts_task is None and vin_res is not None and vin_res.ok:
                parts_task = asyncio.create_task(run_parts_and_show(vin_res.value))

            # Шаг 3: история ремонта (HeyDealer) — на планшете,
            # параллельно с работающим в фоне PARTSNUMBER.
            if need_repair:
                logger.info("Запрашиваю историю ремонта в HeyDealer для номера %s...", plate_number)
                repair_res = await _run_step(
                    step_name="HeyDealer",
                    var_name="_heydealer_session",
                    action=lambda session: session.get_repair_history(
                        plate_number, on_record=on_repair_record
                    ),
                    interpret=_interpret_heydealer,
                    deadline=deadline,
                )
                # Исчерпан дневной лимит — не поломка, но и не ответ.
                # Пробуем снять его сбросом рекламного ID и повторить.
                # РОВНО ОДИН раз за запрос: если и после сброса лимит на
                # месте, значит, дело не в идентификаторе, и повторять
                # дальше — только жечь время и множить сбросы.
                if repair_res.reason == "daily_limit" and await _recover_heydealer_limit():
                    repair_res = await _run_step(
                        step_name="HeyDealer",
                        var_name="_heydealer_session",
                        action=lambda session: session.get_repair_history(
                        plate_number, on_record=on_repair_record
                    ),
                        interpret=_interpret_heydealer,
                        deadline=deadline,
                    )

                if repair_res.cacheable:
                    _cache_put(plate_number, "repair", repair_res.value)
                    repair_text = await _format_repair_text(repair_res.value)

            # Сессия НЕ гасится: следующий запрос переиспользует её и
            # сэкономит 13 секунд на создании сессии и запуске приложения
            # (замер: это 21% времени шага HeyDealer). Живость проверяется
            # перед переиспользованием, состояние приложения приводится в
            # исходное всегда — см. _get_session.
            #
            # Приложение при этом уже оставлено на экране ввода: шаг 10
            # возвращается назад и убирает номер из поля.
            #
            # Сессия всё равно закроется сама, если следующего запроса не
            # будет: newCommandTimeout = 5 минут. И закрывается немедленно
            # при любом сбое шага (см. _run_step) и при остановке бота.
            logger.debug(
                "Сессия _heydealer_session оставлена живой для следующего запроса."
            )

    # --- Планшет отпущен, ждём фоновый PARTSNUMBER ----------------------
    # Прогресс показываем уже ВНЕ лока: следующий запрос в очереди может
    # занять планшет, пока мы дожидаемся своей браузерной части.
    await show_progress()

    if parts_task is not None:
        # Задача сама никогда не бросает исключение (внутри _run_step),
        # поэтому дополнительный try/except здесь не нужен. Результат она
        # уже положила в parts_res и уже показала человеку — здесь мы
        # просто дожидаемся её завершения, чтобы не собрать итоговый текст
        # раньше, чем PARTSNUMBER закончит. Сохранение в базу тоже сделано
        # внутри задачи, повторять его здесь не нужно.
        await parts_task

    zanyalo = REQUEST_BUDGET_SEC - (deadline - time.monotonic())
    logger.info("Проверка номера %s завершена за %.1f сек.", plate_number, zanyalo)

    # Итог проверки — в статистику. Не в лог: по логу это считается
    # только руками и только тем, кто знает, что искать. Сводка нужна,
    # чтобы владелец видел долю полных ответов и расход лимитов, не
    # дожидаясь, пока поломка случится у него на глазах (см. stats.py).
    # Ошибки внутри не поднимаются: статистика не имеет права отменить
    # ответ человеку.
    stats.record(
        plate_number,
        vin=vin_res.status if vin_res else "error",
        repair=repair_res.status if repair_res else "error",
        parts=parts_res.status if parts_res else "error",
        seconds=zanyalo,
    )
    return _assemble(plate_number, vin_res, repair_res, repair_text, parts_res)


async def process_encar_link(
    url: str,
    on_partial_result: Optional[Callable[[str], Awaitable[None]]] = None,
    force_refresh: bool = False,
) -> str:
    """
    Точка входа: ссылка Encar → полный текст ответа.

    EncarParsingError НЕ гасится здесь специально — она должна дойти до
    handlers.py, чтобы человек увидел понятное "не удалось разобрать
    ссылку", а не общую ошибку проверки. Это единственное исключение,
    которое пайплайн выпускает наружу.
    """
    logger.info("Извлекаю номер машины из ссылки Encar: %s", url)
    plate_number, encar_vin, grade_text = await asyncio.to_thread(
        get_vehicle_number_vin_and_grade, url
    )
    logger.info("Номер машины получен: %s (трим с Encar: %r)", plate_number, grade_text)

    return await process_plate_number(
        plate_number,
        on_partial_result=on_partial_result,
        grade_hint=grade_text,
        force_refresh=force_refresh,
        encar_vin=encar_vin,
    )


def device_lock():
    """
    Лок планшета — чтобы посторонние операции с устройством (например,
    сброс рекламного ID через настройки Google) не накладывались на
    идущую проверку. Планшет один, и тапы двух сценариев по одному
    экрану ломают оба.

    Используется как `async with pipeline.device_lock():`.
    """
    return _device_lock


async def close_device_sessions(reason: str = "") -> None:
    """
    Закрывает обе Appium-сессии на планшете.

    Нужно перед любым вмешательством в устройство со стороны: приложения
    читают часть настроек (в том числе рекламный идентификатор) при
    запуске и держат в памяти. Без перезапуска приложение продолжит
    работать со старым значением, и смысл вмешательства пропадёт.
    """
    await _close_session("_carmoodo_session", reason=reason)
    await _close_session("_heydealer_session", reason=reason)


def device_busy() -> bool:
    """Занят ли сейчас планшет — чтобы бот мог честно предупредить об очереди."""
    return _device_lock.locked()


async def shutdown() -> None:
    """Аккуратно закрывает все сессии при остановке бота (хук из bot.py)."""
    logger.info("Остановка: закрываю все открытые сессии...")
    for var_name in ("_heydealer_session", "_carmoodo_session", "_partsnumber_session"):
        await _close_session(var_name, reason="остановка бота")
    storage.close()
