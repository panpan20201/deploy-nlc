def _interpret_heydealer(session, records) -> StepResult:
    if records:
        return StepResult("ok", value=records)

    reason = getattr(session, "last_reason", None)
    if reason in _HEYDEALER_REASON_MESSAGES:
        return StepResult("empty", reason=reason, message=_HEYDEALER_REASON_MESSAGES[reason])
    return StepResult("empty", reason="no_records", message="история ремонта не найдена")


def _interpret_partsnumber(session, card) -> StepResult:
    # get_vehicle_card возвращает None штатно (VIN не найден в базе либо
    # формат VIN некорректен) и бросает исключение при технической
    # неудаче — то есть разделение "ответ" / "сбой" уже сделано внутри
    # модуля, здесь достаточно перенести его в StepResult.
    if card:
        return StepResult("ok", value=card)
    # Каталог марки может быть закрыт для нашего доступа (так бывает,
    # например, с Renault) — это не «машины нет», и человеку надо сказать
    # именно это.
    if getattr(session, "last_reason", None) == "catalog_closed":
        return StepResult(
            "empty", reason="catalog_closed",
            message="каталог этой марки не входит в наш доступ PARTSNUMBER",
        )
    return StepResult("empty", reason="not_found", message="машина не найдена в каталоге")


# ===========================================================================
# Сборка текста ответа
# ===========================================================================
#
# Сообщения уходят с parse_mode=HTML (нужен для <code>, который в Telegram
# копируется одним нажатием — это важно для номера и VIN, их чаще всего
# вставляют куда-то руками). Поэтому ВЕСЬ текст, пришедший с чужих сайтов,
# обязан пройти через html.escape(): один случайный символ "<" или "&" в
# данных иначе ломает разметку, и Telegram отказывается отправлять
# сообщение целиком.

_WAITING = "проверяю... ⏳"


def _format_plate(plate_number: str) -> str:
    return f"🚗 Номер машины: <code>{html.escape(plate_number)}</code>"


def _plural_days(days: int) -> str:
    """
    "день" / "дня" / "дней" по правилам русского счёта.

    Мелочь, но отчёт читает человек, принимающий решение о покупке машины.
    Кривое склонение в таком документе выглядит как небрежность ко всему
    остальному, включая цифры.
    """
    if days % 10 == 1 and days % 100 != 11:
        return "день"
    if days % 10 in (2, 3, 4) and days % 100 not in (12, 13, 14):
        return "дня"
    return "дней"


def format_data_age(obtained_at: Optional[float], now: Optional[float] = None) -> str:
    """
    На какой момент проверены данные — строкой для отчёта.

    По отчёту покупают машины, а история ремонта отдаётся из базы в
    возрасте 22 дней по медиане (замер). После выкладки на Encar машина не эксплуатируется, поэтому сама
    давность не страшна — но государственные и страховые системы публикуют
    события с задержкой, и запись может дописаться уже после выкладки.
    Дата закрывает этот случай и не стоит ни одного запроса из квоты.

    :param obtained_at: время получения (time.time) или None, если данные
                        получены прямо сейчас
    """
    if obtained_at is None:
        return "проверено сейчас"

    now = time.time() if now is None else now
    days = int((now - obtained_at) // 86400)
    if days <= 0:
        return "проверено сегодня"

    when = time.strftime("%d.%m", time.localtime(obtained_at))
    if days == 1:
        return f"проверено {when}, вчера"
    return f"проверено {when}, {days} {_plural_days(days)} назад"


def _format_vin(result: Optional[StepResult]) -> str:
    # Источник в подписи НЕ указывается: VIN приходит то с Encar (см.
    # vin_check, так получается 99% VIN), то от Carmoodo, и фиксированная
    # подпись вроде "(Carmoodo)" врала бы — а в отчёте, по которому
    # покупают машину, неверный источник хуже отсутствующего.
    if result is None:
        return f"🔑 VIN: {_WAITING}"
    if result.ok:
        return f"🔑 VIN: <code>{html.escape(str(result.value))}</code>"
    return f"🔑 VIN: {html.escape(result.message)}"


def _format_repair(
    result: Optional[StepResult],
    repair_text: Optional[str] = None,
    partial_records: Optional[list] = None,
) -> str:
    if result is None:
        # Пока шаг не закончен, показываем то, что уже извлечено. С одним
        # "проверяю... ⏳" человек полторы минуты не видел бы записей,
        # готовых ещё на пятнадцатой секунде.
        #
        # Перевод делается ТУТ ЖЕ и синхронно, и это осознанно: он идёт
        # через словарь и кэш на диске (см. translate_part), то есть для
        # уже знакомых терминов стоит доли миллисекунды. За сеть в DeepL
        # он уходит только на совершенно новом термине — и такой термин
        # всё равно придётся перевести, здесь или тридцатью секундами
        # позже. Разница лишь в том, что кэш наполнится быстрее.
        if partial_records:
            done = _translate_records_safely(partial_records)
            if done:
                return (
                    f"📋 История ремонта (HeyDealer) — "
                    f"найдено записей: {len(partial_records)}, продолжаю искать... ⏳\n"
                    f"{html.escape(done)}"
                )
        return f"📋 История ремонта (HeyDealer): {_WAITING}"
    if result.ok and repair_text:
        # Дата обязательна: это единственный раздел отчёта, который может
        # измениться со временем, и человек должен видеть, на какой момент
        # он проверен (см. format_data_age).
        checked = format_data_age(result.obtained_at)
        return (f"📋 История ремонта (HeyDealer) — {checked}:\n"
                f"{html.escape(repair_text)}")
    if result.ok:
        return "📋 История ремонта (HeyDealer): не удалось оформить результат"
    return f"📋 История ремонта (HeyDealer): {html.escape(result.message)}"


def _translate_records_safely(records: list) -> str:
    """
    Переводит уже извлечённые записи для промежуточного показа.

    Отдельная функция с перехватом ошибок, потому что вызывается в
    середине работы: если перевод споткнётся на новом термине или DeepL
    не ответит, это не повод оборвать проверку — просто покажем на одну
    правку меньше, а итоговый текст соберётся как обычно.
    """
    try:
        return format_and_translate(list(records))
    except Exception:
        logger.debug("Не удалось перевести частичные записи.", exc_info=True)
        return ""


def _format_parts(result: Optional[StepResult], vin_res: Optional[StepResult]) -> str:
    # Пока VIN ещё ищется, детали не «пропущены», а ждут его. Иначе
    # человек полминуты видел бы «пропущено — нет VIN» — отказ, которого
    # на самом деле нет.
    if vin_res is None:
        return "🔧 Детали и даты (PARTSNUMBER): ждёт VIN... ⏳"
    if not vin_res.ok:
        return "🔧 Детали и даты (PARTSNUMBER): пропущено — нет VIN"
    if result is None:
        return f"🔧 Детали и даты (PARTSNUMBER): {_WAITING}"
    if result.ok:
        return f"🔧 Детали и даты (PARTSNUMBER):\n{html.escape(str(result.value))}"
    return f"🔧 Детали и даты (PARTSNUMBER): {html.escape(result.message)}"


def _assemble(
    plate_number: str,
    vin_res: Optional[StepResult],
    repair_res: Optional[StepResult],
    repair_text: Optional[str],
    parts_res: Optional[StepResult],
    partial_records: Optional[list] = None,
) -> str:
    # Сноски про бессрочность VIN и деталей здесь СОЗНАТЕЛЬНО НЕТ, хотя
    # отсутствие даты у этих разделов может показаться недосмотром.
    # Решение владельца: отчёт читают люди, которые и так знают, что VIN
    # не меняется, а лишняя строка в каждом сообщении мешает.
    #
    # Дата у истории ремонта остаётся: это единственный раздел, который
    # может измениться со временем.
    return "\n\n".join([
        _format_plate(plate_number),
        _format_repair(repair_res, repair_text, partial_records),
        _format_vin(vin_res),
        _format_parts(parts_res, vin_res),
    ])


async def _format_repair_text(records: list) -> str:
    """
    Превращает записи HeyDealer в готовый русский текст.

    В ОТДЕЛЬНОМ ПОТОКЕ — и это не формальность: format_and_translate()
    внутри ходит в DeepL по сети (до 8 секунд на незнакомый термин, а их в
    одной карточке бывает несколько). В основном цикле бота это значило
    бы, что на всё время перевода бот замирает целиком и не может даже
    принять сообщение от другого человека.
    """
    return await asyncio.to_thread(format_and_translate, records)


