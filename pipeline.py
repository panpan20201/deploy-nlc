# ===========================================================================
# StepResult — единый ответ любого шага
# ===========================================================================

@dataclass
class StepResult:
    """
    Чем закончился шаг. Три состояния — и различать их важно, потому что
    для человека это три РАЗНЫЕ новости:

    "ok"    — данные получены.

    "empty" — шаг отработал штатно, но данных нет. Это ОТВЕТ ПО СУЩЕСТВУ,
              а не поломка: машины нет в базе, история ремонта пуста.
              Повторять бессмысленно — ответ не изменится.

    "error" — техническая неудача: не смогли получить ответ. Данные,
              возможно, есть, просто мы до них не добрались. Здесь повтор
              осмыслен, и человеку стоит сказать именно это.

    Если слить "empty" и "error" в одно "не удалось определить", человек
    не поймёт, повторять запрос или это окончательно.
    """

    status: str          # "ok" | "empty" | "error"
    value: Any = None
    reason: str = ""     # короткий код причины (для логов и логики)
    message: str = ""    # текст для пользователя

    # Когда данные были получены НА САМОМ ДЕЛЕ. None — прямо сейчас, в этой
    # проверке; число — время из базы, значит данные взяты из хранилища.
    #
    # Без этого поля отчёт не может назвать возраст данных, а замер
    # показал, что история ремонта отдаётся из базы в возрасте 22 дней по
    # медиане. По этому отчёту покупают машины, и
    # умолчание о возрасте — это молчаливый риск, а не экономия места.
    obtained_at: Optional[float] = None

    @property
    def ok(self) -> bool:
        return self.status == "ok"

    @property
    def cacheable(self) -> bool:
        """
        В кэш идут ТОЛЬКО успехи.

        "empty" сознательно не кэшируем: отрицательный ответ мог быть
        получен по временной причине (исчерпан дневной лимит Carmoodo, не
        сопоставился трим), и запомнить его на шесть часов означало бы
        шесть часов повторять человеку неверное "не найдено" — даже
        когда причина уже отпала.
        """
        return self.status == "ok"


