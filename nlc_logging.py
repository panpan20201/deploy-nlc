# -*- coding: utf-8 -*-
"""
nlc_logging.py
==============

ЕДИНАЯ настройка логирования для всего проекта.

ЗАЧЕМ ЭТО НУЖНО — самое важное объяснение в файле
-------------------------------------------------

Разбор любого сбоя строится на правиле "сначала реальный лог, только
потом исправление". Чтобы лог для этого годился, нужно решить три
проблемы:

1. Сообщения через обычный `print()` идут БЕЗ времени, БЕЗ уровня
   важности и, главное, БЕЗ записи в файл. Как только окно консоли
   закрывается или прокручивается — история сбоя исчезает навсегда.

2. Нужно понимать, какие строки относятся к КАКОМУ запросу. Когда бот
   обслуживает нескольких человек, шаги разных проверок перемешиваются
   в одном потоке строк, и без метки разобрать, что за чем шло,
   невозможно.

3. На Windows консоль по умолчанию не в UTF-8, а мы печатаем корейские
   тексты. `print()` с корейским символом в такой консоли может УПАСТЬ с
   UnicodeEncodeError — то есть логирование само по себе способно уронить
   шаг, который в остальном отработал бы нормально.

Что этот файл делает:

* Заводит ротируемый файл `logs/nlc.log` (5 МБ × 10 файлов ≈ 50 МБ
  истории). Он переживает и перезапуски бота, и закрытие окна консоли.
* Подставляет в КАЖДУЮ строку лога идентификатор запроса (`request_id`) —
  короткая метка вида `a3f19c`. Все строки одной проверки помечены
  одинаково, любого пользователя. Найти в общем логе всё, что относится к
  одной проверке, можно простым поиском по этой метке.
* Принудительно переводит консоль в UTF-8 с заменой непечатаемых
  символов, чтобы корейский текст никогда не ронял процесс.
* Приглушает "болтливые" сторонние библиотеки (httpx, urllib3, selenium),
  которые иначе забивают лог служебным шумом и прячут в нём настоящую
  причину сбоя.

Как ЧИТАТЬ получившийся лог:

    2026-08-21 11:57:06 INFO    [a3f19c] pipeline: Шаг Carmoodo: попытка 1/2
    ^ время               ^уровень ^запрос  ^откуда   ^что произошло

Если нужно разобрать конкретный сбой — берём метку запроса из сообщения
об ошибке и ищем по ней в `logs/nlc.log`: получим ровно шаги этой одной
проверки, без чужих.
"""

import contextvars
import logging
import os
import sys
from logging.handlers import RotatingFileHandler

# ---------------------------------------------------------------------------
# Идентификатор текущего запроса.
#
# contextvars (а не обычная глобальная переменная) — принципиальный выбор:
# бот асинхронный и обслуживает несколько проверок одновременно, а
# contextvars хранит СВОЁ значение для каждой параллельной задачи. Обычная
# глобальная переменная показывала бы в логе метку последнего начавшегося
# запроса во всех остальных — то есть ровно ту путаницу, ради устранения
# которой всё и затевалось.
#
# Отдельно важно: значение contextvars автоматически переносится в потоки,
# запущенные через asyncio.to_thread() (он копирует контекст). Благодаря
# этому блокирующий код Appium/Playwright, выполняющийся в отдельном
# потоке, пишет в лог с тем же request_id, что и вызвавшая его корутина —
# ничего специально прокидывать через параметры не нужно.
# ---------------------------------------------------------------------------
request_id_var: contextvars.ContextVar[str] = contextvars.ContextVar(
    "request_id", default="-"
)


def set_request_id(value: str) -> None:
    """Пометить все последующие записи лога в текущей задаче меткой value."""
    request_id_var.set(value)


def new_request_id() -> str:
    """
    Короткая случайная метка запроса (6 символов, например "a3f19c").

    Почему короткая: она печатается в КАЖДОЙ строке лога, и длинный UUID
    занимал бы полстроки, мешая читать сами сообщения. Шести символов
    (16 млн вариантов) с запасом хватает, чтобы метки живущих одновременно
    запросов не совпали.
    """
    import uuid

    return uuid.uuid4().hex[:6]


class _RequestIdFilter(logging.Filter):
    """
    Подставляет request_id в каждую запись лога.

    Реализовано фильтром, а не ручным добавлением метки в текст каждого
    сообщения: так метка появляется во ВСЕХ записях автоматически, включая
    те, что пишут сторонние библиотеки и любой код модулей — ни одной
    строки вызывающего кода менять не нужно.
    """

    def filter(self, record: logging.LogRecord) -> bool:
        record.request_id = request_id_var.get()
        return True


LOG_DIR_NAME = "logs"
LOG_FILE_NAME = "nlc.log"
LOG_MAX_BYTES = 5 * 1024 * 1024  # 5 МБ на файл
LOG_BACKUP_COUNT = 10  # + 10 старых файлов, итого ~50 МБ истории

_LOG_FORMAT = "%(asctime)s %(levelname)-7s [%(request_id)s] %(name)s: %(message)s"
_DATE_FORMAT = "%Y-%m-%d %H:%M:%S"

# Библиотеки, которые на уровне INFO пишут десятки служебных строк на каждую
# команду и полностью хоронят под собой полезные сообщения.
#
# Замер на реальном файле лога без этих настроек (36 087 строк, 3,8 МБ):
#
#     80.9%  3064 КБ  26212 строк  DEBUG  telegram.ext.ExtBot
#      4.0%   150 КБ   2518 строк  ERROR  handlers
#      3.0%   112 КБ    729 строк  INFO   heydealer_history
#      ...
#
# Четыре пятых файла — служебная переписка с Telegram: пустой `getUpdates`
# каждые 10 секунд плюс полный дамп тела каждого сообщения. Полезного в
# ней нет ничего, зато вред прямой: файлы ротируются по 5 МБ, и этот шум
# ВЫТАЛКИВАЕТ из истории настоящие строки о сбоях. То есть страдает ровно
# то, на чём держится весь рабочий процесс проекта, — возможность
# разобрать вчерашний сбой по реальному логу. При таком составе 55 МБ
# истории вмещают лишь около 10 МБ содержательных записей.
#
# Уровни разные и это осознанно. Пакету `telegram` ставится INFO, а не
# WARNING: весь измеренный шум идёт на уровне DEBUG, а INFO у
# python-telegram-bot скупой и осмысленный ("Application started",
# "Updater stopped"). Глушить его заодно значило бы потерять полезное
# вместе с бесполезным. Остальным библиотекам WARNING — у них и на INFO
# нет ничего нужного.
_LOGGER_LEVELS = {
    # Главный источник шума — см. замер выше.
    "telegram": logging.INFO,
    "httpx": logging.WARNING,
    "httpcore": logging.WARNING,
    "urllib3": logging.WARNING,
    "selenium": logging.WARNING,
    "selenium.webdriver.remote.remote_connection": logging.WARNING,
    "asyncio": logging.WARNING,
    "PIL": logging.WARNING,
}

_already_configured = False


def setup_logging(level: int = logging.INFO, log_dir: str = None) -> str:
    """
    Настраивает логирование для всего процесса. Вызывать ОДИН раз, самым
    первым делом при старте (см. bot.py).

    :param level: уровень для нашего кода (INFO обычно, DEBUG при разборе)
    :param log_dir: папка для файлов лога; по умолчанию — "logs" рядом с
        этим файлом
    :return: полный путь к файлу лога (удобно напечатать при старте, чтобы
        было видно, куда смотреть)
    """
    global _already_configured

    if log_dir is None:
        log_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), LOG_DIR_NAME)
    os.makedirs(log_dir, exist_ok=True)
    log_path = os.path.join(log_dir, LOG_FILE_NAME)

    if _already_configured:
        return log_path

    # --- Консоль в UTF-8 --------------------------------------------------
    # Windows-консоль по умолчанию работает НЕ в UTF-8, а мы постоянно
    # печатаем корейские названия деталей, номера машин и тексты диалогов.
    # Без этой строки один корейский символ в сообщении лога роняет весь
    # шаг с UnicodeEncodeError — то есть логирование само становится
    # источником сбоев. errors="replace" — сознательный выбор: лучше
    # увидеть в консоли "?" вместо иероглифа, чем потерять процесс (в
    # ФАЙЛ лога всё равно пишется полноценный UTF-8, там текст целый).
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            # Старая версия Python или подменённый поток вывода — не повод
            # падать на этапе настройки логирования.
            pass

    root = logging.getLogger()
    root.setLevel(logging.DEBUG)  # решение "что писать" принимают
    # обработчики ниже, каждый со своим уровнем

    # Убираем обработчики, которые мог поставить кто-то до нас (например,
    # logging.basicConfig() в тестовом запуске модуля напрямую) — иначе
    # каждая строка задваивается в консоли.
    for handler in list(root.handlers):
        root.removeHandler(handler)

    request_id_filter = _RequestIdFilter()
    formatter = logging.Formatter(_LOG_FORMAT, datefmt=_DATE_FORMAT)

    # --- Файл с ротацией --------------------------------------------------
    # Пишем в файл ВСЁ от DEBUG и выше, даже когда в консоли только INFO:
    # разбор сбоя почти всегда требует подробностей, а вспомнить и включить
    # DEBUG заранее, до того как сбой случился, невозможно.
    file_handler = RotatingFileHandler(
        log_path,
        maxBytes=LOG_MAX_BYTES,
        backupCount=LOG_BACKUP_COUNT,
        encoding="utf-8",
    )
    file_handler.setLevel(logging.DEBUG)
    file_handler.setFormatter(formatter)
    file_handler.addFilter(request_id_filter)
    root.addHandler(file_handler)

    # --- Консоль ----------------------------------------------------------
    console_handler = logging.StreamHandler(sys.stdout)
    console_handler.setLevel(level)
    console_handler.setFormatter(formatter)
    console_handler.addFilter(request_id_filter)
    root.addHandler(console_handler)

    for name, noisy_level in _LOGGER_LEVELS.items():
        logging.getLogger(name).setLevel(noisy_level)

    _already_configured = True

    logging.getLogger(__name__).info(
        "Логирование настроено. Файл лога: %s (до %d МБ × %d файлов). "
        "В файл пишется уровень DEBUG, в консоль — %s.",
        log_path,
        LOG_MAX_BYTES // (1024 * 1024),
        LOG_BACKUP_COUNT + 1,
        logging.getLevelName(level),
    )
    return log_path
