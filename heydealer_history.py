# @text при этом пустой (так же ведёт себя Carmoodo — там кнопка "로그인"
# является View с content-desc и пустым text). Если "알림받기" на планшете
# отрисован как такая кнопка, проверка только по @text его не увидит, и
# обход продолжит листать дальше.
END_OF_LIST_XPATH = " | ".join(
    f'//*[contains(@{attr}, "{mark}")]'
    for mark in END_OF_LIST_MARKS
    for attr in ("text", "content-desc")
)

