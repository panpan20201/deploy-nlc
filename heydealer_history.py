# Задача этого блока: взять сырые записи, которые вернула get_repair_history
# (дата/сервис/пробег на корейском + "сырой" многострочный текст из поля
# 정비이력), и привести их к формату отчёта:
#
#   • 08.05.2023 — 52 150 км
#     • Задний бампер — ремонт связанных деталей: 1 работа
#     • Задний комбинированный фонарь — ремонт: 2 работы
#   • 29.10.2024 — 95 351 км
#     • Задний бампер — ремонт: 2 работы
#     ...
#
# То есть записи группируются ПО ВИЗИТУ (дата + пробег совпадают — значит
# это один и тот же заезд в сервис), а внутри визита каждая исходная
# карточка (= одна деталь/один узел) становится отдельной строкой-буллетом.
#
# ВАЖНОЕ ОГРАНИЧЕНИЕ: формат изначально построен по образцу сырого текста
# поля 정비이력 для двигателя (из XML-дампа модалки):
#     "✓️ 엔진\n엔진\nㄴ 관련 부품 교체(신품 1건)"
# Формат парсера (parse_repair_detail_blocks) построен по этому образцу и
# по легенде с описанием терминов (관련 부품 교체 / 관련 부품 수리 / 판금 /
# 도장), которая есть в том же XML. Логика действий (перевод
# "교체"/"수리"/"판금"/"도장") — рабочая и проверенная по этой легенде.
# А вот словарь НАЗВАНИЙ ДЕТАЛЕЙ (PART_NAME_TRANSLATIONS ниже) лишь
# частично проверен по реальным сырым строкам (см. пометки в словаре);
# остальное — подбор по наиболее распространённым корейским терминам
# (бампер, фонарь, крыло, дверь/крышка багажника, фара). Если реальный
# корейский текст будет отличаться — перевод для него не найдётся, и
# вместо перевода функция вернёт исходный корейский текст с пометкой "[?]"
# в начале (см. translate_part/translate_action), плюс выведет
# предупреждение в лог — так пропущенный термин сразу видно, и словарь
# легко дополнить одной строкой, ничего не отлаживая заново (а при
# настроенном DeepL перевод подставится автоматически, см. ниже).

# ---------------------------------------------------------------------------
# АВТОМАТИЧЕСКИЙ ПЕРЕВОД ЧЕРЕЗ DeepL
# ---------------------------------------------------------------------------
# ПРИЧИНА: ручное пополнение словарей PART_NAME_TRANSLATIONS/ACTION_
# TRANSLATIONS не масштабируется — деталей и формулировок работ в HeyDealer
# сотни, и собирать их одну за одной по мере встречи означает
# бесконечный поток "[?]" в реальных отчётах, пока словарь не разрастётся.
#
# РЕШЕНИЕ: если термина нет ни в словаре, ни в кэше — переводим через DeepL
# (обычный HTTP-запрос, без библиотек — тот же принцип, что и остальные
# HTTP-запросы в проекте, см. encar_parser.py) и СОХРАНЯЕМ результат в
# файл-кэш на диске (TRANSLATION_CACHE_PATH). При следующей встрече того же
# термина — он уже в кэше, повторного запроса к API не будет. Так база
# переводов пополняется сама по себе, по ходу обычной работы бота, без
# ручного собирания.
#
# ПОЧЕМУ DeepL, А НЕ ДРУГОЙ СЕРВИС: поддерживает пару корейский->русский
# напрямую (без промежуточного английского, где смысл автомобильных
# терминов легко теряется), у него щедрый бесплатный тариф (500 000
# символов/месяц — для объёма этого бота этого хватит с огромным запасом),
# и API — один HTTP-запрос с одним ключом, без OAuth и лишней возни.
#
# ПРОВЕРЬ, ЕСЛИ ПЕРЕВОД БУДЕТ НЕТОЧНЫМ ПО АВТОМОБИЛЬНЫМ ТЕРМИНАМ: DeepL —
# универсальный переводчик, не специализированный под автомобильную
# лексику. Если качество на конкретных деталях/поломках не устроит — есть
# смысл попробовать Naver Papago (https://developers.naver.com/products/
# papago/) — он обучен именно на корейском языке и в целом точнее на
# специфической корейской терминологии, но требует пары client_id/client_
# secret вместо одного ключа, поэтому он не выбран вариантом по
# умолчанию. Переключение на него — отдельная функция того же вида,
# добавить несложно.
#
# НАСТРОЙКА: бесплатный ключ берётся на https://www.deepl.com/pro-api и
# вписывается в .env как DEEPL_API_KEY. Если ключ не задан — автоматический
# перевод просто не используется ("[?]" для незнакомых терминов), без
# ключа ничего не ломается.
DEEPL_API_KEY = os.getenv("DEEPL_API_KEY")

# Бесплатные и платные ключи DeepL обслуживаются на РАЗНЫХ адресах — платный
# ключ на api-free.deepl.com не примется, и наоборот. Различить их можно по
# самому ключу: у бесплатных он всегда заканчивается на ":fx" — это
# официальное соглашение DeepL, не наша догадка.
DEEPL_API_URL = (
    "https://api-free.deepl.com/v2/translate"
    if DEEPL_API_KEY and DEEPL_API_KEY.endswith(":fx")
    else "https://api.deepl.com/v2/translate"
)

# Файл-кэш переводов — рядом со скриптом, переживает перезапуски бота.
# Формат: {"part": {"корейский текст": "перевод", ...}, "action": {...}} —
# два раздела, т.к. переводим два разных вида терминов (детали/действия) и
# один и тот же корейский текст в принципе может стоять в обоих разделах
# с разным по смыслу переводом (например, слово может быть и названием
# детали, и частью описания работы).
TRANSLATION_CACHE_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "translation_cache.json"
)


def _load_translation_cache() -> "dict[str, dict[str, str]]":
    """
    Загружает кэш переводов с диска. Если файла ещё нет (первый запуск) —
    возвращает пустую структуру, а не падает: файл появится сам после
    первого же нового перевода (см. _save_translation_cache).
    """
    if not os.path.exists(TRANSLATION_CACHE_PATH):
        return {"part": {}, "action": {}}
    try:
        with open(TRANSLATION_CACHE_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        data.setdefault("part", {})
        data.setdefault("action", {})
        return data
    except (json.JSONDecodeError, OSError) as exc:
        # Повреждённый файл кэша — не повод падать всему боту. Начинаем с
        # пустого кэша (в худшем случае просто заново переведём уже
        # переведённые термины), но не молчим об этом в логе.
        log("translate", f"Не удалось прочитать файл кэша переводов ({exc}) — начинаю с пустого кэша.")
        return {"part": {}, "action": {}}


def _save_translation_cache(cache: "dict[str, dict[str, str]]") -> None:
    """
    Сохраняет кэш переводов на диск ЦЕЛИКОМ при каждом новом переводе.
    Это немного расточительно (перезаписываем весь файл ради одной новой
    строки), но термины добавляются нечасто (не на каждый запрос, а только
    когда встречается ДЕЙСТВИТЕЛЬНО новый термин) — и такой ценой мы
    гарантированно не теряем уже переведённое, даже если бот упадёт или
    будет остановлен сразу после перевода.
    """
    try:
        with open(TRANSLATION_CACHE_PATH, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False, indent=2, sort_keys=True)
    except OSError as exc:
        log("translate", f"Не удалось сохранить файл кэша переводов ({exc}) — перевод этого термина не запомнится до следующего перезапуска.")


_translation_cache = _load_translation_cache()

DEEPL_REQUEST_TIMEOUT_SEC = 8.0


def _translate_via_deepl(text_kr: str) -> Optional[str]:
    """
    Переводит корейский текст на русский через DeepL API.

    Возвращает None (а не бросает исключение), если ключ не задан, запрос
    не удался или сервис ответил не тем, что ожидалось — переводчик не
    должен ронять весь отчёт из-за проблем с сетью или квотой. В этом
    случае вызывающий код (translate_part/translate_action) просто
    покажет исходный текст с "[?]".
    """
    if not DEEPL_API_KEY:
        return None

    try:
        response = requests.post(
            DEEPL_API_URL,
            headers={
                # Ключ передаётся в заголовке, а не в теле запроса как
                # auth_key: DeepL API требует авторизацию через заголовок и
                # на передачу ключа в теле отвечает 403 "Missing
                # Authorization header", даже если ключ рабочий и
                # правильный. Формат заголовка ("DeepL-Auth-Key <ключ>") —
                # см. официальную документацию DeepL.
                "Authorization": f"DeepL-Auth-Key {DEEPL_API_KEY}",
            },
            data={
                "text": text_kr,
                "source_lang": "KO",
                "target_lang": "RU",
            },
            timeout=DEEPL_REQUEST_TIMEOUT_SEC,
        )
    except requests.RequestException as exc:
        log("translate", f'DeepL: не удалось выполнить запрос для "{text_kr}" ({exc}) — оставляю как есть.')
        return None

    if response.status_code != 200:
        log("translate", f'DeepL: сервер ответил кодом {response.status_code} для "{text_kr}" — оставляю как есть. Тело ответа: {response.text[:200]}')
        return None

    try:
        data = response.json()
        translated = data["translations"][0]["text"].strip()
    except (ValueError, KeyError, IndexError) as exc:
        log("translate", f'DeepL: не удалось разобрать ответ для "{text_kr}" ({exc}) — оставляю как есть.')
        return None

    if not translated:
        return None

    log("translate", f'DeepL: "{text_kr}" -> "{translated}" (сохраняю в кэш)')
    return translated


