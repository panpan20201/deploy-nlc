#
#     фильтр НАЙДЕН      46 случаев,   1–6 секунд (чаще всего 2–3)
#     фильтр НЕ НАЙДЕН    9 случаев,  18–22 секунды — ВСЕГДА
#
# Ровные 18–22 секунды у всех девяти означают, что лимит в 5 прокруток
# НЕ СРАБАТЫВАЛ НИ РАЗУ: раньше него успевал сработать
# DEFAULT_TIMEOUT = 20. Причина, судя по всему, в цене одного опроса —
# XPath фильтра содержит ancestor::*[@clickable="true"][1], а обход по
# оси предков uiautomator2 считает медленно, и пять кругов не влезали в
# двадцать секунд.
#
# Отсюда два вывода. Первый: снижать число прокруток бессмысленно, пока
# решение принимает таймаут по времени, — поэтому у поиска фильтра
# СВОЙ, заведомо больший таймаут (FILTER_SEARCH_TIMEOUT), чтобы решал
# именно лимит прокруток. Второй: в лог пишется, сколько прокруток
# и секунд ушло на самом деле, — и лимит можно уточнять по
# фактическим данным, а не на глаз.
FILTER_SEARCH_TIMEOUT = 45  # НЕ ускорение, а разграничение ролей.
# Это не «ждать дольше»: выход происходит по лимиту прокруток, то есть
# раньше. Большое число нужно, чтобы таймаут по времени НЕ мог сработать
# первым — иначе «нет истории» и «устройство тормозило» слились бы
# в один неразличимый отказ.
#
# ПОЧЕМУ НЕСКОЛЬКИХ ПРОКРУТОК В ПРИНЦИПЕ ХВАТАЕТ: блок категорий
# фильтра ("전체 N", "소유자 변경 N", "정비·보험" и
# т.п.) идёт компактным блоком СРАЗУ под вкладками "이력 요약"/"이력 전체"
# — не в конце длинной страницы. К моменту шага 6 экран уже долистан до
# этих вкладок предыдущим шагом (5), так что сам блок категорий должен
# показаться за считанные прокрутки, если он вообще есть. Если у машины
# нет ни одной записи о ремонте/страховых случаях, фильтра "정비·보험"
# нет на странице ВООБЩЕ (подтверждено XML-дампом) — без лимита это
# означало бы полный DEFAULT_TIMEOUT (20 сек) бесполезного скроллинга
# каждый раз для такой машины. Нескольких прокруток с запасом достаточно, чтобы
# добраться до блока категорий, если он существует; дальше листать смысла
# нет, ждать нечего.
POLL_INTERVAL = 0.15  # частый опрос WebDriverWait даёт небольшой, но
# бесплатный прирост скорости на каждом ожидании в скрипте. Если начнут
# проскакивать StaleElementReference из-за слишком частого опроса
# перерисовывающегося UI — интервал стоит увеличить (до 0.3).

DEBUG = False  # диагностические find_elements()-запросы (подсчёт всех
# карточек на экране, вывод примеров их текста) — каждый такой запрос это
# отдельный round-trip к устройству/эмулятору, который в проде не нужен и
# просто тратит время на каждой итерации цикла прокрутки. Включай True
# только при отладке нового номера/структуры экрана.

FIELD_ORDER = ["date", "service_center", "mileage", "repair_details"]


