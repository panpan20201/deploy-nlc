# Блок начинается с "✓️", 1-2 строки названия детали, затем одна или
# несколько строк работ вида "ㄴ {действие}({категория} {N}건)"
_WORK_LINE_RE = re.compile(r'ㄴ\s*([^\(]+?)\s*\(([^)]*?)(\d+)\s*건\)')
_DATE_KR_RE = re.compile(r'(\d+)\s*년\s*(\d+)\s*월\s*(\d+)\s*일')
_MILEAGE_KR_RE = re.compile(r'([\d,]+)\s*km', re.IGNORECASE)


def ru_plural(n: int, one: str, few: str, many: str) -> str:
    """Возвращает правильную форму слова для числа n по правилам русского
    языка (1 работа / 2 работы / 5 работ / 11 работ / 21 работа и т.д.)."""
    n_abs = abs(n) % 100
    n1 = n_abs % 10
    if 11 <= n_abs <= 19:
        return many
    if n1 == 1:
        return one
    if 2 <= n1 <= 4:
        return few
    return many


def format_date_ru(date_kr: Optional[str]) -> str:
    """"2024년 1월 26일" -> "26.01.2024". Если формат неожиданный —
    возвращает исходную строку как есть, ничего не теряя."""
    if not date_kr:
        return ""
    m = _DATE_KR_RE.search(date_kr)
    if not m:
        return date_kr.strip()
    year, month, day = m.groups()
    return f"{int(day):02d}.{int(month):02d}.{int(year):04d}"


def date_sort_key(date_kr: Optional[str]):
    """Ключ для сортировки визитов по возрастанию даты, как в примере."""
    if not date_kr:
        return (0, 0, 0)
    m = _DATE_KR_RE.search(date_kr)
    if not m:
        return (0, 0, 0)
    year, month, day = (int(x) for x in m.groups())
    return (year, month, day)


def format_mileage_ru(mileage_kr: Optional[str]) -> str:
    """"65,996km" -> "65 996 км". Формат из примера — пробел между
    разрядами тысяч, "км" на кириллице."""
    if not mileage_kr:
        return ""
    m = _MILEAGE_KR_RE.search(mileage_kr)
    digits = (m.group(1) if m else mileage_kr).replace(",", "").strip()
    if not digits.isdigit():
        return mileage_kr.strip()
    grouped = "{:,}".format(int(digits)).replace(",", " ")
    return f"{grouped} км"


def parse_repair_detail_blocks(raw_text: Optional[str]) -> List[Dict[str, object]]:
    """
    Разбирает "сырой" многострочный текст поля 정비이력 на отдельные
    работы.

    Реальная структура блока (подтверждено на 7 реальных визитах, включая
    визиты с НЕСКОЛЬКИМИ деталями за один заезд):
    первая строка блока — категория ("바디" или "엔진"), дальше идёт
    ПОВТОРЯЮЩАЯСЯ последовательность пар "название детали" → одна или
    несколько строк "ㄴ {действие}(...N건)" с работами именно по этой
    детали. Например (реальный визит с тремя разными деталями):
        "✓️ 바디\n리어도어\nㄴ 관련 부품 수리(3건)\n전·후펜더\n
         ㄴ 관련 부품 수리(2건)\n컴비네이션램프(후미등)\nㄴ 관련 부품 수리(1건)"
    -> [{"part": "리어도어", ...}, {"part": "전·후펜더", ...},
        {"part": "컴비네이션램프(후미등)", ...}]

    Поэтому парсер идёт по строкам ПОСЛЕДОВАТЕЛЬНО и присваивает работы той
    детали, что шла непосредственно перед ними (устойчиво и к одной детали,
    и к нескольким за визит). Собирать все строки-названия отдельно от всех
    строк-работ нельзя: тогда все работы визита с 3-6 разными деталями
    подписались бы одной и той же (последней) деталью — на образце с
    одной деталью (엔진) это незаметно, а на реальных визитах (например,
    номер 54노7511) даёт неверный отчёт.

    Если строка работы не совпадает с ожидаемым паттерном "ㄴ ...(...N건)" —
    работа всё равно добавляется в результат с count=None и raw-текстом,
    чтобы данные не терялись молча, а были видны для последующей отладки
    формата (см. count и action в формируемой записи).
    """
    if not raw_text:
        return []

    chunks = re.split(r'✓️\s*', raw_text)
    parsed: List[Dict[str, object]] = []

    for chunk in chunks:
        chunk = chunk.strip()
        if not chunk:
            continue

        lines = [ln.strip() for ln in chunk.split("\n") if ln.strip()]
        if not lines:
            continue

        # Первая строка блока — заголовок категории (바디/엔진), а не
        # название конкретной детали — пропускаем её при переборе деталей.
        # Проверяем по известному списку категорий (а не просто "первая
        # строка"), чтобы не потерять данные, если структура вдруг
        # окажется без этой шапки.
        if lines[0] in REPAIR_CARD_TYPE_KEYWORDS:
            body_lines = lines[1:]
        else:
            body_lines = lines

        pending_part_label: Optional[str] = None
        found_work = False

        for ln in body_lines:
            if ln.startswith("ㄴ"):
                found_work = True
                m = _WORK_LINE_RE.match(ln)
                if m:
                    action = m.group(1).strip()
                    grade = m.group(2).strip() or None
                    count = int(m.group(3))
                else:
                    action, grade, count = ln.lstrip("ㄴ").strip(), None, None
                parsed.append({
                    "part": pending_part_label, "action": action,
                    "grade": grade, "count": count, "raw": ln,
                })
            else:
                # Название детали. Если подряд идёт несколько таких строк
                # без работ между ними (как в исходном
                # образце — "엔진\n엔진") — берём последнюю, она обычно
                # самая конкретная.
                pending_part_label = ln

        if not found_work:
            # Во всём блоке не нашлось ни одной строки работ — не теряем
            # данные молча, добавляем то, что есть, как есть
            part_label = pending_part_label or (lines[0] if lines else None)
            parsed.append({
                "part": part_label, "action": None, "grade": None,
                "count": None, "raw": chunk,
            })

    return parsed


def translate_part(part_kr: Optional[str]) -> str:
    """
    Переводит название детали. Три ступени, по возрастанию "стоимости":
      1. Словарь PART_NAME_TRANSLATIONS — вручную проверенные переводы,
         мгновенно, без сети.
      2. Кэш на диске (translation_cache.json) — уже переводили этот же
         термин раньше через DeepL, повторный запрос не нужен.
      3. DeepL API — совсем новый термин, переводим и запоминаем в кэш,
         чтобы в следующий раз сработала ступень 2.
    Если все три ступени не дали результата (термина нет нигде, и DeepL
    недоступен/не настроен) — возвращаем исходный корейский
    текст с пометкой "[?]" и пишем в лог, что термина не хватает.
    """
    if not part_kr:
        return "[?] (нет данных о детали)"

    hit = PART_NAME_TRANSLATIONS.get(part_kr)
    if hit is not None:
        return hit

    cached = _translation_cache["part"].get(part_kr)
    if cached is not None:
        return cached

    translated = _translate_via_deepl(part_kr)
    if translated is not None:
        _translation_cache["part"][part_kr] = translated
        _save_translation_cache(_translation_cache)
        return translated

    log("translate", f'Нет перевода для детали "{part_kr}" (ни в словаре, ни в кэше, DeepL не помог/не настроен) — '
        f'добавь её в PART_NAME_TRANSLATIONS или задай DEEPL_API_KEY в .env. Пока выводится как есть.')
    return f"[?] {part_kr}"


