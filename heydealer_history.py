APPIUM_COMMAND_TIMEOUT_SEC = 120


def _read_driver_command_timeout(driver):
    """
    Таймаут ИМЕННО того соединения, которым ходит переданный драйвер.

    :return: (удалось прочитать, значение)

    Лезем в приватный `_client_config` осознанно: публичного способа
    спросить таймаут у конкретного соединения в selenium 4.47 нет, а
    спрашивать надо именно у него (см. apply_appium_command_timeout).
    Атрибут приватный, значит может исчезнуть в любой версии — поэтому
    неудача здесь не роняет бота, а даёт предупреждение и работу без
    страховки, как и любая другая неудача этой функции.
    """
    try:
        return True, driver.command_executor._client_config.timeout
    except Exception as exc:
        _logger.warning(
            "Не удалось прочитать таймаут соединения драйвера (%s). Считаем, "
            "что страховка не встала: подтвердить её нечем.", exc,
        )
        return False, None


def apply_appium_command_timeout(seconds: int = APPIUM_COMMAND_TIMEOUT_SEC,
                                 driver=None) -> bool:
    """
    Ставит верхнюю границу на ожидание ответа от Appium-сервера.

    Настройка глобальная (на уровне класса соединения Selenium), поэтому
    действует на ВСЕ создаваемые дальше сессии — и HeyDealer, и Carmoodo.
    Вызывается из обоих build_driver().

    Обёрнуто в try/except и НЕ считается фатальным: способ задать этот
    таймаут в разных версиях Selenium назывался по-разному, и если в
    установленной версии его нет — лучше остаться без страховки, но
    работать, чем не запуститься вовсе. В этом случае в логе будет
    предупреждение — по нему и станет понятно, что страховка не встала.

    :param driver: драйвер, чьё соединение мы защищаем. Необязателен, но
        передавать его СТОИТ: только через него проверка смотрит на тот
        объект, который мы хотели изменить (см. ниже).
    :return: True, если таймаут удалось установить
    """
    try:
        from selenium.webdriver.remote.remote_connection import RemoteConnection

        RemoteConnection.set_timeout(seconds)

        # УСПЕХ ПОДТВЕРЖДАЕТСЯ ПРОВЕРКОЙ РЕЗУЛЬТАТА, А НЕ ОТСУТСТВИЕМ
        # ИСКЛЮЧЕНИЯ (та же ловушка, что и со сменой рекламного
        # идентификатора в ads_id: функция может отрапортовать об успехе,
        # ничего не изменив). set_timeout может ничего не сделать, и
        # страховка считалась бы поставленной.
        #
        # ⚠️ И СПРАШИВАТЬ НАДО У ТОГО, КОГО ЗАЩИЩАЕМ. set_timeout пишет в
        # классовый `cls._client_config`, и RemoteConnection.get_timeout()
        # читает его же — то есть ровно то, что мы только что записали.
        # В текущей версии это тот же объект, что и у драйвера (selenium в
        # __init__ соединения присваивает классовому атрибуту экземплярный
        # конфиг, remote_connection.py:333), поэтому проверка работает. Но
        # это совпадение реализации, а не то, что мы проверяем: настоящий
        # вопрос — какой таймаут у соединения ЭТОГО драйвера. Когда
        # драйвер передан, спрашиваем у него.
        if driver is not None:
            ok, actual = _read_driver_command_timeout(driver)
            if not ok:
                return False
        else:
            actual = RemoteConnection.get_timeout()
        if actual != seconds:
            _logger.warning(
                "Таймаут команды Appium не встал: просили %s сек, а "
                "прочиталось %s. Работаем без этой страховки — при "
                "зависании устройства шаг может повиснуть надолго.",
                seconds, actual,
            )
            return False

        log("SETUP", f"Таймаут одной команды Appium: {seconds} сек "
            f"(защита от бесконечного зависания на неотвечающем устройстве).")
        return True
    except Exception as exc:
        _logger.warning(
            "Не удалось установить таймаут команды Appium (%s). Работаем без "
            "этой страховки: при зависании устройства шаг может повиснуть "
            "надолго. Проверь версию selenium.",
            exc,
        )
        return False


