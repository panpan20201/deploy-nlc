# ПРОМО-ЭКРАНЫ ПРИЛОЖЕНИЯ
#
# После сброса рекламного идентификатора HeyDealer считает пользователя
# новым и иногда показывает рекламную панель снизу экрана:
#
#     혜택을 놓치지 않게 알려드릴까요?   ("сообщать вам о выгодных
#                                        предложениях?")
#     [ 나중에 하기 ]        [ 알림 받기 ]
#       "позже"              "получать уведомления"
#
# ⚠️ ГЛАВНОЕ ОБ ЭТОМ ЭКРАНЕ: он появляется НЕ ТОЛЬКО при запуске. Он
# может выскочить уже ПОСЛЕ ввода номера и перекрыть собой
# результат поиска — то есть обработки при создании сессии здесь мало,
# проверять надо и в момент, когда результат не дождались.
#
# ⚠️ ВТОРОЕ: кнопки расположены НАОБОРОТ по сравнению с системными
# диалогами Android. Здесь отказ ("позже") СЛЕВА, а согласие — СПРАВА.
# Правило "берём самую правую кнопку", которое верно для диалогов
# Material, тут привело бы ровно к обратному результату — подписке
# на рекламные уведомления. Поэтому кнопка задаётся точным
# текстом, а не расположением.
#
# Уведомления не нужны ещё и по прикладной причине: всплывающее
# уведомление перекрывает верх экрана и может перехватить тап
# автоматики, то есть само становится источником случайных сбоев.
#
# Список сделан списком, а не одной проверкой, потому что промо-экраны у
# приложения появляются и меняются: добавить новый — одна строка.
# ---------------------------------------------------------------------------
PROMO_SCREENS = (
    {
        "name": "предложение подписаться на уведомления",
        "marker": "혜택을 놓치지 않게",   # часть заголовка
        "dismiss": "나중에 하기",          # "позже" — ЭТО жмём
        "avoid": "알림 받기",              # "получать уведомления" — НЕ жмём
    },
)


def dismiss_promo_screen(driver) -> Optional[str]:
    """
    Закрывает рекламную панель, если она сейчас на экране.

    :return: название закрытого экрана или None, если ничего не было
    """
    page = driver.page_source
    for promo in PROMO_SCREENS:
        if promo["marker"] not in page:
            continue

        # Кнопка — некликабельный TextView внутри кликабельного
        # контейнера. Appium жмёт в центр элемента, попадая в контейнер,
        # поэтому клик по самой надписи срабатывает.
        elements = driver.find_elements(
            AppiumBy.XPATH, f'//*[@text="{promo["dismiss"]}"]'
        )
        if not elements:
            dump_screen_for_debug(driver, "promo_dismiss_button_not_found")
            log("ONBOARD", f'Промо-экран "{promo["name"]}" виден, но кнопки '
                f'"{promo["dismiss"]}" не нашлось — сохранён дамп, не трогаю. '
                f'Нажимать наугад нельзя: рядом кнопка "{promo["avoid"]}".')
            return None

        elements[0].click()
        log("ONBOARD", f'Закрыт промо-экран: {promo["name"]} '
            f'(нажато "{promo["dismiss"]}").')
        return promo["name"]
    return None


# Системный запрос разрешений. Порядок в списке = порядок предпочтения.
#
# Уведомления сознательно ЗАПРЕЩАЕМ, а не разрешаем. Причина прикладная:
# всплывающее уведомление перекрывает верх экрана, и тап автоматики
# может уйти в него вместо нужного элемента — то есть разрешённые
# уведомления сами по себе стали бы источником случайных сбоев. Для
# работы бота уведомления не нужны вовсе.
PERMISSION_BUTTON_IDS = (
    "permission_deny_and_dont_ask_again_button",  # "Больше не спрашивать"
    "permission_deny_button",
    "permission_allow_button",   # запасной вариант: любое закрытие
    "permission_allow_foreground_only_button",  # диалога лучше, чем зависнуть
    "permission_allow_one_time_button",
)
PERMISSION_DIALOG_ID = "grant_dialog"

ONBOARDING_TIMEOUT_SEC = 25.0  # общий предел на прохождение всех экранов
ONBOARDING_SETTLE_SEC = 1.0    # пауза между экранами (они сменяются с анимацией)

# Предел, когда экраны первого запуска ОЖИДАЮТСЯ (сразу после сброса
# рекламного ID). Больше обычного: после сброса приложение стартует
# по-настоящему "с нуля" — сплэш, инициализация, сетевые запросы, — и
# экран согласия выходит не мгновенно.
ONBOARDING_AFTER_RESET_TIMEOUT_SEC = 60.0

# Одноразовый признак "следующая сессия создаётся сразу после сброса
# рекламного идентификатора".
#
# Пример из лога, когда экраны онбординга не ждут:
#
#     15:49:43 Сброс выполнен — повторяю шаг HeyDealer.
#     15:49:56 [2] Ожидание нижней навигации и клик по вкладке "이력조회"...
#     15:50:41 ERROR Шаг HeyDealer: попытка 1/2 не удалась (NoSuchElement)
#     15:50:59 [ONBOARD] Принято согласие с условиями HeyDealer.   ← попытка 2
#
# После сброса приложение показывает экран согласия, но проверка
# онбординга успевает пройти РАНЬШЕ, чем он появился, ничего не находит
# и уходит ждать нижнюю навигацию — которой за этим экраном,
# разумеется, нет. Сорок пять секунд ожидания впустую, сессия
# пересоздаётся, и только вторая попытка случайно попадает в нужный момент.
#
# Причина структурная: handle_onboarding_screens() устроен как "посмотреть
# на экран сейчас". Для обычного запуска это правильно (экранов нет, и
# ждать их — чистая потеря времени на каждом запросе). Но сразу после
# сброса мы ТОЧНО ЗНАЕМ, что HeyDealer считает устройство новым и экраны
# будут. Значит, в этом одном случае их надо именно ЖДАТЬ.
#
# Флаг ставит pipeline сразу после удачного сброса и снимает первая же
# созданная сессия — он относится к одному конкретному следующему
# запуску, а не к режиму работы вообще.
_expect_onboarding = False


def expect_onboarding_next_session() -> None:
    """Сообщает, что следующая сессия стартует после сброса рекламного ID."""
    global _expect_onboarding
    _expect_onboarding = True


def _take_expect_onboarding_flag() -> bool:
    """Читает и сразу снимает одноразовый признак."""
    global _expect_onboarding
    value = _expect_onboarding
    _expect_onboarding = False
    return value


def _tap_first_by_resource_id(driver, id_suffixes) -> Optional[str]:
    """
    Жмёт первую найденную кнопку из списка resource-id.

    Сравнение по окончанию строки: полный идентификатор выглядит как
    "com.android.permissioncontroller:id/permission_allow_button", а
    название пакета на разных прошивках отличается.

    :return: какой идентификатор сработал, или None
    """
    for suffix in id_suffixes:
        elements = driver.find_elements(
            AppiumBy.XPATH, f'//*[contains(@resource-id, "{suffix}")]'
        )
        if elements:
            elements[0].click()
            return suffix
    return None


def handle_onboarding_screens(
    driver,
    timeout: float = ONBOARDING_TIMEOUT_SEC,
    wait_for_screens: bool = False,
) -> bool:
    """
    Проходит экраны первого запуска, если они появились.

    Работает как цикл, а не как разовая проверка: экраны идут ЧЕРЕДОЙ и
    порядок между ними не гарантирован — запрос разрешений может выйти и
    до согласия с условиями, и после. Поэтому на каждом обороте смотрим,
    что сейчас на экране, и обрабатываем то, что видим, пока не
    останется ничего знакомого.

    В обычной работе (а это подавляющее большинство запусков) не делает
    ничего: первая же проверка не находит ни одного из экранов, и мы
    сразу выходим. Цена в спокойном случае — один снимок дерева.

    :param wait_for_screens: ЖДАТЬ появления экранов, а не выходить сразу,
        если их сейчас нет. Включается только после сброса рекламного ID,
        когда мы точно знаем, что экраны будут (см. подробный разбор у
        _expect_onboarding). Ожидание прекращается досрочно, как только на
        экране видна нижняя навигация, — значит, проходить уже нечего.
    :return: True, если хоть что-то пришлось пройти
    """
    handled_anything = False
    deadline = time.time() + timeout

    if wait_for_screens:
        log("ONBOARD", f"Сессия создаётся сразу после сброса рекламного ID — "
            f"ЖДУ экраны первого запуска (до {timeout:.0f} сек), а не просто "
            f"смотрю на экран один раз: после сброса HeyDealer считает "
            f"устройство новым, и экран согласия появляется с задержкой.")

    while time.time() < deadline:
        page = driver.page_source

        # --- Системный запрос разрешений ---------------------------------
        if PERMISSION_DIALOG_ID in page or "permission_allow_button" in page:
            tapped = _tap_first_by_resource_id(driver, PERMISSION_BUTTON_IDS)
            if tapped:
                log("ONBOARD", f"Закрыт системный запрос разрешений (кнопка {tapped}).")
                handled_anything = True
                time.sleep(ONBOARDING_SETTLE_SEC)
                continue
            # Диалог виден, а ни одной знакомой кнопки нет — угадывать
            # координаты в системном диалоге нельзя, там рядом может
            # оказаться что угодно.
            dump_screen_for_debug(driver, "onboarding_permission_unknown")
            log("ONBOARD", "Запрос разрешений на экране есть, но кнопки не опознаны — "
                "сохранён дамп, дальше не трогаю.")
            break

        # --- Согласие с условиями HeyDealer ------------------------------
        if TERMS_AGREE_TEXT in page or TERMS_MARKER in page:
            try:
                # Сам TextView некликабелен — жмём кликабельного родителя.
                click_clickable_ancestor_of_text(driver, TERMS_AGREE_TEXT, timeout=5)
            except TimeoutException:
                # Кликабельного родителя нет — тап по центру самой надписи
                # (Appium жмёт в середину элемента, попадая в кнопку).
                elements = driver.find_elements(
                    AppiumBy.XPATH, f'//*[@text="{TERMS_AGREE_TEXT}"]'
                )
                if not elements:
                    dump_screen_for_debug(driver, "onboarding_terms_no_button")
                    log("ONBOARD", "Экран согласия есть, а кнопки согласия не видно — "
                        "сохранён дамп.")
                    break
                elements[0].click()
            log("ONBOARD", "Принято согласие с условиями HeyDealer.")
            handled_anything = True
            time.sleep(ONBOARDING_SETTLE_SEC)
            continue

        # --- Рекламная панель приложения ---------------------------------
        if dismiss_promo_screen(driver):
            handled_anything = True
            time.sleep(ONBOARDING_SETTLE_SEC)
            continue

        # Ничего знакомого на экране нет.
        if not wait_for_screens:
            # Обычный запуск: онбординга либо не было, либо он пройден.
            break

        # Режим ожидания. Выходим только когда видна нижняя навигация —
        # это и есть признак "приложение догрузилось, проходить нечего".
        # Иначе ждём дальше: экран согласия может ещё не появиться.
        if TAB_HISTORY_TEXT in page:
            log("ONBOARD", "Нижняя навигация уже на экране — экранов первого "
                "запуска после сброса не появилось, иду дальше.")
            break
        time.sleep(ONBOARDING_SETTLE_SEC)

    else:
        if wait_for_screens:
            log("ONBOARD", f"За {timeout:.0f} сек ни экранов первого запуска, ни "
                "нижней навигации не дождался — иду дальше обычным порядком, "
                "шаг 2 попробует сам.")

    if handled_anything:
        log("ONBOARD", "Экраны первого запуска пройдены, продолжаю обычным порядком.")
    return handled_anything


