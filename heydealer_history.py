# ---------------------------------------------------------------------------
# ЗАМЕРЫ СТОИМОСТИ ОБРАЩЕНИЙ К УСТРОЙСТВУ
# ---------------------------------------------------------------------------
#
# ЗАЧЕМ. По логу видно, что HeyDealer занимает примерно две трети
# ожидания пользователя, а внутри него две трети времени уходит на циклы
# прокрутки: 27 сек на 13 свайпов до заголовка "이력 요약" и 32 сек на
# 5 холостых свайпов до маркера конца списка. Деление одного на другое
# даёт около 2 сек на оборот в первом случае и 6.5 сек во втором — при
# том, что в первом обороте один запрос к дереву элементов, а во втором
# три. Отсюда РАСЧЁТНАЯ оценка: один запрос к дереву на экране Compose
# стоит около двух секунд.
#
# Расчётная — значит непроверенная. Любая оптимизация цикла (например,
# сбор дерева один раз за оборот вместо трёх) должна опираться на
# настоящую цену каждого вида запроса, а не на деление в столбик —
# иначе легко оптимизировать не то место (например, PARTSNUMBER, который
# на ожидание пользователя не влияет вовсе).
#
# ЧТО ЭТО НЕ ДЕЛАЕТ. Ничего не меняет в поведении. Здесь только секундомер
# вокруг существующих вызовов: те же вызовы, в том же порядке, с теми
# же аргументами. Ни одного дополнительного обращения к устройству —
# это принципиально, иначе замер сам исказил бы то, что измеряет.
#
# ГДЕ СМОТРЕТЬ РЕЗУЛЬТАТ. В конце каждого разбора номера в лог уходит
# строка "[ЗАМЕР] Итого по устройству" с таблицей: вид запроса, сколько
# раз, сколько всего секунд, сколько в среднем и сколько худший случай.
# Отдельные вызовы дольше _SLOW_CALL_LOG_SEC пишутся сразу, по месту —
# чтобы было видно не только среднее, но и есть ли редкие выбросы.

# Порог, с которого отдельный вызов пишется в лог сразу. 1.0 сек выбрана
# так, чтобы обычные быстрые вызовы (клики, чтение текста элемента) не
# засоряли лог, а всё, что сопоставимо с расчётными двумя секундами, было
# видно поимённо.
_SLOW_CALL_LOG_SEC = 1.0

# Накопитель: вид запроса -> [сколько раз, всего секунд, худший случай].
# Модуль работает строго последовательно (планшет один, шаги разведены
# asyncio.Lock на стороне pipeline), поэтому обычного словаря достаточно
# и блокировка не нужна.
_device_stats: "dict[str, list]" = {}


def _reset_device_stats() -> None:
    """Обнуляет накопитель перед разбором очередного номера."""
    _device_stats.clear()


def _timed(kind: str, func, *args, **kwargs):
    """
    Выполняет обращение к устройству и записывает, сколько оно заняло.

    Возвращает ровно то, что вернул func, и пропускает наружу любое его
    исключение без изменений — время при этом всё равно засчитывается
    (упавший вызов тоже стоит секунд, и знать об этом полезно).
    """
    started = time.monotonic()
    try:
        return func(*args, **kwargs)
    finally:
        elapsed = time.monotonic() - started
        row = _device_stats.setdefault(kind, [0, 0.0, 0.0])
        row[0] += 1
        row[1] += elapsed
        if elapsed > row[2]:
            row[2] = elapsed
        if elapsed >= _SLOW_CALL_LOG_SEC:
            _logger.debug("[ЗАМЕР] %s — %.2f с", kind, elapsed)


def _log_device_stats(context: str) -> None:
    """
    Выводит итоговую таблицу замеров. Сортировка по суммарному времени:
    первым идёт то, на что реально уходит ожидание, а не то, что чаще
    вызывается.
    """
    if not _device_stats:
        return
    rows = sorted(_device_stats.items(), key=lambda item: item[1][1], reverse=True)
    total = sum(row[1] for _, row in rows)
    lines = [
        f"    {kind:<34} {count:>4} раз  {spent:>7.1f} с  "
        f"среднее {spent / count:>5.2f} с  худший {worst:>5.2f} с"
        for kind, (count, spent, worst) in rows
    ]
    _logger.info(
        "[ЗАМЕР] Итого по устройству (%s): %.1f с на %d обращений\n%s",
        context, total, sum(count for _, (count, _s, _w) in rows), "\n".join(lines),
    )


# ---------------------------------------------------------------------------
# ПРОБА: от чего зависит ОТКЛИК устройства (не действия, а ожидание ответа)
# ---------------------------------------------------------------------------
#
# ЧТО ИЗВЕСТНО ИЗ ЗАМЕРОВ (три машины, 193 обращения на самой
# длинной). Ключ ко всему — сравнение трёх строк одной таблицы:
#
#     get_window_size                 0.03 с   пустяковая команда
#     find_element внутри карточки    0.19 с   поиск в маленьком поддереве
#     find_elements по всему экрану   0.95–1.65 с
#     page_source                     1.99 с
#
# Тридцать миллисекунд на пустяковую команду означают, что канал до
# планшета (USB, adb, сам Appium-сервер) НЕ медленный. Ноль целых
# девятнадцать на поиск внутри уже найденной карточки означают, что и
# разбор поддерева стоит копейки. Вся секунда с лишним набегает ровно
# там, где UiAutomator2 обязан построить и отдать ДЕРЕВО ВСЕГО ЭКРАНА.
#
# Отсюда единственный рычаг для отклика: уменьшить дерево. Ускорять
# нечего — ждём мы не связь, а сборку дерева.
#
# Что можно уменьшить, не трогая ни одного действия сценария:
#
#   ignoreUnimportantViews=true — UiAutomator выбрасывает из дерева узлы,
#       помеченные как несущественные для доступности. В этом же файле
#       (см. _apply_speed_settings) настройка НАМЕРЕННО оставлена
#       выключенной: «скорость тут не стоит риска молча перестать
#       находить карточки». Проба позволяет проверить эту осторожность:
#       если нужные узлы на месте, это чистый выигрыш.
#
#   snapshotMaxDepth — предел глубины дерева (по умолчанию 70). Jetpack
#       Compose даёт очень глубокую иерархию, и нижние уровни могут
#       оказаться пустой обёрткой.
#
# ЧТО ДЕЛАЕТ ЭТА ФУНКЦИЯ. Ничего не меняет насовсем: замеряет одни и те
# же запросы при разных настройках на ОДНОМ И ТОМ ЖЕ экране и возвращает
# настройки как были. Кроме времени, считает НАЙДЕННОЕ КОЛИЧЕСТВО по
# каждому запросу — это и есть ответ на «не сломает ли»: если при
# ускорении какой-то запрос стал находить меньше элементов, значит, узлы
# из дерева пропали, и такую настройку включать нельзя.
#
# По умолчанию выключена: проба стоит секунд двадцать и в обычной работе
# не нужна. Включается переменной окружения HEYDEALER_TREE_PROBE=1.
TREE_PROBE_ENABLED = os.getenv("HEYDEALER_TREE_PROBE", "0") == "1"

# Настройки, которые проба перебирает. Порядок важен: первым идёт
# «как сейчас», чтобы остальные сравнивались с фактическим поведением, а
# не с представлением о нём.
TREE_PROBE_VARIANTS = [
    ("как сейчас", {}),
    ("ignoreUnimportantViews=true", {"ignoreUnimportantViews": True}),
    ("snapshotMaxDepth=30", {"snapshotMaxDepth": 30}),
    ("оба вместе", {"ignoreUnimportantViews": True, "snapshotMaxDepth": 30}),
]


def probe_tree_settings(driver, queries: "dict[str, str]") -> None:
    """
    Замеряет цену обращения к дереву при разных настройках драйвера.

    queries — {название: xpath}: те самые запросы, на которых сценарий
    теряет время. Берутся реальные, а не выдуманные для пробы: мерить
    надо то, что потом будет работать.
    """
    if not TREE_PROBE_ENABLED:
        return

    # Запоминаем, что стоит сейчас, чтобы вернуть в точности это.
    try:
        before = driver.get_settings()
    except Exception as exc:
        log("ПРОБА", f"Не удалось прочитать настройки драйвера ({exc}) — "
            f"пробу пропускаю, чтобы не оставить чужие значения.")
        return

    touched = {"ignoreUnimportantViews", "snapshotMaxDepth"}
    restore = {k: before.get(k) for k in touched if k in before}

    log("ПРОБА", "Замер отклика при разных настройках дерева. Поведение "
        "сценария не меняется, настройки будут возвращены.")
    results = []

    try:
        for title, settings in TREE_PROBE_VARIANTS:
            try:
                if settings:
                    driver.update_settings(settings)
                else:
                    # Вариант «как сейчас»: явно возвращаем исходные
                    # значения, а не полагаемся на то, что их ещё никто
                    # не трогал.
                    if restore:
                        driver.update_settings(restore)
                time.sleep(0.3)  # дать настройке вступить в силу

                started = time.monotonic()
                page = driver.page_source
                dump_sec = time.monotonic() - started
                dump_len = len(page)

                per_query = []
                for name, xpath in queries.items():
                    q_started = time.monotonic()
                    found = len(driver.find_elements(AppiumBy.XPATH, xpath))
                    per_query.append((name, time.monotonic() - q_started, found))

                results.append((title, dump_sec, dump_len, per_query))
            except Exception as exc:
                log("ПРОБА", f"Вариант «{title}» замерить не удалось: {exc}")
    finally:
        # Возврат настроек — в finally: проба не имеет права оставить
        # после себя изменённый драйвер, чем бы она ни кончилась.
        try:
            if restore:
                driver.update_settings(restore)
                log("ПРОБА", f"Настройки возвращены: {restore}")
            else:
                # Исходных значений в get_settings не было — значит, они
                # умолчания. Возвращаем документированные умолчания явно.
                driver.update_settings(
                    {"ignoreUnimportantViews": False, "snapshotMaxDepth": 70}
                )
                log("ПРОБА", "Настройки возвращены к умолчаниям "
                    "(ignoreUnimportantViews=false, snapshotMaxDepth=70).")
        except Exception as exc:
            log("ПРОБА", f"⚠️ НЕ УДАЛОСЬ ВЕРНУТЬ НАСТРОЙКИ ({exc}). Перезапусти "
                f"бота перед следующей проверкой — сессия осталась с чужими "
                f"значениями.")

    if not results:
        return

    base = results[0]
    lines = []
    for title, dump_sec, dump_len, per_query in results:
        speedup = f"×{base[1] / dump_sec:.1f}" if dump_sec > 0 else "—"
        shrink = f"{dump_len * 100 // max(base[2], 1)}%"
        lines.append(
            f"    {title:<30} дерево {dump_len:>8} симв ({shrink:>4} от "
            f"исходного), page_source {dump_sec:>5.2f} с ({speedup})"
        )
        for (name, sec, found), (_bn, _bs, base_found) in zip(
            per_query, base[3]
        ):
            # Разница в НАЙДЕННОМ количестве — главное в этой таблице.
            # Меньше, чем в исходном варианте, значит узлы пропали из
            # дерева и настройку включать нельзя, как бы она ни ускоряла.
            verdict = "" if found == base_found else f"  ⚠️ было {base_found}"
            lines.append(
                f"        {name:<34} {sec:>5.2f} с, найдено {found}{verdict}"
            )
    log("ПРОБА", "Результат:\n" + "\n".join(lines))


def build_driver() -> webdriver.Remote:
    """Создаёт сессию Appium с нужными desired capabilities."""
    options = UiAutomator2Options()
    options.platform_name = "Android"
    options.automation_name = "UiAutomator2"
    options.device_name = ANDROID_DEVICE_NAME
    if ANDROID_UDID:
        # Если задан конкретный udid реального устройства — используем его.
        # Это надёжнее, чем полагаться на device_name, особенно если к
        # компьютеру когда-нибудь будет подключено больше одного
        # устройства одновременно.
        options.udid = ANDROID_UDID
    options.app_package = APP_PACKAGE
    options.no_reset = True
    # appActivity намеренно не указываем — подхватится дефолтная активность

    # Ускорение на реальном планшете: отключает
    # анимации переходов между экранами на время сессии. Каждая анимация —
    # это реальные доли секунды ожидания на каждом переходе, а их за один
    # сценарий десятки. Appium сам возвращает настройки анимаций устройства
    # в исходное состояние при завершении сессии, так что для устройства
    # это временно и безвредно.
    options.set_capability("appium:disableWindowAnimation", True)

    # СКОЛЬКО СЕССИЯ ЖИВЁТ БЕЗ КОМАНД.
    #
    # У Appium умолчание — 60 секунд: не получив команд минуту, он сам
    # закрывает сессию. С переиспользованием сессии (см. _get_session в
    # pipeline) выигрыш доставался бы только запросам, пришедшим встык, а
    # в остальных случаях сессия успевала бы умереть и создавалась заново.
    #
    # Пять минут: одна проверка занимает 90-140 секунд, поэтому идущие
    # подряд запросы укладываются с запасом. Держать дольше незачем —
    # планшет всё это время числится занятым сессией.
    #
    # Зависшая сессия не страшна: бота перезапускает watchdog, а новая
    # сессия на том же udid обрывает старую.
    options.set_capability("appium:newCommandTimeout", 300)

    driver = webdriver.Remote(APPIUM_SERVER_URL, options=options)

    # Страховка от бесконечного зависания на неотвечающем Appium/устройстве
    # (см. подробное объяснение у apply_appium_command_timeout выше).
    #
    # ⚠️ ТОЛЬКО ПОСЛЕ СОЗДАНИЯ ДРАЙВЕРА, И ЭТО НЕ КОСМЕТИКА.
    # RemoteConnection._client_config проставляется в __init__ соединения
    # (selenium 4.47, remote_connection.py:333). До этого момента
    # классовый set_timeout() падает с AttributeError, и страховка
    # молча не встаёт ни на одном запуске.
    #
    # Драйвер передаётся не для красоты: подтверждение читает таймаут
    # соединения ИМЕННО этого драйвера, а не классовый атрибут, куда мы
    # сами только что записали (см. apply_appium_command_timeout).
    apply_appium_command_timeout(driver=driver)
    driver.implicitly_wait(0)  # используем только явные ожидания

    _apply_speed_settings(driver)

    # Если приложение НЕ было открыто на
    # экране устройства в момент создания сессии (например, устройство
    # только что включено и показывает главный экран Android) — одних
    # capabilities (appPackage + noReset) Appium'у иногда недостаточно,
    # чтобы САМОМУ запустить нужное приложение. Сессия создаётся успешно,
    # но driver остаётся смотреть на тот экран, что был открыт до этого
    # (например, на Home) — а не на HeyDealer, и все дальнейшие ожидания
    # элементов приложения просто никогда не находят их, уходя в таймаут.
    # activate_app() — явная, отдельная от capabilities команда Appium
    # "запусти/выведи на передний план вот это приложение" — она надёжно
    # решает эту проблему независимо от того, в каком состоянии было
    # устройство до создания сессии.
    driver.activate_app(APP_PACKAGE)
    time.sleep(1.0)  # даём приложению реально открыться после команды
    # запуска, прежде чем дальнейший код начнёт искать на экране элементы

    return driver


def _apply_speed_settings(driver) -> None:
    """
    Настройки Appium, заметно ускоряющие работу на реальном устройстве
    (без них на планшете всё выполняется ощутимо медленнее, чем на
    эмуляторе).

    ГЛАВНАЯ ПРИЧИНА МЕДЛЕННОСТИ (и почему именно эти настройки):
    UiAutomator2 перед КАЖДОЙ командой ждёт, пока интерфейс приложения
    "успокоится" (перестанут идти события перерисовки) — waitForIdleTimeout.
    По умолчанию это ожидание составляет 10 секунд. В обычном нативном
    приложении интерфейс замирает почти сразу, и это ожидание незаметно.
    Но и HeyDealer, и Carmoodo — приложения на WebView, где что-то
    перерисовывается практически постоянно (анимации, подгрузка, реклама),
    поэтому "покой" не наступает никогда, и Appium честно выжидает весь
    таймаут ПЕРЕД КАЖДЫМ действием. Отсюда и общая вязкость сценария.

    waitForIdleTimeout=0 отключает это ожидание. Это безопасно именно в
    нашем случае, потому что весь код и так построен на ЯВНЫХ ожиданиях
    (WebDriverWait до появления конкретного элемента) — то есть мы и без
    того не полагаемся на "интерфейс уже готов", а каждый раз явно ждём
    нужный элемент. Настройка убирает лишнюю паузу, а не проверку.

    Остальные две — по той же логике, помельче:
      - actionAcknowledgmentTimeout=0: не ждать подтверждения завершения
        жеста дольше необходимого (у нас после свайпов и так стоят свои
        короткие паузы + явные ожидания);
      - ignoreUnimportantViews=false: НАМЕРЕННО оставлено false (значение
        по умолчанию). Включение ускорило бы обход дерева элементов, но
        оно скрывает часть узлов из дерева доступности — а мы ищем
        элементы по тексту внутри WebView, и часть нужных узлов вполне
        может оказаться в "неважных". Скорость тут не стоит риска молча
        перестать находить карточки.

    Обёрнуто в try/except: update_settings — не критичная для сценария
    команда, и если конкретная версия Appium/драйвера какую-то настройку
    не поддержит, лучше продолжить работу чуть медленнее, чем упасть.
    """
    try:
        driver.update_settings({
            "waitForIdleTimeout": 0,
            "actionAcknowledgmentTimeout": 0,
        })
        log("SPEED", "Применены настройки ускорения (waitForIdleTimeout=0).")
    except Exception as exc:
        log("SPEED", f"Не удалось применить настройки ускорения (не критично, продолжаю): {exc}")


def click_clickable_ancestor_of_text(driver, text: str, timeout: int = DEFAULT_TIMEOUT):
    """
    Находит TextView с точным текстом и кликает на его ближайшего
    clickable-родителя (сам TextView часто не кликабелен).
    """
    xpath = f'//android.widget.TextView[@text="{text}"]/ancestor::*[@clickable="true"][1]'
    el = WebDriverWait(driver, timeout, poll_frequency=POLL_INTERVAL).until(
        EC.presence_of_element_located((AppiumBy.XPATH, xpath))
    )
    el.click()
    return el


