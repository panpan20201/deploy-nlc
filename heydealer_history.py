# Распознавание экрана "проверка ещё идёт"
#
# (см. tests/fixtures/evidence/
#  heydealer_debug_step5_no_search_result_20260904_175210.xml, номер
# 04조5666).
#
# Вместо результата поиска HeyDealer может показать полноэкранный прогресс:
#
#     [====================        ] 90%
#     앱을 나가셔도 이력은 조회되고 있어요.
#     («можете выйти из приложения — история всё ещё ищется»)
#     공장 생산이력 / 정비 이력 / 명의 변경 / 보험 이력
#     완료되면 알림을 보내드릴게요.
#
# ЗАЧЕМ ЭТО РАСПОЗНАВАТЬ. Замер 127 УСПЕШНЫХ ожиданий шага 5 дал
# медиану 17 сек, p90 26 сек и максимум 34 сек — то есть порог
# SEARCH_RESULT_TIMEOUT = 30 стоит не за хвостом распределения, а
# внутри него. Без распознавания приложение, работающее и стоящее на
# 90%, считалось бы поломкой: сохранение дампа, исключение, пересоздание
# сессии и повторный ввод номера — то есть ЕЩЁ ОДНА ПОТРАЧЕННАЯ ПРОВЕРКА
# из десяти суточных. В логах такое видно: первая попытка падает по
# таймауту, вторая по той же машине отдаёт результат за 25 секунд.
#
# ПОЧЕМУ НЕ "ПОДНЯТЬ ПОРОГ ДО 45". Тогда каждый по-настоящему сломанный
# случай стал бы дороже на 15 секунд. Порог по секундомеру в принципе
# не умеет отличать медленную работу от поломки — для этого надо
# смотреть на экран.
#
# ПРИЗНАКИ. Первым идёт resource-id (он стабильнее текста) — пара
# progress_indicator + tv_percentage встречается только вместе и только
# здесь. Текстовые группы вспомогательные, но самые содержательные.
# Маркеры записаны БЕЗ ПРОБЕЛОВ: в дампе слова разделены \xa0 (как и
# везде в этом приложении), а _matches_marker_groups пробелы вычищает.
#
# ⚠️ Маркеры намеренно НЕ пересекают перенос строки: в дампе между
# "이력은" и "조회되고" стоит XML-сущность &#10;, которая в исходнике
# страницы остаётся текстом. Признак вида "이력은조회되고" не совпал бы
# никогда — молча.
# ---------------------------------------------------------------------------
LOOKUP_IN_PROGRESS_MARKER_GROUPS = (
    ("id/progress_indicator", "id/tv_percentage"),   # самый надёжный признак
    ("조회되고있어요",),          # "история всё ещё ищется"
    ("완료되면알림을보내드릴게요",),  # "сообщим, когда закончим"
)

# Узел с процентом ищется ПО resource-id, а не как "первое число с
# процентом во всём XML". На имеющемся дампе оба способа дают верные 90,
# но любой посторонний "%" выше по дереву (рекламное "скидка 50%") увёл бы
# второй способ в мусор — молча. И этот мусор был бы принят за признак
# живости приложения, то есть за основание ждать или не ждать дальше.
#
# `[^<>]*` не даёт выйти за границы одного узла, поэтому порядок
# атрибутов не важен: в имеющемся дампе text стоит ПЕРЕД resource-id, но
# uiautomator порядок не гарантирует.
_LOOKUP_PERCENT_NODE_RE = re.compile(r"<[^<>]*tv_percentage[^<>]*>")
_LOOKUP_PERCENT_RE = re.compile(r"(\d{1,3})\s*%")


def looks_like_lookup_in_progress(page_source: str) -> bool:
    """Идёт ли прямо сейчас проверка истории (полноэкранный прогресс)."""
    return _matches_marker_groups(page_source, LOOKUP_IN_PROGRESS_MARKER_GROUPS)


def read_lookup_percent(page_source: str) -> Optional[int]:
    """
    Процент готовности с экрана проверки, если он там есть.

    Нужен не для красоты лога, а как признак ЖИВОСТИ: если процент не
    сдвинулся за целое окно продления, значит проверка действительно
    зависла, и ждать дальше бессмысленно (см. шаг 5).

    Ищется в узле tv_percentage и только в нём — почему именно так,
    написано у _LOOKUP_PERCENT_NODE_RE выше.
    """
    if not page_source:
        return None
    for node in _LOOKUP_PERCENT_NODE_RE.finditer(page_source):
        match = _LOOKUP_PERCENT_RE.search(node.group(0))
        if not match:
            continue
        value = int(match.group(1))
        return value if 0 <= value <= 100 else None
    return None


