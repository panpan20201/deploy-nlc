# Распознавание экрана "исчерпан дневной лимит"
#
# HeyDealer разрешает 10 проверок номеров в сутки на устройство. При
# исчерпании вместо результата поиска показывается экран:
#
#     하루 최대 10대까지 조회 가능해요. 📋
#     내일 다시 조회해 주세요.
#     서비스 과부하를 막기 위함이니, 양해 부탁드립니다.
#     [네, 알겠습니다]
#
# ("В день можно проверить максимум 10 машин. Повторите завтра — это
#  чтобы не перегружать сервис, просим понять.")
#
# Без распознавания этот экран неотличим от поломки: шаг просто падает с
# "элемент не найден за 30 сек". А лечится он совершенно иначе — не
# повтором, а сбросом рекламного идентификатора.
#
# ⚠️ ВАЖНАЯ ОСОБЕННОСТЬ ЭТОГО ТЕКСТА: слова в нём разделены НЕРАЗРЫВНЫМИ
# пробелами (\xa0), а не обычными. Это видно прямо в дампе. Поиск по
# строке с обычным пробелом ("하루 최대") НЕ НАШЁЛ БЫ НИЧЕГО, и признак
# молча никогда не срабатывал бы. Поэтому перед сравнением мы удаляем из
# текста все пробельные символы вообще — тогда неважно, какими именно
# пробелами приложение решит разделять слова в следующей версии.
#
# Признаки намеренно НЕ включают число "10": лимит могут изменить, и
# привязка к конкретной цифре сломала бы распознавание ровно в тот
# момент, когда оно нужнее всего.
# ---------------------------------------------------------------------------
DAILY_LIMIT_MARKER_GROUPS = (
    ("하루최대", "조회가능"),      # "в день максимум ... можно проверить"
    ("내일다시조회해",),           # "проверьте снова завтра"
)


# Всё, что приложение может вставить между словами (и внутри слов), но что
# на смысл не влияет: обычные пробелы и переводы строк — плюс НЕВИДИМЫЕ
# символы.
#
# ⚠️ ПРО НЕВИДИМЫЕ ОТДЕЛЬНО, ЭТО НЕ ПЕДАНТИЗМ. Регулярное выражение \s в
# Python НЕ считает пробелом U+200B (zero-width space) — он относится к
# категории "форматирующие", а не "пробельные". А HeyDealer его вставляет,
# и не между словами, а ВНУТРИ слова: маркер конца списка приходит и
# как '알\u200b림\u200b받\u200b기'. То есть очистка только по \s оставила бы
# такой текст неузнаваемым, и признак молча не срабатывал бы — тот же
# способ отказа, что и с \xa0 в кнопке "네, 알겠습니다" и в экранах лимита
# и имени владельца.
_INVISIBLE_CHARS_RE = re.compile(r"[\s\u00ad\u200b-\u200f\u2060\ufeff]+")


def _matches_marker_groups(page_source: str, groups) -> bool:
    """
    Есть ли на экране любая из ГРУПП признаков (все слова группы сразу).

    Группы, а не отдельные слова: одиночное слово вроде "조회가능"
    ("можно проверить") встречается в приложении и в безобидных местах, а
    вот вместе с "하루최대" ("в день максимум") — это уже однозначно
    нужный экран.

    ⚠️ ПРОБЕЛЫ И НЕВИДИМЫЕ СИМВОЛЫ УДАЛЯЮТСЯ ПЕРЕД СРАВНЕНИЕМ, и это не
    косметика, а главное свойство этой функции. В текстах HeyDealer между
    словами (и внутри слов) встречаются обычный пробел, неразрывный
    (\\xa0) и невидимый разделитель (\\u200b) — всё это видно прямо в
    дампах и логах. Сравнение с обычной строкой промахнулось бы, причём
    МОЛЧА: признак просто никогда не срабатывал бы, а в логе было бы ровно
    то же, что при штатной работе.

    Убирая эти символы вообще, мы перестаём зависеть от того, чем
    приложение решит разделять слова в следующей версии.
    """
    if not page_source:
        return False
    squeezed = _INVISIBLE_CHARS_RE.sub("", page_source)
    return any(all(word in squeezed for word in group) for group in groups)


def looks_like_daily_limit(page_source: str) -> bool:
    """Показан ли сейчас экран исчерпанного дневного лимита."""
    return _matches_marker_groups(page_source, DAILY_LIMIT_MARKER_GROUPS)


