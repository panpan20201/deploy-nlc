# теория: маркер конца списка приходит и в виде '알\u200b림\u200b받\u200b기',
# то есть разделители стоят даже ВНУТРИ одного слова. XPath contains()
# сравнивает строку буквально и на таком тексте промахнётся.
#
# Поэтому здесь тот же приём, что и при распознавании дневного лимита и
# требования имени владельца: убираем из текста экрана ВСЕ пробельные
# символы и сравниваем со склеенными признаками. Тогда неважно, чем
# приложение решит разделять слова в следующей версии.
#
# Маркеры END_OF_LIST_MARKS работают параллельно с этим способом:
# блоки в конце списка появляются вразнобой, и какой из них
# достанется на конкретной машине — заранее неизвестно. Конец фиксируется
# по ЛЮБОМУ сработавшему признаку.
END_OF_LIST_TEXT_GROUPS = (
    ("모든차량무사고",),   # "все машины без аварий" — подпись промо-блока
    ("인증중고차",),        # "сертифицированный б/у автомобиль" — его заголовок
)


def looks_like_end_of_list(page_source: str, screen_height: Optional[int] = None) -> bool:
    """
    Виден ли на экране рекламный блок, ниже которого истории уже нет.

    ⚠️ ИМЕННО "ВИДЕН НА ЭКРАНЕ", А НЕ "ЕСТЬ В ДЕРЕВЕ". page_source отдаёт
    ВСЁ дерево элементов, включая то, что лежит далеко ниже видимой части
    экрана. Рекламный блок в этом дереве присутствует с самого начала —
    просто он в самом низу длинного списка. Проверка "есть ли такой
    текст" ответила бы "есть" ещё до первой прокрутки и оборвала бы обход
    на старте: ни одной прокрутки, ни одной просмотренной карточки, ноль
    записей о ремонте у машины, у которой они есть.

    Поэтому мало найти текст — надо убедиться, что элемент с ним
    реально попадает в видимую область. Координаты берём из атрибута
    bounds ("[x1,y1][x2,y2]"), высоту экрана — из корневого узла дампа.
    Элемент считается видимым, если его верх выше нижней границы экрана.

    :param page_source: XML-дамп экрана
    :param screen_height: высота экрана; если не задана — берётся из дампа
    """
    if not page_source:
        return False

    if screen_height is None:
        root_match = re.search(r'<hierarchy[^>]*height="(\d+)"', page_source)
        if root_match:
            screen_height = int(root_match.group(1))
        else:
            # Высоту определить не удалось — единственный безопасный ответ
            # "не конец списка": лишняя прокрутка стоит секунды, а ложный
            # конец обхода стоит всех записей о ремонте у машины.
            log("7", "В дампе экрана нет высоты — проверку конца списка по "
                "тексту пропускаю (лишняя прокрутка безопаснее, чем "
                "потерянные записи).")
            return False

    # Разбираем узлы поштучно: нужен не только текст, но и его bounds.
    node_re = re.compile(
        r'(?:text|content-desc)="([^"]*)"[^>]*?bounds="\[(-?\d+),(-?\d+)\]\[(-?\d+),(-?\d+)\]"'
    )
    for match in node_re.finditer(page_source):
        label = match.group(1)
        if not label.strip():
            continue
        if not _matches_marker_groups(label, END_OF_LIST_TEXT_GROUPS):
            continue
        top = int(match.group(3))
        if top < screen_height:
            return True
